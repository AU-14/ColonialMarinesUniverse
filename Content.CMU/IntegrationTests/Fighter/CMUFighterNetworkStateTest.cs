using System.IO;
using System.Numerics;
using Content.IntegrationTests.Fixtures;
using Content.Server.CMU14.Fighter;
using Content.Shared.CMU14.Fighter;
using Robust.Shared.GameObjects;
using Robust.Shared.GameStates;
using Robust.Shared.Serialization;
using Robust.Shared.Timing;

namespace Content.IntegrationTests.CMU14.Fighter;

[TestFixture]
public sealed class CMUFighterNetworkStateTest : GameTest
{
    [Test]
    public async Task IdleRefreshStaysCleanAndFlightSendsApplicableSmallerDeltas()
    {
        var map = await Pair.CreateTestMap();
        Entity<FighterAircraftComponent> aircraft = default;
        GameTick baseline = default;
        IComponentState baselineState = null!;
        await Server.WaitAssertion(() =>
        {
            aircraft = Server.System<FighterSystem>().CreateAircraft(Server.Transform(map.Grid).MapUid!.Value, Vector2.Zero);
            aircraft.Comp.GroundState = FighterGroundState.Grounded;
        });
        await Pair.RunTicksSync(40);
        await Server.WaitPost(() => baseline = Server.ResolveDependency<IGameTiming>().CurTick);
        await Pair.RunTicksSync(40);
        await Server.WaitAssertion(() =>
        {
            var seat = SEntMan.GetComponent<FighterSeatComponent>(aircraft.Comp.FrontSeat!.Value);
            var weapons = SEntMan.GetComponent<FighterWeaponsComponent>(aircraft);
            Assert.That(EntityManager.GetModifiedAspects(aircraft.Comp, baseline), Is.Zero, "Idle aircraft must not resend full state.");
            Assert.That(EntityManager.GetModifiedAspects(seat, baseline), Is.Zero, "Unchanged seats must stay clean.");
            Assert.That(EntityManager.GetModifiedAspects(weapons, baseline), Is.Zero, "An unchanged weapon scan must stay clean.");

            aircraft.Comp.GroundState = FighterGroundState.Airborne;
            aircraft.Comp.Entry = Vector2.Zero;
            aircraft.Comp.Exit = new Vector2(100, 0);
            aircraft.Comp.Flying = true;
            aircraft.Comp.Phase = FighterPhase.Pass;
            SEntMan.Dirty(aircraft, aircraft.Comp);
        });
        await Pair.RunTicksSync(12);
        await Server.WaitPost(() =>
        {
            baseline = Server.ResolveDependency<IGameTiming>().CurTick;
            baselineState = SEntMan.GetComponentState(SEntMan.EventBus, aircraft.Comp, null, GameTick.Zero)!;
        });
        await Pair.RunTicksSync(12);
        await Server.WaitAssertion(() =>
        {
            var full = SEntMan.GetComponentState(SEntMan.EventBus, aircraft.Comp, null, GameTick.Zero)!;
            var update = SEntMan.GetComponentState(SEntMan.EventBus, aircraft.Comp, null, baseline)!;
            Assert.That(update, Is.InstanceOf<IAutoGeneratedComponentDeltaState>());
            var serializer = Server.ResolveDependency<IRobustSerializer>();
            using var fullBytes = new MemoryStream();
            using var deltaBytes = new MemoryStream();
            serializer.Serialize(fullBytes, full);
            serializer.Serialize(deltaBytes, update);
            Assert.That(deltaBytes.Length, Is.LessThan(fullBytes.Length));
            TestContext.Out.WriteLine($"Fighter component state: full={fullBytes.Length} bytes, flight delta={deltaBytes.Length} bytes.");

            var expected = aircraft.Comp.Position;
            var terrain = aircraft.Comp.TerrainMap;
            var merged = ((IComponentDeltaState) update).CreateNewFullState(baselineState);
            aircraft.Comp.Position = new Vector2(-999);
            var apply = new ComponentHandleState(merged, null);
            SEntMan.EventBus.RaiseComponentEvent(aircraft, aircraft.Comp, ref apply);
            Assert.That(aircraft.Comp.Position, Is.EqualTo(expected));
            Assert.That(aircraft.Comp.TerrainMap, Is.EqualTo(terrain));
            SEntMan.DeleteEntity(Server.Transform(aircraft).MapUid);
        });
    }
}
