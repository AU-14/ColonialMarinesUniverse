using System.Linq;
using Content.Shared.CMU14.Ambassador;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.CMU14.Ambassador;

[GenerateTypedNameReferences]
public sealed partial class AmbassadorThirdPartyWindow : DefaultWindow
{
    public event Action<string>? OnCallThirdParty;

    private List<string> _thirdPartyIds = new();
    private Dictionary<string, (string DisplayName, float Cost)> _thirdParties = new();
    private HashSet<string> _calledParties = new();
    private string? _selectedThirdPartyId;
    private int _callsLeft = int.MaxValue;
    private TimeSpan _nextCallInAt;

    public AmbassadorThirdPartyWindow()
    {
        RobustXamlLoader.Load(this);

        ThirdPartyList.OnItemSelected += args =>
        {
            if (args.ItemList[args.ItemIndex].Metadata is string id)
                SelectThirdParty(id);
        };

        ThirdPartyList.OnItemDeselected += args =>
        {
            if (args.ItemList[args.ItemIndex].Metadata is string id && id == _selectedThirdPartyId)
                SelectThirdParty(null);
        };

        CallBtn.OnPressed += _ =>
        {
            if (_selectedThirdPartyId is { } id &&
                _thirdParties.ContainsKey(id) &&
                !_calledParties.Contains(id) &&
                CanCallIn())
            {
                OnCallThirdParty?.Invoke(id);
                StatusLabel.Text = Loc.GetString("ambassador-third-party-requesting");
            }
        };
    }

    public void UpdateState(AmbassadorThirdPartyBuiState s)
    {
        BudgetLabel.Text = Loc.GetString("ambassador-console-budget", ("amount", s.Budget.ToString("F0")));

        var newIds = s.CallableParties.Keys.ToList();
        var changed = !_thirdPartyIds.SequenceEqual(newIds) || !_calledParties.SetEquals(s.CalledParties);

        _thirdParties = s.CallableParties;
        _calledParties = s.CalledParties;
        _callsLeft = s.CallsLeft;
        _nextCallInAt = s.NextCallInAt;
        UpdateCallLimit();

        if (changed)
        {
            var previousSelectedKey = _selectedThirdPartyId;

            _thirdPartyIds = newIds;
            ThirdPartyList.Clear();

            if (_thirdPartyIds.Count == 0)
            {
                StatusLabel.Text = Loc.GetString("ambassador-third-party-none");
                SelectThirdParty(null);
                CostLabel.Text = Loc.GetString("ambassador-third-party-cost-na");
                return;
            }

            StatusLabel.Text = "";

            for (int i = 0; i < _thirdPartyIds.Count; i++)
            {
                var id = _thirdPartyIds[i];
                var info = s.CallableParties[id];
                var label = _calledParties.Contains(id)
                    ? Loc.GetString(
                        "ambassador-third-party-entry-called",
                        ("name", info.DisplayName),
                        ("cost", info.Cost.ToString("F0")))
                    : Loc.GetString(
                        "ambassador-third-party-entry",
                        ("name", info.DisplayName),
                        ("cost", info.Cost.ToString("F0")));

                ThirdPartyList.Add(new ItemList.Item(ThirdPartyList)
                {
                    Text = label,
                    Metadata = id,
                });
            }

            var restoreIdx = previousSelectedKey != null ? _thirdPartyIds.IndexOf(previousSelectedKey) : -1;
            var selectIdx = restoreIdx >= 0 ? restoreIdx : _thirdPartyIds.FindIndex(id => !_calledParties.Contains(id));
            if (selectIdx < 0)
                selectIdx = 0;

            ThirdPartyList[selectIdx].Selected = true;
            SelectThirdParty(_thirdPartyIds[selectIdx]);
        }
        else
        {
            SelectThirdParty(_selectedThirdPartyId);
        }
    }

    private void SelectThirdParty(string? id)
    {
        _selectedThirdPartyId = id;

        if (id == null || !_thirdParties.TryGetValue(id, out var info))
        {
            CostLabel.Text = _thirdPartyIds.Count == 0
                ? Loc.GetString("ambassador-third-party-cost-na")
                : Loc.GetString("ambassador-third-party-cost", ("cost", "0"));
            CallBtn.Disabled = true;
            return;
        }

        CostLabel.Text = Loc.GetString("ambassador-third-party-cost", ("cost", info.Cost.ToString("F0")));
        CallBtn.Disabled = _calledParties.Contains(id) || !CanCallIn();
    }

    private bool CanCallIn()
    {
        return _callsLeft > 0 && IoCManager.Resolve<IGameTiming>().CurTime >= _nextCallInAt;
    }

    private void UpdateCallLimit()
    {
        if (_callsLeft <= 0)
        {
            CallLimitLabel.Text = Loc.GetString("ambassador-third-party-no-calls-left");
            return;
        }

        var wait = _nextCallInAt - IoCManager.Resolve<IGameTiming>().CurTime;
        CallLimitLabel.Text = wait > TimeSpan.Zero
            ? Loc.GetString("ambassador-third-party-cooldown",
                ("left", _callsLeft), ("minutes", (int) Math.Ceiling(wait.TotalMinutes)))
            : Loc.GetString("ambassador-third-party-calls-left", ("left", _callsLeft));
    }
}
