using Content.Client.CMU14.UI;
using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using static Content.Client.CMU14.UI.CMUMachineUiStyle;

namespace Content.Client.CMU14.Chemistry.Research;

[GenerateTypedNameReferences]
public sealed partial class ChemSimulatorWindow : DefaultWindow
{
    private const int CreditsBarMax = 100;
    private const int CreditsGoodThreshold = 60;
    private const int CreditsDefaultThreshold = 40;
    private const int CreditsAverageThreshold = 15;

    private readonly Font _noticeFont;

    public ChemSimulatorWindow()
    {
        RobustXamlLoader.Load(this);
        RemoveWindowBorder(this);

        var cache = IoCManager.Resolve<IResourceCache>();
        _noticeFont = cache.GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);
        CreditsLabel.FontOverride = cache.GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 10);

        SimulateButton.SetIcon(CMUIcons.Radiation, Loc.GetString("research-sim-ui-simulate"));
        OverrideButton.SetIcon(CMUIcons.HardDrive, Loc.GetString("research-sim-ui-override"));
        EjectTargetButton.SetIcon(CMUIcons.FileImport, Loc.GetString("research-sim-ui-eject-targ"));
        EjectReferenceButton.SetIcon(CMUIcons.FileImport, Loc.GetString("research-sim-ui-eject-ref"));
        AmplifyButton.SetIcon(CMUIcons.SquarePlus, Loc.GetString("research-sim-ui-amplify"));
        SuppressButton.SetIcon(CMUIcons.SquareMinus, Loc.GetString("research-sim-ui-suppress"));
        AddButton.SetIcon(CMUIcons.ArrowRight, Loc.GetString("research-sim-ui-add"));
        RelateButton.SetIcon(CMUIcons.Repeat, Loc.GetString("research-sim-ui-relate"));
        FinalizeButton.SetIcon(CMUIcons.FloppyDisk, Loc.GetString("research-sim-ui-finalize"));
    }

    public void SetCredits(int sampleData)
    {
        CreditsLabel.Text = Loc.GetString("research-sim-ui-credits", ("NUM", sampleData));

        var color = sampleData >= CreditsGoodThreshold ? GoodColor
            : sampleData >= CreditsDefaultThreshold ? ButtonColor
            : sampleData >= CreditsAverageThreshold ? AverageColor
            : BadColor;
        Bar(CreditsBar, (float) sampleData / CreditsBarMax, color);
    }

    public void SetNotice(PanelContainer panel, Label label, string text, Color color)
    {
        Notice(panel, label, text, color, _noticeFont);
    }

    public static void SetModeButton(CMUMachineButton button, bool selected)
    {
        button.Accent = selected ? ButtonSelectedColor : ButtonColor;
    }

    public sealed class SelectButton : CMUMachineButton
    {
        public string Id = string.Empty;
        public Action<string>? OnSelect;

        public SelectButton()
        {
            OnPressed += _ => OnSelect?.Invoke(Id);
        }
    }
}
