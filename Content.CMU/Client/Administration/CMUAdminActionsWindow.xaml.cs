using Content.Client.Stylesheets;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Maths;
using Robust.Shared.Timing;

namespace Content.Client.CMU14.Administration;

[GenerateTypedNameReferences]
public sealed partial class CMUAdminActionsWindow : DefaultWindow
{
    [Dependency] private IConfigurationManager _configuration = default!;
    [Dependency] private IStylesheetManager _styles = default!;
    [Dependency] private IResourceCache _resources = default!;

    public int TransformCategory { get; private set; }
    public event Action? TransformCategoryChanged;

    private Control? _revealing;
    private Thickness _revealMargin;
    private float _revealTime;

    public CMUAdminActionsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        Points.InitDefaultButtons();
        SpecialistPoints.InitDefaultButtons();
        Points.IsValid = value => value >= 0;
        SpecialistPoints.IsValid = value => value >= 0;
        BindTabs(Tabs, ["rmc-ui-transform-tab", "rmc-ui-marine-tab", "rmc-ui-xeno-tab"]);
        BindTabs(MarineTab, ["cmu-admin-skills", "cmu-admin-squads", "cmu-admin-equipment"]);
        BindTabs(XenoTab, ["cmu-admin-hives", "cmu-admin-create-hive"]);

        CMUAdminActionsTheme.Apply(this);
        CMUAdminActionsTheme.Apply(TransformTab, CMUAdminActionsTheme.Violet);
        CMUAdminActionsTheme.Apply(XenoTab, CMUAdminActionsTheme.Violet);
        CMUAdminActionsTheme.Apply(NeomorphCategory, CMUAdminActionsTheme.Amber);
        CMUAdminActionsTheme.Apply(CreateCorruptedHive, CMUAdminActionsTheme.Amber);
        XenoCategory.Label.AddStyleClass(CMUAdminActionsTheme.Heading);
        NeomorphCategory.Label.AddStyleClass(CMUAdminActionsTheme.Heading);
        CMUAdminActionsTheme.SetAccent(Tabs, CMUAdminActionsTheme.Violet);
        Tabs.OnTabChanged += index => CMUAdminActionsTheme.SetAccent(Tabs,
            index == 1 ? CMUAdminActionsTheme.Cyan : CMUAdminActionsTheme.Violet);
        HeaderClass = CMUAdminActionsTheme.Header;
        TitleClass = CMUAdminActionsTheme.Heading;

        var categories = new[] { XenoCategory, NeomorphCategory };
        for (var i = 0; i < categories.Length; i++)
        {
            var category = i;
            categories[i].Pressed = i == TransformCategory;
            categories[i].OnPressed += _ =>
            {
                foreach (var button in categories)
                    button.Pressed = button == categories[category];
                if (TransformCategory == category)
                    return;
                TransformCategory = category;
                TransformCategoryChanged?.Invoke();
                Reveal(Transforms);
            };
        }
        ApplyTheme();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        ApplyTheme();
        _styles.CrtThemeChanged += ApplyTheme;
    }

    protected override void ExitedTree()
    {
        _styles.CrtThemeChanged -= ApplyTheme;
        FinishReveal();
        base.ExitedTree();
    }

    private void ApplyTheme()
    {
        Stylesheet = CMUAdminActionsTheme.Create(_styles.SheetNano, _resources);
    }

    private void BindTabs(TabContainer tabs, string[] titles)
    {
        for (var i = 0; i < titles.Length; i++)
            tabs.SetTabTitle(i, Loc.GetString(titles[i]));
        tabs.OnTabChanged += index => Reveal(tabs.GetChild(index));
    }

    private void Reveal(Control page)
    {
        FinishReveal();
        if (_configuration.GetCVar(CCVars.ReducedMotion))
            return;

        _revealing = page;
        _revealMargin = page.Margin;
        _revealTime = 0;
        AnimateReveal(0);
    }

    private void AnimateReveal(float progress)
    {
        if (_revealing == null)
            return;

        var remaining = MathF.Pow(1 - progress, 3);
        var offset = 6 * remaining;
        // Opposing margins translate the page without changing its available width.
        _revealing.Margin = new Thickness(_revealMargin.Left + offset, _revealMargin.Top,
            _revealMargin.Right - offset, _revealMargin.Bottom);
        _revealing.Modulate = Color.White.WithAlpha(1 - 0.25f * remaining);
    }

    private void FinishReveal()
    {
        if (_revealing == null)
            return;
        _revealing.Margin = _revealMargin;
        _revealing.Modulate = Color.White;
        _revealing = null;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_revealing == null)
            return;

        _revealTime += args.DeltaSeconds;
        var progress = _configuration.GetCVar(CCVars.ReducedMotion) ? 1 : Math.Min(1, _revealTime / 0.16f);
        AnimateReveal(progress);
        if (progress >= 1)
            FinishReveal();
    }
}
