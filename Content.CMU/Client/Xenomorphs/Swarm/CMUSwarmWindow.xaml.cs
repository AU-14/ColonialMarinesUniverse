using System.Linq;
using Content.Shared.CMU14.Xenomorphs.Swarm;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CMU14.Xenomorphs.Swarm;

[GenerateTypedNameReferences]
public sealed partial class CMUSwarmWindow : DefaultWindow
{
    public event Action<CMUSwarmCommandMessage>? Command;
    public event Action<bool>? Target;
    private readonly HashSet<NetEntity> _selected = new();
    private List<CMUSwarmMemberInfo> _members = new();

    public CMUSwarmWindow()
    {
        RobustXamlLoader.Load(this);
        for (var i = 0; i <= 4; i++)
            Squad.AddItem(i == 0 ? Loc.GetString("cmu-swarm-ungrouped") : Loc.GetString("cmu-swarm-squad", ("number", i)), i);
        foreach (var kind in new[] { CMUSwarmOrderKind.Guard, CMUSwarmOrderKind.Follow, CMUSwarmOrderKind.Roam,
                     CMUSwarmOrderKind.Patrol, CMUSwarmOrderKind.Build, CMUSwarmOrderKind.Weed })
            Order.AddItem(OrderName(kind), (int) kind);
        foreach (var kind in new[] { CMUSwarmOrderKind.Rally, CMUSwarmOrderKind.Attack, CMUSwarmOrderKind.Defend })
            Marker.AddItem(OrderName(kind), (int) kind);
        foreach (var structure in Enum.GetValues<CMUSwarmStructure>())
            Structure.AddItem(Loc.GetString($"cmu-swarm-structure-{structure.ToString().ToLowerInvariant()}"), (int) structure);
        foreach (var aggression in Enum.GetValues<CMUSwarmAggression>())
            Aggression.AddItem(AggressionName(aggression), (int) aggression);
        Aggression.SelectId((int) CMUSwarmAggression.Defensive);
        foreach (var option in new[] { Squad, Order, Marker, Structure, Aggression })
            option.OnItemSelected += args => option.SelectId(args.Id);

        SelectAll.OnPressed += _ => Select(_members);
        SelectNone.OnPressed += _ => Select(Array.Empty<CMUSwarmMemberInfo>());
        SelectSquad.OnPressed += _ => Select(_members.Where(m => m.Squad == Squad.SelectedId));
        AssignSquad.OnPressed += _ => Send(CMUSwarmCommand.AssignSquad);
        ApplyAggression.OnPressed += _ => Send(CMUSwarmCommand.Aggression);
        Release.OnPressed += _ => Send(CMUSwarmCommand.Release);
        ClearMarkers.OnPressed += _ => Send(CMUSwarmCommand.ClearMarkers);
        PlaceOrder.OnPressed += _ => Prepare((CMUSwarmOrderKind) Order.SelectedId);
        PlaceMarker.OnPressed += _ => Prepare((CMUSwarmOrderKind) Marker.SelectedId);
        UpdateSelection();
    }

    private void Send(CMUSwarmCommand command, CMUSwarmOrderKind order = CMUSwarmOrderKind.Guard)
    {
        Command?.Invoke(new CMUSwarmCommandMessage(command, _selected.ToList(), Squad.SelectedId, order,
            (CMUSwarmAggression) Aggression.SelectedId, (CMUSwarmStructure) Structure.SelectedId, Append.Pressed));
    }

    private void Prepare(CMUSwarmOrderKind order)
    {
        Send(CMUSwarmCommand.Prepare, order);
        Target?.Invoke(order == CMUSwarmOrderKind.Follow);
        Hint.Text = Loc.GetString("cmu-swarm-target-hint");
    }

    private void Select(IEnumerable<CMUSwarmMemberInfo> members)
    {
        _selected.Clear();
        foreach (var member in members)
            _selected.Add(member.Entity);
        RebuildRoster();
    }

    public void Update(CMUSwarmUiState state)
    {
        var full = state.Members.Count >= CMUQueenSwarmComponent.MaxLivingMembers;
        Summon.Disabled = full || state.CooldownSeconds > 0;
        Summon.Text = full
            ? Loc.GetString("cmu-swarm-full", ("limit", CMUQueenSwarmComponent.MaxLivingMembers))
            : state.CooldownSeconds > 0
            ? Loc.GetString("cmu-swarm-menu-cooldown", ("seconds", state.CooldownSeconds))
            : Loc.GetString("cmu-swarm-menu-summon");
        if (_members.SequenceEqual(state.Members))
            return;
        _members = state.Members;
        _selected.IntersectWith(_members.Select(m => m.Entity));
        RebuildRoster();
    }

    private void RebuildRoster()
    {
        Roster.RemoveAllChildren();
        foreach (var member in _members)
        {
            var text = Loc.GetString("cmu-swarm-member", ("number", member.Number), ("squad", member.Squad),
                ("order", OrderName(member.Order)),
                ("aggression", Loc.GetString($"cmu-swarm-aggression-short-{member.Aggression.ToString().ToLowerInvariant()}")));
            if (member.Resting)
                text += Loc.GetString("cmu-swarm-member-resting");
            if (member.Working)
                text += Loc.GetString("cmu-swarm-member-working");
            var check = new CheckBox { Text = text, Pressed = _selected.Contains(member.Entity) };
            check.OnToggled += args =>
            {
                if (args.Pressed)
                    _selected.Add(member.Entity);
                else
                    _selected.Remove(member.Entity);
                UpdateSelection();
            };
            Roster.AddChild(check);
        }
        UpdateSelection();
    }

    private void UpdateSelection()
    {
        SelectionCount.Text = Loc.GetString("cmu-swarm-selection-count", ("count", _selected.Count));
        PlaceOrder.Disabled = Release.Disabled = AssignSquad.Disabled = ApplyAggression.Disabled = _selected.Count == 0;
    }

    private static string OrderName(CMUSwarmOrderKind kind) => Loc.GetString($"cmu-swarm-order-{kind.ToString().ToLowerInvariant()}");
    private static string AggressionName(CMUSwarmAggression kind) => Loc.GetString($"cmu-swarm-aggression-{kind.ToString().ToLowerInvariant()}");
}
