namespace Content.Client.CMU14.Guidebook;

/// <summary>
/// Read-only recipe lookup. Only the selected recipe resolves sprite textures; browsing never crafts items.
/// </summary>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class CMUGuideCraftingRecipes : BoxContainer, IDocumentTag
{
    [Dependency] private readonly IEntityManager _entities = default!;
    [Dependency] private readonly IPrototypeManager _prototypes = default!;

    private readonly List<(CraftingRecipePrototype Recipe, string Name, string Search)> _entries = new();
    private readonly List<CraftingRecipePrototype> _matches = new();
    private CraftingRecipePrototype? _selected;
    private int _batches = 1;

    public CMUGuideCraftingRecipes()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        MouseFilter = MouseFilterMode.Stop;

        foreach (var amount in new[] { 1, 5, 10 })
            Batches.AddItem(Loc.GetString("cmu-industry-recipes-batch-count", ("count", amount)), amount);

        Batches.SelectId(1);
        Batches.OnItemSelected += args =>
        {
            Batches.SelectId(args.Id);
            _batches = args.Id;
            ShowRecipe();
        };
        Search.OnTextChanged += _ => FilterRecipes();
        Recipes.OnItemSelected += args =>
        {
            _selected = _matches[args.ItemIndex];
            ShowRecipe();
        };
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        var recipes = _prototypes.EnumeratePrototypes<CraftingRecipePrototype>();
        if (args.TryGetValue("Recipes", out var ids))
        {
            var chosen = new List<CraftingRecipePrototype>();
            foreach (var id in ids.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries))
            {
                if (!_prototypes.TryIndex<CraftingRecipePrototype>(id, out var recipe))
                    return false;

                chosen.Add(recipe);
            }

            recipes = chosen;
        }

        foreach (var recipe in recipes)
        {
            var name = Loc.GetString(recipe.Name);
            var ingredients = recipe.Consumables.Select(IngredientName);
            _entries.Add((recipe, name, string.Join(" ", ingredients.Prepend(name))));
        }

        _entries.Sort((a, b) => string.Compare(a.Name, b.Name, StringComparison.CurrentCultureIgnoreCase));
        FilterRecipes();
        control = this;
        return true;
    }

    private string IngredientName(CraftConsumable ingredient)
    {
        if (ingredient.Stack is { } stackId)
        {
            var stack = _prototypes.Index(stackId);
            return _prototypes.Index(stack.Spawn).Name;
        }

        return ingredient.Item is { } item ? _prototypes.Index(item).Name : string.Empty;
    }

    private void FilterRecipes()
    {
        var previous = _selected;
        var query = Search.Text.Trim();
        Recipes.Clear();
        _matches.Clear();
        foreach (var entry in _entries)
        {
            if (!entry.Search.Contains(query, StringComparison.CurrentCultureIgnoreCase))
                continue;

            Recipes.AddItem(entry.Name);
            _matches.Add(entry.Recipe);
        }

        MatchCount.Text = _matches.Count == 0
            ? Loc.GetString("cmu-industry-recipes-empty")
            : Loc.GetString("cmu-industry-recipes-matches", ("count", _matches.Count));
        _selected = previous != null && _matches.Contains(previous) ? previous : _matches.FirstOrDefault();
        if (_selected != null)
            Recipes[_matches.IndexOf(_selected)].Selected = true;
        else
            ShowRecipe();
    }

    private void ShowRecipe()
    {
        Details.Visible = _selected != null;
        if (_selected is not { } recipe)
            return;

        // Reuse the crafting menu's stack names and icons without opening its window or sending a request.
        var card = _entities.System<CraftingSystem>().BuildCards(new[] { recipe.ID }).Single();
        OutputIcon.Texture = card.Icon;
        SetText(RecipeName, card.Name);
        OutputCount.Text = Loc.GetString("cmu-industry-recipes-output", ("count", recipe.OutputCount * _batches));
        RecipeTime.Text = Loc.GetString("cmu-industry-recipes-time", ("seconds", recipe.Time.TotalSeconds));
        Ingredients.RemoveAllChildren();
        foreach (var ingredient in card.Ingredients)
        {
            var row = new BoxContainer { SeparationOverride = 8, HorizontalExpand = true };
            row.AddChild(new TextureRect
            {
                Texture = ingredient.Icon,
                MinSize = new Vector2(32, 32),
                MaxSize = new Vector2(32, 32),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
            });
            var label = new RichTextLabel { HorizontalExpand = true, VerticalAlignment = VAlignment.Center };
            SetText(label, Loc.GetString("cmu-industry-recipes-ingredient",
                ("count", ingredient.Amount * _batches), ("name", ingredient.Name)));
            row.AddChild(label);
            Ingredients.AddChild(row);
        }

        SetText(Tools, string.IsNullOrEmpty(card.Tools)
            ? Loc.GetString("cmu-industry-recipes-no-tools")
            : Loc.GetString("cmu-industry-recipes-tools", ("tools", card.Tools)));
        var skills = recipe.Skills.Select(pair => Loc.GetString("cmu-industry-recipes-skill",
            ("name", _prototypes.Index(pair.Key).Name), ("level", pair.Value)));
        SetText(Skills, recipe.Skills.Count == 0
            ? Loc.GetString("cmu-industry-recipes-no-skills")
            : Loc.GetString("cmu-industry-recipes-skills", ("skills", string.Join(", ", skills))));
        Minigames.Visible = recipe.Minigames.Count > 0;
        if (Minigames.Visible)
            SetText(Minigames, Loc.GetString("cmu-industry-recipes-minigames", ("count", recipe.Minigames.Count)));
    }

    private static void SetText(RichTextLabel label, string text)
    {
        var message = new FormattedMessage();
        message.AddText(text);
        label.SetMessage(message);
    }
}
