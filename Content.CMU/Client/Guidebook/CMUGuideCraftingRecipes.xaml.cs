namespace Content.Client.CMU14.Guidebook;

/// <summary>Read-only production and acquisition lookup; browsing never crafts or spawns anything.</summary>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class CMUGuideCraftingRecipes : BoxContainer, IDocumentTag
{
    [Dependency] private readonly IEntityManager _entities = default!;
    [Dependency] private readonly IPrototypeManager _prototypes = default!;

    private readonly List<CMUGuideRecipe> _entries = new();
    private readonly List<CMUGuideRecipe> _matches = new();
    private readonly Stack<NavigationState> _history = new();
    private CMUGuideRecipeCatalog _catalog = default!;
    private HashSet<string>? _scope;
    private CMUGuideRecipe? _selected;
    private int _batches = 1;

    private sealed record NavigationState(HashSet<string>? Scope, string Search, CMUGuideRecipe? Selected, int Batches);

    public CMUGuideCraftingRecipes()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        MouseFilter = MouseFilterMode.Stop;

        foreach (var amount in new[] { 1, 5, 10 })
            Batches.AddItem(Loc.GetString("cmu-industry-recipes-batch-count", ("count", amount)), amount);

        Batches.SelectId(1);
        Batches.OnItemSelected += args =>
        {
            Batches.SelectId(args.Id);
            _batches = args.Id;
            ShowRecipe();
        };
        Search.OnTextChanged += _ => FilterRecipes();
        Back.OnPressed += _ => GoBack();
        Recipes.OnItemSelected += args =>
        {
            _selected = _matches[args.ItemIndex];
            ShowRecipe();
        };
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        if (args.TryGetValue("Recipes", out var ids))
        {
            _scope = new HashSet<string>();
            foreach (var id in ids.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries))
            {
                if (!_prototypes.HasIndex<CraftingRecipePrototype>(id))
                    return false;
                _scope.Add(id);
            }
        }

        // Ingredient links may leave a chapter's starter list; Back restores its exact selection and batch count.
        _catalog = new CMUGuideRecipeCatalog(_entities, _prototypes);
        _entries.AddRange(_catalog.Entries.OrderBy(e => e.Name, StringComparer.CurrentCultureIgnoreCase).ThenBy(e => e.Id));
        FilterRecipes();
        control = this;
        return true;
    }

    private void OpenIngredient(CMUGuideMaterial material)
    {
        var sources = _catalog.Sources(material);
        if (sources == null)
        {
            var id = $"unknown:{material.Kind}:{material.Id}";
            if (_entries.All(e => e.Id != id))
            {
                _entries.Add(new CMUGuideRecipe
                {
                    Id = id,
                    Name = _catalog.Name(material),
                    Search = _catalog.Name(material),
                    Method = Loc.GetString("cmu-industry-source-unknown"),
                    Instructions = Loc.GetString("cmu-industry-source-unknown-help"),
                    Outputs = new() { new(material, null) },
                    CanPlan = false,
                });
            }
            sources = new HashSet<string> { id };
        }

        _history.Push(new NavigationState(_scope, Search.Text, _selected, _batches));
        _scope = sources;
        Search.Text = string.Empty;
        _selected = null;
        _batches = 1;
        Batches.SelectId(_batches);
        FilterRecipes();
    }

    private void GoBack()
    {
        if (!_history.TryPop(out var state))
            return;
        _scope = state.Scope;
        Search.Text = state.Search;
        _selected = state.Selected;
        _batches = state.Batches;
        Batches.SelectId(_batches);
        FilterRecipes();
    }

    private void FilterRecipes()
    {
        Back.Visible = _history.Count > 0;
        var previous = _selected;
        var query = Search.Text.Trim();
        Recipes.Clear();
        _matches.Clear();
        foreach (var entry in _entries)
        {
            if ((_scope != null && !_scope.Contains(entry.Id)) ||
                !entry.Search.Contains(query, StringComparison.CurrentCultureIgnoreCase))
                continue;
            Recipes.AddItem(entry.Name);
            _matches.Add(entry);
        }

        MatchCount.Text = _matches.Count == 0
            ? Loc.GetString("cmu-industry-recipes-empty")
            : Loc.GetString("cmu-industry-recipes-matches", ("count", _matches.Count));
        _selected = previous != null && _matches.Contains(previous) ? previous : _matches.FirstOrDefault();
        if (_selected != null)
            Recipes[_matches.IndexOf(_selected)].Selected = true;
        ShowRecipe();
    }

    private void ShowRecipe()
    {
        Details.Visible = _selected != null;
        if (_selected is not { } entry)
            return;

        OutputIcon.Texture = Icon(entry.Outputs[0].Material, entry.HandRecipe?.Icon);
        OutputIcon.Visible = OutputIcon.Texture != null;
        SetText(RecipeName, entry.Name);
        SetText(OutputCount, string.Join("\n", entry.Outputs.Select(p => Describe(p, entry.CanPlan ? _batches : 1))));
        RecipeTime.Visible = entry.Seconds != null;
        RecipeTime.Text = Loc.GetString("cmu-industry-recipes-time", ("seconds", entry.Seconds ?? 0));
        BatchRow.Visible = entry.CanPlan;
        SetText(Instructions, entry.Instructions);
        Equipment.RemoveAllChildren();
        EquipmentHeading.Visible = entry.Equipment.Count > 0;
        foreach (var equipment in entry.Equipment.Distinct())
            AddMaterialButton(Equipment, new(CMUGuideMaterial.Item(equipment), null), 1);

        Ingredients.RemoveAllChildren();
        IngredientsHeading.Visible = entry.Inputs.Count > 0;
        foreach (var ingredient in entry.Inputs)
            AddMaterialButton(Ingredients, ingredient, entry.CanPlan ? _batches : 1);

        Tools.Visible = Skills.Visible = entry.HandRecipe != null;
        Minigames.Visible = false;
        if (entry.HandRecipe is not { } recipe)
            return;

        var tools = recipe.Tools.Select(t => Loc.GetString(_prototypes.Index(t).ToolName));
        SetText(Tools, recipe.Tools.Count == 0
            ? Loc.GetString("cmu-industry-recipes-no-tools")
            : Loc.GetString("cmu-industry-recipes-tools", ("tools", string.Join(", ", tools))));
        var skills = recipe.Skills.Select(pair => Loc.GetString("cmu-industry-recipes-skill",
            ("name", _prototypes.Index(pair.Key).Name), ("level", pair.Value)));
        SetText(Skills, recipe.Skills.Count == 0
            ? Loc.GetString("cmu-industry-recipes-no-skills")
            : Loc.GetString("cmu-industry-recipes-skills", ("skills", string.Join(", ", skills))));
        Minigames.Visible = recipe.Minigames.Count > 0;
        if (Minigames.Visible)
            SetText(Minigames, Loc.GetString("cmu-industry-recipes-minigames", ("count", recipe.Minigames.Count)));
    }

    private string Describe(CMUGuideIngredient ingredient, int batches)
    {
        var name = _catalog.Name(ingredient.Material);
        if (ingredient.Amount is not { } amount)
            return name;
        var text = Loc.GetString(ingredient.Material.Kind == CMUGuideMaterialKind.Fluid
                ? "cmu-industry-source-fluid" : "cmu-industry-recipes-ingredient",
            ("count", amount * (ingredient.Kept ? 1 : batches)), ("name", name));
        return ingredient.Kept ? Loc.GetString("cmu-industry-source-kept", ("item", text)) : text;
    }

    private void AddMaterialButton(BoxContainer container, CMUGuideIngredient ingredient, int batches)
    {
        var button = new ContainerButton
        {
            HorizontalExpand = true,
            ToolTip = Loc.GetString("cmu-industry-recipes-open-ingredient", ("name", _catalog.Name(ingredient.Material))),
        };
        button.AddStyleClass(ContainerButton.StyleClassButton);
        button.OnPressed += _ => OpenIngredient(ingredient.Material);
        var row = new BoxContainer
        {
            SeparationOverride = 8,
            HorizontalExpand = true,
            MouseFilter = MouseFilterMode.Ignore,
        };
        var icon = Icon(ingredient.Material);
        if (icon != null)
        {
            row.AddChild(new TextureRect
            {
                Texture = icon,
                MinSize = new Vector2(32, 32),
                MaxSize = new Vector2(32, 32),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                MouseFilter = MouseFilterMode.Ignore,
            });
        }
        var label = new RichTextLabel
        {
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            MouseFilter = MouseFilterMode.Ignore,
        };
        SetText(label, Describe(ingredient, batches));
        row.AddChild(label);
        row.AddChild(new Label { Text = "→", MouseFilter = MouseFilterMode.Ignore });
        button.AddChild(row);
        container.AddChild(button);
    }

    private Texture? Icon(CMUGuideMaterial material, SpriteSpecifier? specifier = null)
    {
        specifier ??= _catalog.Icon(material);
        return specifier == null ? null : _entities.System<SpriteSystem>().Frame0(specifier);
    }

    private static void SetText(RichTextLabel label, string text)
    {
        var message = new FormattedMessage();
        message.AddText(text);
        label.SetMessage(message);
    }
}
