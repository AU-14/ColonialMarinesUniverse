namespace Content.Client.CMU14.Guidebook;

/// <summary>A searchable CRT guidebook card for one RUMC product.</summary>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class CMUGuideRecipeCard : BoxContainer, ISearchableControl, IPrototypeRepresentationControl
{
    private const int MaxPathDepth = 12;

    [Dependency] private IEntityManager _entities = default!;

    private readonly CMUGuideRecipeCatalog _catalog;
    private readonly string _searchText;

    public IPrototype? RepresentedPrototype { get; }

    public CMUGuideRecipeCard(
        CMUGuideRecipeCatalog catalog,
        CMUGuideMaterial product,
        IReadOnlyList<CMUGuideRecipe> recipes,
        IReadOnlyList<CMUGuideRecipe> sources)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _catalog = catalog;
        _searchText = string.Join(" ", recipes.Concat(sources).Select(entry => entry.Search)
            .Prepend(catalog.Name(product)));
        MouseFilter = MouseFilterMode.Stop;

        RepresentedPrototype = catalog.Prototype(product);
        ProductIcon.Texture = Icon(product);
        ProductIcon.Visible = ProductIcon.Texture != null;
        ProductName.SetMarkup(Loc.GetString("guidebook-reagent-name",
            ("color", Color.White), ("name", catalog.Name(product))));
        NameBackground.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#245b70"),
        };

        RecipeHeading.OnToggled += args =>
        {
            if (args.Pressed)
                PopulateRows(RecipesBody, recipes);
        };

        PathContainer.Visible = recipes.Count > 0;
        var pathBuilt = false;
        PathHeading.OnToggled += args =>
        {
            if (!args.Pressed || pathBuilt)
                return;
            pathBuilt = true;
            foreach (var recipe in recipes)
                AddProductionPath(PathBody, recipe);
        };

        SourcesContainer.Visible = sources.Count > 0;
        SourceHeading.OnToggled += args =>
        {
            if (args.Pressed)
                PopulateRows(SourcesBody, sources);
        };

        CrtLobbyTheme.Apply(this, useCrtTypography: false);
    }

    private void PopulateRows(BoxContainer body, IReadOnlyList<CMUGuideRecipe> entries)
    {
        if (body.ChildCount != 0)
            return;

        foreach (var entry in entries)
            AddRecipeRow(body, entry);
        CrtLobbyTheme.Apply(body, useCrtTypography: false);
    }

    public bool CheckMatchesSearch(string query) =>
        _searchText.Contains(query, StringComparison.CurrentCultureIgnoreCase) || this.ChildrenContainText(query);

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    private void AddRecipeRow(BoxContainer parent, CMUGuideRecipe recipe)
    {
        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(0, 4),
        };
        var flow = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };

        flow.AddChild(MaterialColumn(recipe.Inputs, HAlignment.Left));
        flow.AddChild(ProcessColumn(recipe));
        flow.AddChild(MaterialColumn(recipe.Outputs, HAlignment.Right));
        row.AddChild(flow);

        var details = new List<string>();
        if (recipe.Seconds is { } seconds)
            details.Add(Loc.GetString("cmu-industry-recipes-time", ("seconds", seconds)));
        if (!string.IsNullOrWhiteSpace(recipe.Instructions))
            details.Add(recipe.Instructions);
        if (details.Count > 0)
            row.AddChild(Text(string.Join(" ", details), HAlignment.Left));

        row.AddChild(new PanelContainer
        {
            StyleClasses = { "LowDivider" },
            Margin = new Thickness(0, 5),
        });
        parent.AddChild(row);
    }

    private void AddProductionPath(BoxContainer parent, CMUGuideRecipe recipe)
    {
        var route = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(0, 4),
            SeparationOverride = 3,
        };
        route.AddChild(Text(Loc.GetString("cmu-industry-recipes-path-route", ("method", recipe.Method)), HAlignment.Left));

        var visiting = new HashSet<string> { recipe.Id };
        foreach (var input in recipe.Inputs)
            AddPathIngredient(route, input, input.Amount ?? 1, 0, visiting);

        route.AddChild(new PanelContainer
        {
            StyleClasses = { "LowDivider" },
            Margin = new Thickness(0, 5),
        });
        parent.AddChild(route);
    }

    private void AddPathIngredient(
        BoxContainer parent,
        CMUGuideIngredient ingredient,
        double required,
        int depth,
        HashSet<string> visiting)
    {
        var displayed = ingredient with { Amount = required };
        var material = Material(displayed);
        material.Margin = new Thickness(depth * 12, 0, 0, 0);
        parent.AddChild(material);

        if (depth >= MaxPathDepth)
        {
            AddPathNote(parent, Loc.GetString("cmu-industry-recipes-path-depth"), depth + 1);
            return;
        }

        var canonical = _catalog.Canonical(ingredient.Material);
        var ids = _catalog.Sources(ingredient.Material) ?? _catalog.Sources(canonical);
        if (ids == null)
        {
            AddPathNote(parent, Loc.GetString("cmu-industry-recipes-path-external"), depth + 1);
            return;
        }

        var sources = ids.Select(_catalog.TryGet)
            .Where(entry => entry != null)
            .Cast<CMUGuideRecipe>()
            .Where(entry => !visiting.Contains(entry.Id))
            .OrderBy(entry => entry.CanPlan ? 0 : 1)
            .ThenBy(entry => entry.StationGroup == null ? 1 : 0)
            .ThenBy(entry => entry.Inputs.Count)
            .ThenBy(entry => entry.Method, StringComparer.CurrentCultureIgnoreCase)
            .ThenBy(entry => entry.Id, StringComparer.Ordinal)
            .ToList();

        if (sources.Count == 0)
        {
            AddPathNote(parent, Loc.GetString("cmu-industry-recipes-path-cycle"), depth + 1);
            return;
        }

        var source = sources[0];
        var output = source.Outputs.FirstOrDefault(candidate => _catalog.Canonical(candidate.Material) == canonical);
        var outputAmount = Math.Max(output?.Amount ?? 1, 0.0001);
        var batches = source.CanPlan ? Math.Ceiling(required / outputAmount) : 1;
        var alternateCount = sources.Count - 1;
        AddPathNote(parent, Loc.GetString("cmu-industry-recipes-path-step",
            ("method", source.Method),
            ("batches", batches),
            ("alternates", alternateCount)), depth + 1);

        if (!source.CanPlan)
            return;

        var nextVisiting = new HashSet<string>(visiting) { source.Id };
        foreach (var input in source.Inputs)
        {
            var amount = input.Amount ?? 1;
            AddPathIngredient(parent, input, input.Kept ? amount : amount * batches, depth + 2, nextVisiting);
        }
    }

    private static void AddPathNote(BoxContainer parent, string value, int depth)
    {
        var note = Text(value, HAlignment.Left);
        note.Margin = new Thickness(depth * 12, 0, 0, 0);
        parent.AddChild(note);
    }

    private BoxContainer MaterialColumn(IEnumerable<CMUGuideIngredient> ingredients, HAlignment alignment)
    {
        var column = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            HorizontalAlignment = alignment,
            VerticalAlignment = VAlignment.Center,
            SeparationOverride = 3,
        };
        foreach (var ingredient in ingredients)
            column.AddChild(Material(ingredient));
        return column;
    }

    private BoxContainer ProcessColumn(CMUGuideRecipe recipe)
    {
        var column = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
            MinWidth = 90,
        };

        foreach (var equipment in recipe.Equipment.Distinct().Take(3))
            column.AddChild(Material(new CMUGuideIngredient(CMUGuideMaterial.Item(equipment), null)));
        column.AddChild(Text(recipe.Method, HAlignment.Center));
        return column;
    }

    private Control Material(CMUGuideIngredient ingredient)
    {
        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            SeparationOverride = 4,
            VerticalAlignment = VAlignment.Center,
        };
        var icon = Icon(ingredient.Material);
        if (icon != null)
        {
            row.AddChild(new TextureRect
            {
                Texture = icon,
                MinSize = new System.Numerics.Vector2(24, 24),
                MaxSize = new System.Numerics.Vector2(24, 24),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                MouseFilter = MouseFilterMode.Ignore,
            });
        }

        var message = new FormattedMessage();
        var amount = ingredient.Amount is { } count ? $" [{count:g}]" : string.Empty;
        var kept = ingredient.Kept ? " (kept)" : string.Empty;
        message.AddText(_catalog.Name(ingredient.Material) + amount + kept);
        var link = new GuidebookRichPrototypeLink
        {
            LinkedPrototype = _catalog.Prototype(ingredient.Material),
        };
        link.SetMessage(message);
        row.AddChild(link);
        return row;
    }

    private static RichTextLabel Text(string value, HAlignment alignment)
    {
        var label = new RichTextLabel
        {
            HorizontalAlignment = alignment,
            HorizontalExpand = true,
        };
        var message = new FormattedMessage();
        message.AddText(value);
        label.SetMessage(message);
        return label;
    }

    private Texture? Icon(CMUGuideMaterial material)
    {
        var specifier = _catalog.Icon(material);
        return specifier == null ? null : _entities.System<SpriteSystem>().Frame0(specifier);
    }
}
