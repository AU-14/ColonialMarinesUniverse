using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.CMU14.SceneAnimation;

[GenerateTypedNameReferences]
public sealed partial class CMUGroundTextDecalWindow : DefaultWindow
{
    public event Action<string, float, float, float, Color>? OnPlace;

    public CMUGroundTextDecalWindow()
    {
        RobustXamlLoader.Load(this);

        ColorSelector.Color = Color.White;
        LetterSpacing.OnValueChanged += _ => UpdateLabels();
        LineSpacing.OnValueChanged += _ => UpdateLabels();
        Wonkiness.OnValueChanged += _ => UpdateLabels();
        PlaceButton.OnPressed += _ => OnPlace?.Invoke(
            Rope.Collapse(TextInput.TextRope),
            LetterSpacing.Value,
            LineSpacing.Value,
            Wonkiness.Value,
            ColorSelector.Color);
        UpdateLabels();
    }

    private void UpdateLabels()
    {
        LetterSpacingLabel.Text = $"Letter spacing: {LetterSpacing.Value:F2}";
        LineSpacingLabel.Text = $"Line spacing: {LineSpacing.Value:F2}";
        WonkinessLabel.Text = $"Wonkiness: {Wonkiness.Value:F2}";
    }
}
