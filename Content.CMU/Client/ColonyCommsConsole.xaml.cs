using Content.Shared.CMU14;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.CMU14;

[GenerateTypedNameReferences]
public sealed partial class ColonyCommsConsole : DefaultWindow
{
    [Dependency] private IGameTiming _timing = default!;

    private ColonyRotationTransportStatus _transport;
    private TimeSpan? _transportAt;

    public ColonyCommsConsole()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void UpdateTransport(ColonyCommsConsoleBuiState state)
    {
        _transport = state.Transport;
        _transportAt = state.TransportAt;
        TransportBox.Visible = state.Transport != ColonyRotationTransportStatus.None;
        TransportCall.Visible = state.Transport == ColonyRotationTransportStatus.Scheduled;
        TransportCall.Disabled = !state.CanCall;
        TransportRecall.Visible = state.Transport == ColonyRotationTransportStatus.Inbound;
        TransportRecall.Disabled = !state.CanRecall;
        UpdateTransportStatus();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (TransportBox.Visible)
            UpdateTransportStatus();
    }

    private void UpdateTransportStatus()
    {
        var left = _transportAt is { } at ? at - _timing.CurTime : TimeSpan.Zero;
        if (left < TimeSpan.Zero)
            left = TimeSpan.Zero;

        var time = $"{(int) left.TotalMinutes:00}:{left.Seconds:00}";
        TransportStatus.Text = _transport switch
        {
            ColonyRotationTransportStatus.Scheduled => Loc.GetString("colony-rotation-console-scheduled", ("time", time)),
            ColonyRotationTransportStatus.Inbound => Loc.GetString("colony-rotation-console-inbound", ("time", time)),
            ColonyRotationTransportStatus.Approaching => Loc.GetString("colony-rotation-console-approaching"),
            ColonyRotationTransportStatus.Docked => Loc.GetString("colony-rotation-console-docked", ("time", time)),
            ColonyRotationTransportStatus.Departing => Loc.GetString("colony-rotation-console-departing"),
            _ => string.Empty,
        };
    }
}
