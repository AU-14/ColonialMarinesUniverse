using System.Linq;
using Content.Client.Lobby.UI;
using Content.Shared.CMU14.CorporateWork;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.CMU14.CorporateWork;

[GenerateTypedNameReferences]
public sealed partial class CMUNegotiationTerminalWindow : DefaultWindow
{
    [Dependency] private IGameTiming _timing = default!;

    public event Action<int>? OnStart;
    public event Action<int>? OnOffer;
    public event Action? OnAccept;

    /// <summary>
    ///     Offer steps, as fractions of the list price.
    /// </summary>
    private static readonly float[] Steps = { -0.1f, -0.01f, 0.01f, 0.1f };

    private CMUNegotiationTerminalBuiState? _state;
    private int _offer;

    public CMUNegotiationTerminalWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        CrtLobbyTheme.ApplyWindow(this, useCrtTypography: true);
        CMUTerminalLayout.StylePanel(WorkPanel);

        OfferButton.OnPressed += _ => OnOffer?.Invoke(_offer);
        AcceptButton.OnPressed += _ => OnAccept?.Invoke();

        foreach (var step in Steps)
        {
            var button = new Button
            {
                Text = Loc.GetString("cmu-negotiation-step", ("percent", (int) MathF.Round(step * 100))),
                HorizontalExpand = true,
                MinHeight = 32,
            };
            button.OnPressed += _ =>
            {
                if (_state is not { ActiveTier: not null } state)
                    return;

                var change = Math.Max(10, (int) MathF.Round(Math.Abs(step) * state.ListPrice / 10f) * 10);
                _offer = Math.Clamp(_offer + (step < 0 ? -change : change), 10, state.Ask);
                UpdateOffer();
            };
            StepButtons.AddChild(button);
        }
    }

    public void UpdateState(CMUNegotiationTerminalBuiState state)
    {
        var newDeal = _state?.ActiveTier != state.ActiveTier || _state?.Supplier != state.Supplier;
        _state = state;
        if (newDeal || _offer > state.Ask || _offer <= 0)
            _offer = state.Ask;

        TierButtons.RemoveAllChildren();
        for (var i = 0; i < state.Tiers.Count; i++)
        {
            var tier = state.Tiers[i];
            var index = i;
            var button = new Button
            {
                Text = Loc.GetString("cmu-negotiation-tier",
                    ("name", Loc.GetString(tier.Name)), ("patience", tier.Patience), ("reward", tier.Reward)),
                HorizontalExpand = true,
                MinHeight = 34,
            };
            button.OnPressed += _ => OnStart?.Invoke(index);
            TierButtons.AddChild(button);
        }

        DealRows.RemoveAllChildren();
        if (state.ActiveTier != null)
        {
            var rows = new[]
            {
                Loc.GetString("cmu-negotiation-row-supplier", ("supplier", state.Supplier)),
                Loc.GetString("cmu-negotiation-row-goods", ("goods", state.Goods)),
                Loc.GetString("cmu-negotiation-row-list", ("price", state.ListPrice)),
                Loc.GetString("cmu-negotiation-row-ask", ("price", state.Ask)),
                Loc.GetString("cmu-negotiation-row-patience", ("patience", state.Patience)),
            };
            for (var i = 0; i < rows.Length; i++)
                DealRows.AddChild(CMUTerminalLayout.Row(new Label { Text = rows[i] }, i));
        }

        LogRows.RemoveAllChildren();
        for (var i = 0; i < state.Log.Count; i++)
        {
            var exchange = state.Log[i];
            LogRows.AddChild(CMUTerminalLayout.Row(new Label
            {
                Text = Loc.GetString($"cmu-negotiation-reply-{exchange.Reply.ToString().ToLowerInvariant()}",
                    ("offer", exchange.Offer), ("ask", exchange.Ask)),
            }, i));
        }

        UpdateOffer();
        UpdateStatus();

        // Rows are rebuilt on every update, so they need the theme again.
        CrtLobbyTheme.Apply(this, useCrtTypography: true);
    }

    private void UpdateOffer()
    {
        var active = _state?.ActiveTier != null;
        OfferLabel.Text = active ? Loc.GetString("cmu-negotiation-your-offer", ("price", _offer)) : string.Empty;
        OfferButton.Disabled = !active;
        AcceptButton.Disabled = !active;
        foreach (var child in StepButtons.Children)
        {
            if (child is Button button)
                button.Disabled = !active;
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_state is { ActiveTier: null } && _state.NextCaseAt > _timing.CurTime)
            UpdateStatus();
    }

    private void UpdateStatus()
    {
        if (_state == null)
            return;

        if (_state.ActiveTier is { } active)
        {
            StatusLabel.Text = Loc.GetString("cmu-negotiation-status-active", ("name", Loc.GetString(_state.Tiers[active].Name)));
            return;
        }

        var lines = new List<string>();
        if (_state.LastResult is { } result)
        {
            lines.Add(result.Price is { } price
                ? Loc.GetString("cmu-negotiation-status-closed", ("price", price), ("list", result.ListPrice), ("payout", result.Payout))
                : Loc.GetString("cmu-negotiation-status-walked"));
        }

        var remaining = _state.NextCaseAt - _timing.CurTime;
        lines.Add(remaining > TimeSpan.Zero
            ? Loc.GetString("cmu-negotiation-status-cooldown", ("seconds", (int) Math.Ceiling(remaining.TotalSeconds)))
            : Loc.GetString("cmu-negotiation-status-idle"));

        StatusLabel.Text = string.Join("\n", lines);
    }
}
