using System.Linq;
using Content.Client.Lobby.UI;
using Content.Shared.CMU14.CorporateWork;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.CMU14.CorporateWork;

/// <summary>
///     The window shared by every corporate review desk: the day's rules, a queue of documents, and a
///     decision for each.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CMUReviewDeskWindow : DefaultWindow
{
    [Dependency] private IGameTiming _timing = default!;

    public event Action<int>? OnStart;
    public event Action<int[]>? OnSubmit;

    private CMUReviewDeskBuiState? _state;
    private int[] _decisions = Array.Empty<int>();

    public CMUReviewDeskWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        CrtLobbyTheme.ApplyWindow(this, useCrtTypography: true);
        CMUTerminalLayout.StylePanel(WorkPanel);

        SubmitButton.OnPressed += _ => OnSubmit?.Invoke(_decisions.ToArray());
    }

    public void UpdateState(CMUReviewDeskBuiState state)
    {
        // Another player opening the terminal re-sends the same case; keep this player's decisions.
        var sameCase = _state != null && _state.ActiveTier == state.ActiveTier && _state.Items.Count == state.Items.Count &&
                       _state.Items.Zip(state.Items).All(p => p.First.Title == p.Second.Title);
        if (!sameCase)
            _decisions = Enumerable.Repeat(-1, state.Items.Count).ToArray();

        _state = state;
        Title = state.Title;
        HeadingLabel.Text = state.Heading;
        InstructionsLabel.Text = state.Instructions;

        TierButtons.RemoveAllChildren();
        for (var i = 0; i < state.Tiers.Count; i++)
        {
            var tier = state.Tiers[i];
            var index = i;
            var button = new Button
            {
                Text = Loc.GetString("cmu-desk-tier",
                    ("name", Loc.GetString(tier.Name)),
                    ("items", tier.Items),
                    ("rules", tier.Rules),
                    ("reward", tier.Reward)),
                HorizontalExpand = true,
                MinHeight = 34,
            };
            button.OnPressed += _ => OnStart?.Invoke(index);
            TierButtons.AddChild(button);
        }

        RuleRows.RemoveAllChildren();
        for (var i = 0; i < state.Rules.Count; i++)
        {
            var label = new RichTextLabel { HorizontalExpand = true };
            label.SetMessage(state.Rules[i]);
            RuleRows.AddChild(CMUTerminalLayout.Row(label, i));
        }

        RebuildCards();
        UpdateStatus();
    }

    private void RebuildCards()
    {
        if (_state == null)
            return;

        ItemCards.RemoveAllChildren();
        for (var i = 0; i < _state.Items.Count; i++)
        {
            var item = _state.Items[i];
            var card = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, SeparationOverride = 2 };
            card.AddChild(new Label { Text = item.Title, StyleClasses = { "LabelHeading" } });
            foreach (var line in item.Lines)
            {
                var label = new RichTextLabel { HorizontalExpand = true };
                label.SetMessage(line);
                card.AddChild(label);
            }

            var buttons = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6, Margin = new Thickness(0, 4, 0, 0) };
            for (var o = 0; o < _state.Options.Count; o++)
            {
                var itemIndex = i;
                var option = o;
                var button = new Button
                {
                    Text = _state.Options[o],
                    ToggleMode = true,
                    Pressed = _decisions[i] == o,
                    HorizontalExpand = true,
                    MinHeight = 30,
                };
                button.OnPressed += _ =>
                {
                    _decisions[itemIndex] = _decisions[itemIndex] == option ? -1 : option;
                    RebuildCards();
                };
                buttons.AddChild(button);
            }

            card.AddChild(buttons);
            ItemCards.AddChild(CMUTerminalLayout.Row(card, i));
        }

        SubmitButton.Disabled = _state.ActiveTier == null;

        // Cards are rebuilt on every change, so they need the theme again.
        CrtLobbyTheme.Apply(this, useCrtTypography: true);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_state is { ActiveTier: null } && _state.NextCaseAt > _timing.CurTime)
            UpdateStatus();
    }

    private void UpdateStatus()
    {
        if (_state == null)
            return;

        if (_state.ActiveTier is { } active)
        {
            var decided = _decisions.Count(d => d >= 0);
            StatusLabel.Text = Loc.GetString("cmu-desk-status-active",
                ("name", Loc.GetString(_state.Tiers[active].Name)),
                ("decided", decided),
                ("total", _state.Items.Count));
            return;
        }

        var lines = new List<string>();
        if (_state.LastResult is { } result)
        {
            lines.Add(Loc.GetString("cmu-desk-status-result",
                ("correct", result.Correct), ("wrong", result.Wrong), ("undecided", result.Undecided), ("payout", result.Payout)));
        }

        var remaining = _state.NextCaseAt - _timing.CurTime;
        lines.Add(remaining > TimeSpan.Zero
            ? Loc.GetString("cmu-desk-status-cooldown", ("seconds", (int) Math.Ceiling(remaining.TotalSeconds)))
            : Loc.GetString("cmu-desk-status-idle"));

        StatusLabel.Text = string.Join("\n", lines);
    }
}
