namespace Content.Client.CMU14.Insurgency.Selection;

[GenerateTypedNameReferences]
public sealed partial class InsurgencyFactionSelectWindow : DefaultWindow
{
    private readonly IPrototypeManager _prototypes = IoCManager.Resolve<IPrototypeManager>();
    private readonly Texture _defaultInsignia = IoCManager.Resolve<IResourceCache>().GetTexture(CMUIcons.CircleDot);
    private readonly SpriteSystem _sprites = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>();
    private readonly IResourceManager _resources = IoCManager.Resolve<IResourceManager>();
    private readonly IGameTiming _timing = IoCManager.Resolve<IGameTiming>();
    private readonly ResPath? _exclusionsFile;
    private readonly HashSet<int> _excluded = new();
    private readonly Dictionary<int, ContainerButton> _rows = new();
    private DefaultFactionOption? _selected;
    private TimeSpan? _deadline;
    private int _seconds = -1;
    private bool _showKit;

    public int[] Exclusions => _excluded.ToArray();
    public event Action<int>? OnSelectDefault;
    public event Action<int[]>? OnExclusionsChanged;

    public InsurgencyFactionSelectWindow()
    {
        RobustXamlLoader.Load(this);
        GmodStyle.StyleWindow(this);
        ContextPanel.PanelOverride = Navigation.PanelOverride = Actions.PanelOverride = GmodStyle.Panel(GmodStyle.PanelBg);
        Details.PanelOverride = GmodStyle.Panel(GmodStyle.DetailBg);
        Countdown.FontColorOverride = GmodStyle.Accent;
        GmodStyle.Modernize(BriefingTab, true);
        GmodStyle.Modernize(KitTab, true);
        GmodStyle.Modernize(Vote, baseBg: GmodStyle.RowSelected);

        if (IoCManager.Resolve<Robust.Shared.Network.IClientNetManager>().ServerChannel is { } channel)
        {
            var server = channel.RemoteEndPoint;
            _exclusionsFile = new ResPath($"/cmu-insurgency-{channel.UserId}-{server.Address.ToString().Replace(':', '-')}-{server.Port}.txt");
            if (_resources.UserData.TryReadAllText(_exclusionsFile.Value, out var saved))
            {
                foreach (var field in saved.Split(' '))
                {
                    if (int.TryParse(field, out var id))
                        _excluded.Add(id);
                }
            }
        }

        var viewport = UserInterfaceManager.WindowRoot.Size;
        if (viewport.X > 0 && viewport.Y > 0)
        {
            var available = Vector2.Max(Vector2.One, viewport - new Vector2(16, 16));
            MinSize = Vector2.Min(MinSize, available);
            SetSize = Vector2.Min(SetSize, available);
        }

        BriefingTab.OnPressed += _ => ShowTab(false);
        KitTab.OnPressed += _ => ShowTab(true);
        Vote.OnPressed += _ =>
        {
            if (_selected is { Opposes: true } faction && !_excluded.Contains(faction.Id))
                OnSelectDefault?.Invoke(faction.Id);
        };
        Exclude.OnToggled += args =>
        {
            if (_selected is not { } faction)
                return;
            if (args.Pressed)
                _excluded.Add(faction.Id);
            else
                _excluded.Remove(faction.Id);
            if (_exclusionsFile is { } file)
            {
                using var writer = _resources.UserData.OpenWriteText(file);
                writer.Write(string.Join(" ", _excluded));
            }
            UpdateActions();
            OnExclusionsChanged?.Invoke(Exclusions);
        };
    }

    public void SetState(InsurgencyFactionSelectEuiState state)
    {
        Opponent.SetMessage(state.GovforPlatoonName is { } name
            ? Loc.GetString("insfor-select-govfor", ("name", name))
            : Loc.GetString("insfor-select-govfor-unknown"));
        _deadline = state.Deadline;
        UpdateCountdown();
        FactionList.RemoveAllChildren();
        _rows.Clear();
        foreach (var group in state.Defaults.OrderByDescending(option => option.Opposes)
                     .ThenBy(TitleOf, StringComparer.CurrentCultureIgnoreCase).GroupBy(option => option.Opposes))
        {
            var heading = new RichTextLabel
            {
                HorizontalExpand = true, StyleClasses = { "LabelKeyText" }, Margin = new Thickness(4, 5, 0, 2),
            };
            heading.SetMessage(Loc.GetString(group.Key ? "cmu-insfor-ballot-available" : "cmu-insfor-ballot-unavailable"), GmodStyle.Accent);
            FactionList.AddChild(heading);
            foreach (var faction in group)
            {
                var row = GmodStyle.NavigationButton(TitleOf(faction), GetInsignia(faction),
                    faction.Opposes ? Color.White : Color.LightGray);
                row.OnPressed += _ => SelectFaction(faction);
                FactionList.AddChild(row);
                _rows.Add(faction.Id, row);
            }
        }
        var current = state.Defaults.Find(option => option.Id == _selected?.Id);
        var first = state.Defaults.Where(option => option.Opposes && !_excluded.Contains(option.Id))
            .OrderBy(TitleOf, StringComparer.CurrentCultureIgnoreCase).FirstOrDefault();
        SelectFaction(current ?? first ?? state.Defaults.FirstOrDefault(option => option.Opposes) ?? state.Defaults.FirstOrDefault());
    }

    private static string TitleOf(DefaultFactionOption option) =>
        string.IsNullOrWhiteSpace(option.Title) ? Loc.GetString("insfor-select-untitled") : option.Title;

    private void SelectFaction(DefaultFactionOption? option)
    {
        _selected = option;
        foreach (var (id, button) in _rows)
            GmodStyle.SelectButton(button, id == option?.Id);
        FactionName.SetMessage(option == null ? Loc.GetString("insfor-select-empty") : TitleOf(option), GmodStyle.Accent);
        Insignia.Texture = option == null ? null : GetInsignia(option);
        Insignia.Visible = Insignia.Texture != null;
        Tabs.Visible = Actions.Visible = option != null;
        Exclude.Pressed = option != null && _excluded.Contains(option.Id);
        UpdateActions();
        ShowTab(_showKit);
    }

    private Texture GetInsignia(DefaultFactionOption option)
    {
        if (option.FlagEntity is { } flag && _prototypes.TryIndex<EntityPrototype>(flag, out var entity))
            return _sprites.GetPrototypeIcon(entity).Default;
        if (option.StatusIcon is { } icon && _prototypes.TryIndex<FactionIconPrototype>(icon, out var status))
            return _sprites.Frame0(status.Icon);
        return _defaultInsignia;
    }

    private void UpdateActions()
    {
        Vote.Disabled = _selected is not { Opposes: true } || Exclude.Pressed || _seconds <= 0;
    }

    private void ShowTab(bool kit)
    {
        _showKit = kit;
        GmodStyle.SelectButton(BriefingTab, !kit);
        GmodStyle.SelectButton(KitTab, kit);
        DetailBody.RemoveAllChildren();
        DetailScroll.SetScrollValue(Vector2.Zero);
        if (_selected is not { } option)
            return;

        if (kit)
        {
            var grid = new WrapContainer { HorizontalExpand = true, SeparationOverride = 3, CrossSeparationOverride = 3 };
            foreach (var id in option.CellKitEntities)
            {
                if (!_prototypes.TryIndex<EntityPrototype>(id, out var prototype))
                    continue;
                var tile = new PanelContainer { SetSize = new Vector2(44, 44), ToolTip = prototype.Name,
                    MouseFilter = MouseFilterMode.Stop, PanelOverride = GmodStyle.Panel(GmodStyle.RowBg) };
                tile.AddChild(new TextureRect
                {
                    Texture = _sprites.GetPrototypeIcon(prototype).Default,
                    CanShrink = true, Stretch = TextureRect.StretchMode.KeepAspectCentered, Margin = new Thickness(4),
                    MouseFilter = MouseFilterMode.Ignore,
                });
                grid.AddChild(tile);
            }
            DetailBody.AddChild(grid);
            if (grid.ChildCount == 0)
                AddText(Loc.GetString("insfor-select-cellkit-empty"));
            return;
        }

        if (!option.Opposes)
            AddText(Loc.GetString("insfor-select-not-opposed"));
        if (!string.IsNullOrWhiteSpace(option.Description))
            AddText(option.Description.Trim());
        if (!string.IsNullOrWhiteSpace(option.Roleplay))
        {
            DetailBody.AddChild(new Label { Text = Loc.GetString("insfor-select-playstyle-header"),
                StyleClasses = { "LabelKeyText" }, FontColorOverride = GmodStyle.Accent });
            AddText(option.Roleplay.Trim());
        }
        if (DetailBody.ChildCount == 0)
            AddText(Loc.GetString("cmu-insfor-ballot-no-briefing"));
    }

    private void AddText(string text)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(text);
        DetailBody.AddChild(label);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateCountdown();
    }

    private void UpdateCountdown()
    {
        var seconds = _deadline is { } end ? Math.Max(0, (int) Math.Ceiling((end - _timing.CurTime).TotalSeconds)) : 0;
        if (seconds == _seconds)
            return;
        _seconds = seconds;
        Countdown.Text = Loc.GetString("cmu-insfor-ballot-remaining", ("seconds", seconds));
        UpdateActions();
    }
}
