using System.Numerics;
using Content.Client.Lobby.UI;
using Content.Client.Stylesheets;
using Content.Shared._RMC14.TacticalMap;
using Content.Shared.CMU14.DropPod;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CMU14.DropPod;

[GenerateTypedNameReferences]
public sealed partial class CMUDropPodConsoleWindow : DefaultWindow
{
    private const int RingSegments = 48;
    private static readonly Color TargetColor = Color.FromHex("#FF4040");
    private static readonly Color RingColor = Color.FromHex("#FFB040");

    private readonly Dictionary<NetEntity, CheckBox> _checks = new();

    public CMUDropPodConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        Map.QueenEyeMode = true;
        Map.IsCanvas = false;
        Map.Drawing = false;
        SelectAllButton.OnPressed += _ =>
        {
            foreach (var check in _checks.Values)
            {
                if (!check.Disabled)
                    check.Pressed = true;
            }
        };
    }

    public List<NetEntity> GetSelected()
    {
        var selected = new List<NetEntity>();
        foreach (var (pod, check) in _checks)
        {
            if (check.Pressed && !check.Disabled)
                selected.Add(pod);
        }

        return selected;
    }

    public void UpdateState(CMUDropPodConsoleBuiState state, TimeSpan now)
    {
        TargetLabel.Text = state.Target is { } target
            ? Loc.GetString("cmu-drop-pod-console-target", ("x", target.X), ("y", target.Y))
            : Loc.GetString("cmu-drop-pod-console-no-target-set");

        TargetHintLabel.Text = state.Target != null
            ? Loc.GetString("cmu-drop-pod-console-target-hint")
            : state.AllowBlindDrop
                ? Loc.GetString("cmu-drop-pod-console-blind-hint")
                : Loc.GetString("cmu-drop-pod-console-no-blind-hint");

        ClearTargetButton.Disabled = state.Target == null;
        FireButton.Text = state.Target == null && state.AllowBlindDrop
            ? Loc.GetString("cmu-drop-pod-console-fire-blind")
            : Loc.GetString("cmu-drop-pod-console-fire");

        var remaining = state.NextLaunch - now;
        CooldownLabel.Text = remaining > TimeSpan.Zero
            ? Loc.GetString("cmu-drop-pod-console-cooldown-remaining", ("seconds", (int) Math.Ceiling(remaining.TotalSeconds)))
            : Loc.GetString("cmu-drop-pod-console-ready");

        var previous = new HashSet<NetEntity>(GetSelected());
        _checks.Clear();
        PodList.RemoveAllChildren();
        var maxRadius = 0f;
        var index = 0;
        foreach (var entry in state.Pods)
        {
            var text = entry.Custom
                ? Loc.GetString("cmu-drop-pod-console-entry-custom", ("name", entry.Name))
                : Loc.GetString("cmu-drop-pod-console-entry",
                    ("name", entry.Name),
                    ("occupant", entry.Occupant ?? Loc.GetString("cmu-drop-pod-console-empty")),
                    ("weapons", entry.Weapons));

            var check = new CheckBox
            {
                Text = text,
                Disabled = !entry.Ready,
                Pressed = entry.Ready && previous.Contains(entry.Pod),
                HorizontalExpand = true,
                ClipText = true,
                ToolTip = text,
            };

            _checks[entry.Pod] = check;
            PodList.AddChild(new PanelContainer
            {
                HorizontalExpand = true,
                StyleClasses = { index++ % 2 == 1 ? StyleNano.StyleClassCrtTableCellAlt : StyleNano.StyleClassCrtTableCell },
                Children = { new BoxContainer { Margin = new Thickness(4, 2), Children = { check } } },
            });
            maxRadius = Math.Max(maxRadius, entry.Radius);
        }

        PodsEmptyLabel.Visible = state.Pods.Count == 0;
        CrtLobbyTheme.Apply(PodList);
        DrawTarget(state.Target, maxRadius);
    }

    private void DrawTarget(Vector2i? target, float radius)
    {
        Map.RemoveLinesByColor(TargetColor);
        Map.RemoveLinesByColor(RingColor);
        if (target is not { } tile)
            return;

        var center = new Vector2(tile.X + 0.5f, tile.Y + 0.5f);
        Map.Lines.Add(Line(TargetColor, 2, center + new Vector2(-1.5f, 0), center + new Vector2(1.5f, 0)));
        Map.Lines.Add(Line(TargetColor, 2, center + new Vector2(0, -1.5f), center + new Vector2(0, 1.5f)));
        if (radius <= 0)
            return;

        var ring = new Vector2[RingSegments + 1];
        for (var i = 0; i <= RingSegments; i++)
        {
            var angle = MathF.Tau * i / RingSegments;
            ring[i] = center + new Vector2(MathF.Cos(angle), MathF.Sin(angle)) * radius;
        }

        Map.Lines.Add(new TacticalMapLine(Vector2i.Zero, Vector2i.Zero, RingColor, 1.5f, ring));
    }

    private static TacticalMapLine Line(Color color, float thickness, Vector2 start, Vector2 end)
    {
        return new TacticalMapLine(Vector2i.Zero, Vector2i.Zero, color, thickness, [start, end]);
    }
}
