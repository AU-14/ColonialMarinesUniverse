namespace Content.Client.CMU14.Construction;

[GenerateTypedNameReferences]
public sealed partial class GmodConstructionMenu : DefaultWindow, IConstructionMenuView
{
    private const string All = "construction-category-all";
    private const string Favorites = "construction-category-favorites";
    private const string DefaultCollection = "AU14";

    private readonly Texture _catalogIcon = IoCManager.Resolve<IResourceCache>().GetTexture(CMUIcons.Book);
    private IReadOnlyDictionary<string, EntityPrototype>? _categoryExamples;

    public string[] Categories { get; set; } = [];
    public int SelectedCategoryId { get; private set; }
    public string SelectedSpawnlist { get; private set; } = DefaultCollection;
    public bool UseGroupedView => true;
    public bool CloseOnConstruct => false;
    public bool GridViewButtonPressed { get => true; set { } }
    public bool EraseButtonPressed { get => EraseButton.Pressed; set => EraseButton.Pressed = value; }
    public bool BuildButtonPressed { get => BuildButton.Pressed; set => BuildButton.Pressed = value; }

    // The classic view also offers a flat grid and list. The presenter clears these when switching views.
    public ListContainer Recipes { get; } = new();
    public GridContainer RecipesGrid { get; } = new();

    public event EventHandler<(string search, string catagory)>? PopulateRecipes;
    public event EventHandler<ConstructionMenu.ConstructionMenuListData?>? RecipeSelected { add { } remove { } }
    public event EventHandler? RecipeFavorited;
    public event EventHandler<bool>? BuildButtonToggled;
    public event EventHandler<bool>? EraseButtonToggled;
    public event EventHandler? ClearAllGhosts;

    public GmodConstructionMenu()
    {
        RobustXamlLoader.Load(this);
        GmodStyle.StyleWindow(this);
        Toolbar.PanelOverride = Navigation.PanelOverride = GhostTools.PanelOverride = GmodStyle.Panel(GmodStyle.PanelBg);
        RecipeDetails.PanelOverride = GmodStyle.Panel(GmodStyle.DetailBg);
        Catalog.PanelOverride = new StyleBoxFlat { BackgroundColor = GmodStyle.CatalogBg };
        SearchBar.StyleBoxOverride = GmodStyle.Panel(GmodStyle.FieldBg);
        GmodStyle.Modernize(Collections);
        GmodStyle.Modernize(FavoritesFilter, true);
        GmodStyle.Modernize(BuildButton, true);
        GmodStyle.Modernize(FavoriteButton);
        GmodStyle.Modernize(EraseButton, true);
        GmodStyle.Modernize(ClearButton);
        ConfigureAdminTools();
        Collections.OnItemSelected += args =>
        {
            Collections.SelectId(args.Id);
            SelectedSpawnlist = (string) Collections.GetItemMetadata(Collections.GetIdx(args.Id))!;
            SelectedCategoryId = 0;
            RefreshRecipes();
        };
        FavoritesFilter.OnToggled += _ => RefreshRecipes();
        SearchBar.OnTextChanged += _ => RefreshRecipes();
        FavoriteButton.OnPressed += _ => RecipeFavorited?.Invoke(this, EventArgs.Empty);
        BuildButton.OnToggled += args => BuildButtonToggled?.Invoke(this, args.Pressed);
        EraseButton.OnToggled += args => EraseButtonToggled?.Invoke(this, args.Pressed);
        ClearButton.OnPressed += _ => ClearAllGhosts?.Invoke(this, EventArgs.Empty);
    }

    private void RefreshRecipes()
    {
        var searching = !string.IsNullOrWhiteSpace(SearchBar.Text);
        FavoritesFilter.Disabled = searching;
        Collections.Disabled = searching || FavoritesFilter.Pressed;
        foreach (var button in CategoryButtons.Children.OfType<ContainerButton>())
            button.Disabled = Collections.Disabled;

        var category = FavoritesFilter.Pressed ? Favorites : Categories.ElementAtOrDefault(SelectedCategoryId) ?? All;
        PopulateRecipes?.Invoke(this, (SearchBar.Text, category));
    }

    public void SetCategories(string[] names, int selected, IReadOnlyDictionary<string, EntityPrototype>? examples = null)
    {
        if (!Categories.SequenceEqual(names) || examples != null && (_categoryExamples == null || !examples.SequenceEqual(_categoryExamples)))
        {
            Categories = names;
            _categoryExamples = examples;
            var sprites = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>();
            CategoryButtons.RemoveAllChildren();
            for (var i = 0; i < names.Length; i++)
            {
                var id = i;
                var label = i == 0 ? Loc.GetString("cmu-construction-all-categories") : names[i];
                var icon = examples != null && examples.TryGetValue(names[i], out var example)
                    ? sprites.GetPrototypeIcon(example).Default : _catalogIcon;
                var button = GmodStyle.NavigationButton(label, icon);
                button.Disabled = Collections.Disabled;
                button.OnPressed += _ => TrySelectCategory(id);
                CategoryButtons.AddChild(button);
            }
        }
        SelectedCategoryId = selected;
        for (var i = 0; i < CategoryButtons.ChildCount; i++)
        {
            var button = (ContainerButton) CategoryButtons.GetChild(i);
            GmodStyle.SelectButton(button, i == selected);
        }
    }

    public void TrySelectCategory(int id)
    {
        SelectedCategoryId = id;
        RefreshRecipes();
    }

    public void SetSpawnlists(IReadOnlyList<string> spawnlists)
    {
        Collections.Clear();
        var selected = 0;
        foreach (var name in spawnlists)
        {
            if (ZLevelPageSpawnlists.Contains(name))
                continue;

            var id = Collections.ItemCount;
            Collections.AddItem(name == DefaultCollection ? Loc.GetString("cmu-construction-all-collections") : name, id);
            Collections.SetItemMetadata(id, name);
            if (name == SelectedSpawnlist)
                selected = id;
        }

        Collections.Visible = Collections.ItemCount > 1;
        if (Collections.TrySelect(selected))
            SelectedSpawnlist = (string) Collections.GetItemMetadata(selected)!;
    }

    public void ClearRecipeInfo()
    {
        RecipeDetails.Visible = false;
        RecipeSteps.RemoveAllChildren();
        SkillDiscount.Text = string.Empty;
        _targetEntity = null;
        _recipeId = null;
        UpdateRecipeActions();
    }

    public void SetRecipeInfo(string name, string description, EntityPrototype? targetPrototype, Color iconColor,
        bool placeGhost, bool addFavorite, ConstructionPrototype prototype)
    {
        RecipeDetails.Visible = true;
        TargetName.SetMessage(name, GmodStyle.Accent);
        TargetDescription.SetMessage(description);
        BuildButton.Text = Loc.GetString(prototype.RMCPrototype != null ? "rmc-construction-build-here" :
            placeGhost ? "construction-menu-place-ghost" : "construction-menu-craft");
        FavoriteButton.Text = Loc.GetString(addFavorite ? "construction-add-favorite-button" : "construction-remove-from-favorite-button");
        _targetEntity = targetPrototype?.ID;
        _recipeId = prototype.ID;
        UpdateRecipeActions();
    }

    public void SetConstructionSkillInfo(int skillLevel, int discountPercent)
    {
        SkillDiscount.Text = discountPercent > 0 ? Loc.GetString("cmu-construction-discount", ("discount", discountPercent)) : string.Empty;
    }

    public void AddRecipeStep(string text, Texture icon)
    {
        var row = new BoxContainer { SeparationOverride = 4 };
        if (icon != Texture.Transparent)
            row.AddChild(new TextureRect { Texture = icon, SetSize = new Vector2(20, 20), Stretch = TextureRect.StretchMode.KeepAspectCentered });
        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(text);
        row.AddChild(label);
        RecipeSteps.AddChild(row);
    }

    public void ResetPlacement()
    {
        BuildButton.Pressed = false;
        EraseButton.Pressed = false;
    }
}
