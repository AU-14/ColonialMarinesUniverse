using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.CMU14.Lobby;

/// <summary>Faction artwork and the live roster share one surface.</summary>
[GenerateTypedNameReferences]
public sealed partial class JoinRoundWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IStylesheetManager _styles = default!;
    internal static readonly CmuChoiceCard.Palette GovforPalette = new(
        Color.FromHex("#527F72"), Color.FromHex("#131E20"), Color.FromHex("#233735"), Color.FromHex("#9CCDB8"));
    internal static readonly CmuChoiceCard.Palette OpforPalette = new(
        Color.FromHex("#97565C"), Color.FromHex("#23181D"), Color.FromHex("#3E272C"), Color.FromHex("#D59B99"));
    private readonly Dictionary<string, CmuFactionCard> _cards = new();
    // This scroll area shares a column with the roster. Report its cards' height rather than
    // ScrollContainer's default zero, otherwise the entire faction picker is clipped away.
    private readonly ScrollContainer _cardsScroll = new() { HScrollEnabled = false, HorizontalExpand = true, ReturnMeasure = true, MaxHeight = 350 };
    private readonly CmuRevealPanel _expanded = new() { Visible = false, HorizontalExpand = true, VerticalExpand = true };
    private readonly BoxContainer _expansionContent = new() { Orientation = BoxContainer.LayoutOrientation.Vertical, VerticalExpand = true, SeparationOverride = 10 };
    private readonly CmuJoinRoster _roster;
    private readonly CmuAdaptiveGrid _otherActions = new(220) { HSeparationOverride = 12, VSeparationOverride = 12, Visible = false };
    private readonly CmuAccentLabel _heading = new() { Margin = new Thickness(0, 4, 0, 8), StyleClasses = { StyleNano.StyleClassCrtHeading } };
    private readonly RichTextLabel _empty = new() { Visible = false, HorizontalExpand = true, Margin = new Thickness(4, 12) };
    private readonly ClientGameTicker _ticker;
    private readonly GhostSystem _ghosts;
    private string? _selected;
    private bool _hunterWhitelisted;

    public Button JoinColonistsButton => _cards["colonists"];
    public Button JoinGovforButton => _cards["govfor"];
    public Button JoinOpforButton => _cards["opfor"];
    public Button JoinOtherButton { get; } = CmuLobbyPresentation.Action(Loc.GetString("cmu-workspace-ghost-roles"));
    public Button JoinHuntButton { get; } = CmuLobbyPresentation.Action(Loc.GetString("rmc-lobby-join-hunt"));

    public JoinRoundWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        Title = Loc.GetString("cmu-lobby-join-round-window-title");
        Stylesheet = _styles.SheetNano;
        CrtLobbyTheme.ApplyWindow(this, useCrtTypography: true);
        _ticker = _entities.System<ClientGameTicker>();
        _ghosts = _entities.System<GhostSystem>();
        _roster = new CmuJoinRoster();
        _roster.Joined += Close;
        Choices.AddChild(new Label { Text = Loc.GetString("cmu-workspace-frontier-operations"), FontColorOverride = CmuLobbyPresentation.Muted, ClipText = true });
        var title = CmuLobbyPresentation.Heading(Loc.GetString("cmu-workspace-choose-faction"));
        title.ClipText = true;
        Choices.AddChild(title);
        var cards = new CmuAdaptiveGrid(190) { HSeparationOverride = 10, VSeparationOverride = 10, HorizontalExpand = true };
        foreach (var id in new[] { "colonists", "govfor", "opfor", "other" })
        {
            var button = new CmuFactionCard(id);
            button.OnPressed += _ => SelectFaction(id);
            _cards.Add(id, button);
            cards.AddChild(button);
        }
        _cardsScroll.AddChild(cards);
        Choices.AddChild(_cardsScroll);
        Choices.AddChild(_empty);
        _expanded.PanelOverride = CmuLobbyPresentation.Box();
        _expanded.AddChild(_expansionContent);
        var header = new BoxContainer();
        _heading.ClipText = true;
        _heading.HorizontalExpand = true;
        header.AddChild(_heading);
        var close = CmuLobbyPresentation.Action("×");
        close.ToolTip = Loc.GetString("cmu-workspace-close-roster");
        close.HorizontalExpand = false;
        close.OnPressed += _ => CloseRoster();
        header.AddChild(close);
        _expansionContent.AddChild(header);
        _expansionContent.AddChild(_otherActions);
        _otherActions.AddChild(JoinOtherButton);
        _otherActions.AddChild(JoinHuntButton);
        _expansionContent.AddChild(_roster);
        Choices.AddChild(_expanded);
        CmuLobbyPresentation.Style(JoinOtherButton, CmuLobbyPresentation.FactionColor("other"));
        CmuLobbyPresentation.Style(JoinHuntButton, CmuLobbyPresentation.FactionColor("opfor"));
        JoinOtherButton.MinHeight = JoinHuntButton.MinHeight = 70;
        CrtLobbyTheme.Apply(Choices);
        UpdateAvailability();
    }

    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        _cardsScroll.MaxHeight = Math.Max(44, Math.Min(_expanded.Visible ? 116 : 350, availableSize.Y * (_expanded.Visible ? 0.25f : 0.7f)));
        return base.MeasureOverride(availableSize);
    }

    private void CloseRoster()
    {
        _expanded.Visible = false;
        _selected = null;
        foreach (var card in _cards.Values)
            card.SetExpanded(false, false);
    }

    public void SetHuntVisible(bool visible)
    {
        _hunterWhitelisted = visible;
        UpdateAvailability();
    }

    private void SelectFaction(string faction)
    {
        if (_selected == faction && _expanded.Visible) return;
        _selected = faction;
        var accent = CmuLobbyPresentation.FactionColor(faction);
        _expanded.PanelOverride = CmuLobbyPresentation.Box(accent);
        _heading.SemanticColor = accent;
        foreach (var (id, card) in _cards)
            card.SetExpanded(true, id == faction);
        _heading.Text = Loc.GetString($"cmu-workspace-faction-{faction}");
        _otherActions.Visible = faction == "other";
        _roster.Visible = faction != "other";
        if (_roster.Visible) _roster.SelectFaction(faction);
        _expanded.Reveal();
    }

    private void UpdateAvailability()
    {
        var any = false;
        foreach (var (id, button) in _cards)
        {
            button.Visible = id == "other"
                ? _ghosts.AvailableGhostRoleCount > 0 || _hunterWhitelisted && _roster.HasFaction("hunt")
                : _roster.HasFaction(id);
            any |= button.Visible;
            button.SetAvailability(id == "other" ? _ghosts.AvailableGhostRoleCount + (_hunterWhitelisted ? _roster.AvailableRoles("hunt") : 0) : _roster.AvailableRoles(id));
        }
        JoinOtherButton.Visible = _ghosts.AvailableGhostRoleCount > 0;
        JoinHuntButton.Visible = _hunterWhitelisted && _roster.HasFaction("hunt");
        _cardsScroll.Visible = any;
        _empty.Visible = !any;
        _empty.SetMessage(Loc.GetString(_ticker.DisallowedLateJoin
            ? "cmu-workspace-late-join-disabled"
            : "cmu-workspace-no-factions"), CmuLobbyPresentation.Text);
        if (_selected != null && !_cards[_selected].Visible)
        {
            CloseRoster();
        }
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _ticker.LobbyJobsAvailableUpdated += OnJobs;
        _ticker.LobbyLateJoinStatusUpdated += UpdateAvailability;
        _ghosts.GhostRoleCountUpdated += OnGhosts;
        UpdateAvailability();
    }

    protected override void ExitedTree()
    {
        _ticker.LobbyJobsAvailableUpdated -= OnJobs;
        _ticker.LobbyLateJoinStatusUpdated -= UpdateAvailability;
        _ghosts.GhostRoleCountUpdated -= OnGhosts;
        base.ExitedTree();
    }

    private void OnJobs(IReadOnlyDictionary<NetEntity, Dictionary<ProtoId<JobPrototype>, int?>> _) => UpdateAvailability();
    private void OnGhosts(GhostUpdateGhostRoleCountEvent _) => UpdateAvailability();
}
