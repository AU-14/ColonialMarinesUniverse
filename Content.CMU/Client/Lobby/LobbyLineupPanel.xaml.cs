    public LobbyLineupPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _interactions = new LobbyLineupInteractionOverlay();
        AddChild(_interactions);
        Backing.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#081114EF") };
        ActionDeck.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#0B222ADF") };
        Salute.OnPressed += _ => Perform(LobbyLineupEmote.Salute);
        Wave.OnPressed += _ => Perform(LobbyLineupEmote.Wave);
        Gear.OnPressed += _ => Perform(LobbyLineupEmote.CheckGear);
        Stretch.OnPressed += _ => Perform(LobbyLineupEmote.Stretch);
        PreviousMove.OnPressed += _ => SelectMove(_moveIndex - 1);
        NextMove.OnPressed += _ => SelectMove(_moveIndex + 1);
        PerformMove.OnPressed += _ => Perform(LobbyLineupChoreography.SoloMoves[_moveIndex]);
        RandomMove.OnPressed += _ =>
        {
            SelectMove(_moveIndex + _random.Next(1, LobbyLineupChoreography.SoloMoves.Length));
            Perform(LobbyLineupChoreography.SoloMoves[_moveIndex]);
        };
        PreviousTeam.OnPressed += _ => SelectTeam(_teamIndex - 1);
        NextTeam.OnPressed += _ => SelectTeam(_teamIndex + 1);
        PerformTeam.OnPressed += _ => Perform(LobbyLineupChoreography.TeamMoves[_teamIndex]);
        AllTeams.OnPressed += _ => PlayShowcaseFormations();
        SelectMove(0);
        SelectTeam(0);
        Send.OnPressed += _ => SendChat();
        MessageInput.OnTextEntered += _ => SendChat();
        Bubbles.OnToggled += _ => UpdatePreferences();
        Ambient.OnToggled += _ => UpdatePreferences();
        InitializeShows();
    }

    private void SelectMove(int index)
    {
        var count = LobbyLineupChoreography.SoloMoves.Length;
        _moveIndex = (index % count + count) % count;
        MoveName.Text = Loc.GetString(LobbyLineupCard.EmoteLocale(LobbyLineupChoreography.SoloMoves[_moveIndex]));
        MoveName.ToolTip = MoveName.Text;
    }

    private void SelectTeam(int index)
    {
        var count = LobbyLineupChoreography.TeamMoves.Length;
        _teamIndex = (index % count + count) % count;
        TeamName.Text = Loc.GetString(LobbyLineupCard.EmoteLocale(LobbyLineupChoreography.TeamMoves[_teamIndex]));
        TeamName.ToolTip = TeamName.Text;
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _ticker = _entities.System<ClientGameTicker>();
        _social = _entities.System<LobbyLineupSystem>();
        _chatUi = UserInterfaceManager.GetUIController<ChatUIController>();
        _ticker.InfoBlobUpdated += Refresh;
        _ticker.LobbyStatusUpdated += Refresh;
        _social.EmoteReceived += OnEmote;
        _social.ShowReceived += OnShow;
        _chatUi.MessageAdded += OnChat;
        _chatUi.MessagesDeleted += OnMessagesDeleted;
        _configuration.OnValueChanged(CCVars.LobbyPartyTime, OnPartyTimeChanged);
        _configuration.OnValueChanged(CCVars.LobbyPartyTimeFlyby, OnShowSettingsChanged);
        _configuration.OnValueChanged(CCVars.LobbyPartyTimeParade, OnShowSettingsChanged);
        Refresh();
    }

    protected override void ExitedTree()
    {
        _configuration.UnsubValueChanged(CCVars.LobbyPartyTime, OnPartyTimeChanged);
        _configuration.UnsubValueChanged(CCVars.LobbyPartyTimeFlyby, OnShowSettingsChanged);
        _configuration.UnsubValueChanged(CCVars.LobbyPartyTimeParade, OnShowSettingsChanged);
        if (_ticker != null)
        {
            _ticker.InfoBlobUpdated -= Refresh;
            _ticker.LobbyStatusUpdated -= Refresh;
            _ticker = null;
        }
        if (_social != null)
        {
            _social.EmoteReceived -= OnEmote;
            _social.ShowReceived -= OnShow;
        }
        if (_chatUi != null)
        {
            _chatUi.MessageAdded -= OnChat;
            _chatUi.MessagesDeleted -= OnMessagesDeleted;
        }
        _social = null;
        _chatUi = null;
        Clear();
        base.ExitedTree();
    }

    private void Refresh()
    {
        if (_ticker == null)
            return;
        if (_ticker.IsGameStarted)
        {
            Visible = false;
            Clear();
            return;
        }

        if (!LobbyPartySettings.IsEnabled(_configuration))
        {
            if (_departing)
                return;
            _arrivalPending = false;
            if (Visible && _cards.Count > 0)
            {
                _departing = true;
                BeginStageMotion(true);
            }
            else
            {
                Visible = false;
                Clear();
            }
            return;
        }

        if (!Visible || _departing)
        {
            ReleaseStageMotion();
            _departing = false;
            _arrivalPending = true;
        }
        Visible = true;
        SetLineup(_showcase ?? _ticker.LobbyLineup);
    }

    private void BeginStageMotion(bool leaving)
    {
        _interactions.Clear();
        if (leaving)
            ReleaseShow();
        ReleaseStageMotion();
        _stageMotion = new LobbyLineupStageTransition(_cards.Values, leaving, _configuration.GetCVar(CCVars.ReducedMotion));
        var motion = _stageMotion;
        // Arrival can start while the UI tree is being enumerated, so attach after the frame update.
        UserInterfaceManager.DeferAction(() =>
        {
            if (_stageMotion != motion)
                return;
            // StateRoot is underneath ScreenRoot: the opaque lobby background would cover every
            // moving sprite there. WindowRoot draws above the active screen (and preview windows).
            var root = UserInterfaceManager.WindowRoot;
            LayoutContainer.SetAnchorPreset(motion, LayoutContainer.LayoutPreset.Wide);
            root.AddChild(motion);
            motion.Measure(root.Size);
            motion.Arrange(new UIBox2(System.Numerics.Vector2.Zero, root.Size));
            motion.Visible = VisibleInTree;
            motion.Advance(0);
        });
        UpdateActions();
    }

    protected override void VisibilityChanged(bool newVisible)
    {
        base.VisibilityChanged(newVisible);
        if (_stageMotion != null)
            _stageMotion.Visible = newVisible;
        if (_partyShow != null)
            _partyShow.Visible = newVisible;
    }

    private void ReleaseStageMotion()
    {
        _stageMotion?.Release();
        _stageMotion = null;
        Backing.Modulate = Color.White;
    }

    private void OnPartyTimeChanged(bool enabled)
    {
        _cooldown = _rallyCooldown = 0;
        Refresh();
    }

    public void SetShowcase(IReadOnlyList<LobbyLineupEntry>? entries, bool showcaseControls = false, LobbyPartyShow? initialShow = null)
    {
        _interactions.Clear();
        ReleaseShow();
        _showCooldown = 0;
        _nextShowcaseShow = 20;
        ReleaseStageMotion();
        _departing = false;
        _arrivalPending = true;
        _showcase = entries;
        _showcaseControls = entries != null && showcaseControls;
        _selected = entries?.FirstOrDefault()?.UserId;
        _cooldown = _rallyCooldown = 0;
        _nextBanter = 2;
        _nextFormation = 2;
        _formationIndex = 0;
        Title.Text = Loc.GetString(entries == null ? "cmu-lobby-lineup-title" : "cmu-lobby-lineup-showcase");
        DemoBanter.Visible = _showcaseControls;
        AllTeams.Visible = _showcaseControls;
        MessageInput.PlaceHolder = Loc.GetString(_showcaseControls
            ? "cmu-lobby-lineup-demo-placeholder" : "cmu-lobby-lineup-chat-placeholder");
        Refresh();
        if (entries != null && initialShow is { } show)
            OnShow(new LobbyPartyShowEvent(show, _random.Next(), entries.Select(entry => entry.UserId).ToList(), false));
    }

    public void SetLineup(IReadOnlyList<LobbyLineupEntry> entries)
    {
        _entries = entries;
        var remaining = entries.Select(entry => entry.UserId).ToHashSet();
        foreach (var (id, card) in _cards.ToArray())
        {
            if (remaining.Contains(id))
                continue;
            card.Orphan();
            card.Dispose();
            _cards.Remove(id);
        }
        if (_showcase == null)
            _selected = _players.LocalUser;
        else if (_selected == null || !remaining.Contains(_selected.Value))
            _selected = entries.FirstOrDefault()?.UserId;

        var sectionIndex = 0;
        foreach (var group in entries.GroupBy(entry => entry.SectionId))
        {
            var first = group.First();
            if (!_sections.TryGetValue(group.Key, out var section))
            {
                section = new LobbyLineupSection();
                _sections.Add(group.Key, section);
                Sections.AddChild(section);
            }
            section.SetPositionInParent(sectionIndex);
            section.SetSection(first.SectionName, first.Color, group.Count(), sectionIndex++);
            var cardIndex = 0;
            foreach (var entry in group)
            {
                if (_cards.TryGetValue(entry.UserId, out var card) && card.Parent != section.Cards)
                {
                    card.Orphan();
                    card.Dispose();
                    _cards.Remove(entry.UserId);
                    card = null;
                }
                if (card == null)
                {
                    card = new LobbyLineupCard();
                    card.Selected += SelectCharacter;
                    card.AmbientEmote += OnAmbientEmote;
                    _cards.Add(entry.UserId, card);
                    section.Cards.AddChild(card);
                }
                card.SetEntry(entry, cardIndex);
                card.SetPositionInParent(cardIndex++);
            }
        }
        var activeSections = entries.Select(entry => entry.SectionId).ToHashSet();
        foreach (var (id, section) in _sections.ToArray())
        {
            if (activeSections.Contains(id))
                continue;
            section.Orphan();
            section.Dispose();
            _sections.Remove(id);
        }
        ReadyCount.Text = Loc.GetString("cmu-lobby-lineup-count", ("count", entries.Count));
        EmptyLabel.Visible = entries.Count == 0;
        UpdatePreferences();
        UpdateActions();
    }

    private void SelectCharacter(NetUserId user)
    {
        // The normal preview uses the same one-character controls as the live lobby.
        if (!_showcaseControls)
            return;
        _selected = user;
        UpdatePreferences();
        UpdateActions();
    }

    private void UpdatePreferences()
    {
        foreach (var (id, card) in _cards)
        {
            card.IsSelected = id == _selected;
            card.IsLocalPlayer = id == _selected && !_showcaseControls;
            card.AmbientEnabled = Ambient.Pressed;
            card.BubblesEnabled = Bubbles.Pressed;
            if (!Bubbles.Pressed)
                card.ClearBubble();
        }
    }

    private void Perform(LobbyLineupEmote emote)
    {
        if (_stageMotion != null || _arrivalPending || _departing || _partyShow != null)
            return;
        var entry = _entries.FirstOrDefault(entry => entry.UserId == _selected);
        if (entry == null || _cooldown > 0 || LobbyLineupEmoteEvent.IsTeamEmote(emote) && _rallyCooldown > 0)
            return;
        if (_showcase == null)
            _social?.RequestEmote(emote);
        else
        {
            var participants = LobbyLineupEmoteEvent.IsTeamEmote(emote)
                ? _entries.Where(other => other.SectionId == entry.SectionId).Select(other => other.UserId).ToList()
                : new List<NetUserId> { entry.UserId };
            PlayEmote(CreateLocalEmote(entry.UserId, emote, participants));
        }
        _cooldown = Math.Max(LobbyLineupEmoteEvent.ActionCooldown,
            LobbyLineupChoreography.Duration(LobbyLineupChoreography.TeamMember(emote, 0).Move));
        _nextBanter = 8;
        _nextFormation = 8;
        if (LobbyLineupEmoteEvent.IsTeamEmote(emote))
            _rallyCooldown = LobbyLineupEmoteEvent.SquadCooldown;
        UpdateActions();
    }

    private void OnEmote(LobbyLineupEmoteEvent ev)
    {
        if (_showcase == null && _stageMotion == null && !_departing && _partyShow == null)
            PlayEmote(ev);
    }

    private void PlayEmote(LobbyLineupEmoteEvent ev)
    {
        var index = 0;
        var duration = 0f;
        foreach (var user in ev.Participants)
        {
            if (_cards.TryGetValue(user, out var card))
            {
                var participantIndex = index++;
                var (move, delay) = LobbyLineupChoreography.TeamMember(ev.Emote, participantIndex);
                duration = Math.Max(duration, LobbyLineupChoreography.Duration(move) + delay);
                card.PlayEmote(move, delay);
                if (participantIndex < ev.Targets.Count && _cards.TryGetValue(ev.Targets[participantIndex], out var target))
                    _interactions.Add(card, target, move, ev.Seed + participantIndex, delay);
                else if (ev.Targets.Count == 0 && move is LobbyLineupEmote.PieToss or LobbyLineupEmote.BananaPeel or LobbyLineupEmote.ConfettiCannon)
                    _interactions.Add(card, card, move, ev.Seed, delay);
            }
            else
                index++;
        }
        if (LobbyLineupEmoteEvent.IsTeamEmote(ev.Emote))
        {
            var sender = _entries.FirstOrDefault(entry => entry.UserId == ev.Sender);
            if (sender != null && _sections.TryGetValue(sender.SectionId, out var section))
                section.PlayTeamEffect(ev.Emote is LobbyLineupEmote.SquadDisco or LobbyLineupEmote.SquadDanceOff or LobbyLineupEmote.SquadConga, duration);
        }
        if (LobbyLineupEmoteEvent.IsTeamEmote(ev.Emote) && _selected is { } selected && ev.Participants.Contains(selected))
            _rallyCooldown = LobbyLineupEmoteEvent.SquadCooldown;
        UpdateActions();
    }

    private void SendChat()
    {
        if (_stageMotion != null || _arrivalPending || _departing)
            return;
        var text = MessageInput.Text.Trim();
        if (text.Length == 0 || _selected is not { } selected || !_cards.TryGetValue(selected, out var card))
            return;
        if (_showcase == null)
            _chat.SendMessage(text, ChatSelectChannel.OOC);
        else
            card.ShowBubble(text);
        _nextBanter = 8;
        MessageInput.Clear();
    }

    private void OnChat(ChatMessage message)
    {
        if (_showcase != null || message.Channel != ChatChannel.OOC || message.HideChat || message.SenderKey == null)
            return;
        var entry = _entries.FirstOrDefault(entry => entry.ChatKey == message.SenderKey);
        if (entry != null && _cards.TryGetValue(entry.UserId, out var card))
            card.ShowBubble(message.Message);
    }

    private void OnMessagesDeleted(MsgDeleteChatMessagesBy message)
    {
        foreach (var entry in _entries)
        {
            if (entry.ChatKey == message.Key && _cards.TryGetValue(entry.UserId, out var card))
                card.ClearBubble();
        }
    }

    private void UpdateActions()
    {
        var entry = _entries.FirstOrDefault(entry => entry.UserId == _selected);
        var moving = _stageMotion != null || (_arrivalPending && _cards.Count > 0) || _departing || _partyShow != null;
        UpdateShowActions();
        foreach (var button in new[] { Salute, Wave, Gear, Stretch, PerformTeam, AllTeams })
            button.Disabled = moving || entry == null || _cooldown > 0;
        PerformTeam.Disabled |= _rallyCooldown > 0;
        PerformMove.Disabled = RandomMove.Disabled = moving || entry == null || _cooldown > 0;
        Send.Disabled = moving || entry == null;
        MessageInput.Editable = !moving && entry != null;
        PlayerIdentity.Text = entry == null ? Loc.GetString("cmu-lobby-lineup-action-unready")
            : _showcaseControls ? Loc.GetString("cmu-lobby-lineup-demo-acting", ("name", entry.Name))
            : Loc.GetString("cmu-lobby-lineup-acting", ("name", entry.Name), ("section", entry.SectionName));
        PlayerIdentity.ToolTip = PlayerIdentity.Text;
        PlayerIdentity.FontColorOverride = entry?.Color ?? Color.FromHex("#C3D3CE");
        ActionStatus.Text = _partyShow != null ? Loc.GetString("cmu-lobby-party-playing")
            : moving ? Loc.GetString(_departing ? "cmu-lobby-lineup-departing" : "cmu-lobby-lineup-arriving")
            : entry == null ? string.Empty
            : _cooldown > 0 ? Loc.GetString("cmu-lobby-lineup-cooldown", ("seconds", (int) Math.Ceiling(_cooldown)))
            : Loc.GetString("cmu-lobby-lineup-standing-by");
        PerformMove.Text = Loc.GetString(_cooldown > 0 ? "cmu-lobby-lineup-wait" : "cmu-lobby-lineup-perform-move",
            ("seconds", (int) Math.Ceiling(_cooldown)));
        PerformTeam.Text = Loc.GetString(_cooldown > 0 || _rallyCooldown > 0 ? "cmu-lobby-lineup-wait" : "cmu-lobby-lineup-perform-team",
            ("seconds", (int) Math.Ceiling(Math.Max(_cooldown, _rallyCooldown))));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!VisibleInTree)
            return;
        AdvanceShowCooldown(args.DeltaSeconds);
        if (_arrivalPending && _cards.Count > 0 && _cards.Values.All(card => card.StageBounds.Height > 0))
        {
            _arrivalPending = false;
            BeginStageMotion(false);
        }
        if (_stageMotion != null)
        {
            _stageMotion.Advance(args.DeltaSeconds);
            Backing.Modulate = Color.White.WithAlpha(_departing ? 1 - _stageMotion.Progress * 0.8f : 1);
            if (!_stageMotion.Finished)
                return;
            ReleaseStageMotion();
            if (_departing)
            {
                Visible = false;
                Clear();
                return;
            }
            _nextBanter = _nextFormation = 2;
            UpdateActions();
        }
        AdvanceShow(args.DeltaSeconds);
        _cooldown = Math.Max(0, _cooldown - args.DeltaSeconds);
        _rallyCooldown = Math.Max(0, _rallyCooldown - args.DeltaSeconds);
        var seconds = (int) Math.Ceiling(_cooldown);
        var squadSeconds = (int) Math.Ceiling(_rallyCooldown);
        if (_lastCooldownSecond != seconds || _lastSquadCooldownSecond != squadSeconds)
        {
            _lastCooldownSecond = seconds;
            _lastSquadCooldownSecond = squadSeconds;
            UpdateActions();
        }
        if (_partyShow != null)
            return;
        _interactions.Advance(args.DeltaSeconds);
        if (_showcase != null && Ambient.Pressed && (_nextFormation -= args.DeltaSeconds) <= 0)
            PlayShowcaseFormations();
        if (_showcase == null || !DemoBanter.Pressed || _showcase.Count == 0 || (_nextBanter -= args.DeltaSeconds) > 0)
            return;
        _nextBanter = 4.5f;
        // Each bay gets sample activity. Never invent messages on behalf of real players.
        var sectionIndex = 0;
        foreach (var group in _showcase.GroupBy(entry => entry.SectionId))
        {
            var entry = group.ElementAt(_banterIndex % group.Count());
            if (!_showcaseControls && entry.UserId == _selected)
                continue;
            if (!_cards.TryGetValue(entry.UserId, out var card))
                continue;
            var variation = _banterIndex + sectionIndex++;
            card.ShowBubble(Loc.GetString("cmu-lobby-lineup-banter-" + variation % 12));
            if (Ambient.Pressed && !card.IsPerforming)
            {
                var move = LobbyLineupChoreography.SoloMoves[_random.Next(LobbyLineupChoreography.SoloMoves.Length)];
                card.PlayEmote(move);
                OnAmbientEmote(card, move);
            }
        }
        _banterIndex++;
    }

    private void PlayShowcaseFormations()
    {
        if (_showcase == null)
            return;
        var index = _formationIndex++;
        foreach (var group in _showcase.GroupBy(entry => entry.SectionId))
        {
            // Keep the preview player's squad available for their own commands.
            if (!_showcaseControls && group.Any(entry => entry.UserId == _selected))
                continue;
            var routine = LobbyLineupChoreography.TeamMoves[index++ % LobbyLineupChoreography.TeamMoves.Length];
            PlayEmote(CreateLocalEmote(group.First().UserId, routine, group.Select(entry => entry.UserId).ToList()));
        }
        _nextFormation = 12;
        UpdateActions();
    }

    private void Clear()
    {
        _interactions.Clear();
        ReleaseShow();
        _showCooldown = 0;
        ReleaseStageMotion();
        _arrivalPending = _departing = false;
        foreach (var section in _sections.Values)
        {
            section.Orphan();
            section.Dispose();
        }
        _cards.Clear();
        _sections.Clear();
        _entries = Array.Empty<LobbyLineupEntry>();
    }

    private LobbyLineupEmoteEvent CreateLocalEmote(NetUserId sender, LobbyLineupEmote move, List<NetUserId> participants)
    {
        var seed = _random.Next();
        return new LobbyLineupEmoteEvent(sender, move, participants,
            LobbyLineupInteractions.SelectTargets(move, participants, _entries.Select(entry => entry.UserId).ToArray(), seed), seed);
    }

    private void OnAmbientEmote(LobbyLineupCard source, LobbyLineupEmote move)
    {
        if (!LobbyLineupInteractions.CanTarget(move) || _partyShow != null || _stageMotion != null || _arrivalPending || _departing)
            return;
        var sender = _cards.FirstOrDefault(pair => pair.Value == source).Key;
        var ev = CreateLocalEmote(sender, move, new List<NetUserId> { sender });
        if (ev.Targets.Count > 0 && _cards.TryGetValue(ev.Targets[0], out var target))
            _interactions.Add(source, target, move, ev.Seed);
        else if (!LobbyLineupInteractionChoreography.IsGun(move))
            _interactions.Add(source, source, move, ev.Seed);
    }
