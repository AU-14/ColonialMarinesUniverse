    private float _cooldown;
    private float _rallyCooldown;
    private float _nextBanter = 2;
    private int _banterIndex;
    private int _lastCooldownSecond = -1;
    private int _lastSquadCooldownSecond = -1;
    private int _moveIndex;
    private int _teamIndex;
    private int _formationIndex;
    private float _nextFormation = 2;
