    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);
        var size = PixelSize;
        var accent = _entry?.Color ?? Color.White;
        var center = size.X / 2;
        var floor = _groundY * UIScale;
        var unit = Math.Min(size.X / 164f, size.Y / 200f);
        var light = IsSelected ? 0.18f : _hovered ? 0.12f : 0.05f;
        var beam = _quadVertices;
        beam[0] = new(center - 14 * unit, _bubbleHeight * UIScale);
        beam[1] = new(center + 14 * unit, _bubbleHeight * UIScale);
        beam[2] = new(size.X - 8 * unit, floor);
        beam[3] = new(8 * unit, floor);
        handle.DrawPrimitives(DrawPrimitiveTopology.TriangleFan, beam, accent.WithAlpha(light));
        DrawEllipse(handle, new(center, floor), new(54 * unit, 9 * unit), Color.FromHex("#050A0EBB"));
        DrawEllipse(handle, new(center, floor), new(47 * unit, 5 * unit), accent.WithAlpha(IsSelected ? 0.3f : 0.12f));
        handle.DrawLine(new(center - 35 * unit, floor + 3 * unit), new(center + 35 * unit, floor + 3 * unit), accent.WithAlpha(0.65f));

        var plate = _plateY * UIScale;
        var nameplate = _quadVertices;
        nameplate[0] = new(0, plate);
        nameplate[1] = new(size.X, plate - 4 * unit);
        nameplate[2] = new(size.X, size.Y);
        nameplate[3] = new(0, size.Y);
        handle.DrawPrimitives(DrawPrimitiveTopology.TriangleFan, nameplate, Color.FromHex("#080F13EF"));
        handle.DrawLine(new(0, plate), new(size.X, plate - 4 * unit), accent.WithAlpha(IsSelected ? 1 : 0.5f));
        if (IsSelected || _hovered)
            handle.DrawRect(new UIBox2(0, plate, 3 * UIScale, size.Y), accent);

        if (BubblePanel.Visible)
        {
            var tail = _tailVertices;
            tail[0] = new(center - 5 * unit, _bubbleHeight * 0.88f * UIScale);
            tail[1] = new(center + 7 * unit, _bubbleHeight * 0.88f * UIScale);
            tail[2] = new(center, _bubbleHeight * UIScale);
            handle.DrawPrimitives(DrawPrimitiveTopology.TriangleFan, tail, Color.FromHex("#D4E2DFF5").WithAlpha(BubblePanel.Modulate.A));
        }
        if (_gesture != null && _gestureDelay <= 0)
        {
            // Arcade signal beside the actual sprite; appearance and equipment stay intact.
            var origin = new Vector2(size.X - 14 * unit, _bubbleHeight * UIScale + 14 * unit);
            handle.DrawCircle(origin, 10 * unit, Color.FromHex("#071116E8"));
            handle.DrawCircle(origin, 10 * unit, accent, false);
            DrawGesture(handle, origin, accent, _gesture.Value, unit);
            DrawActionEffects(handle, new Vector2(center, floor), accent, unit);
        }
    }

    private void DrawGesture(DrawingHandleScreen handle, Vector2 origin, Color accent, LobbyLineupEmote emote, float unit)
    {
        void Line(float x1, float y1, float x2, float y2) =>
            handle.DrawLine(origin + new Vector2(x1, y1) * unit, origin + new Vector2(x2, y2) * unit, accent);

        switch (emote)
        {
            case LobbyLineupEmote.CheckGear:
                Line(-5, 0, -1, 4);
                Line(-1, 4, 6, -4);
                break;
            case LobbyLineupEmote.Wave:
                Line(-4, 5, -4, -3);
                Line(-1, 5, -1, -6);
                Line(2, 5, 2, -5);
                Line(5, 5, 5, -2);
                Line(-4, 5, 5, 5);
                break;
            case LobbyLineupEmote.Stretch:
                Line(-7, 0, 7, 0);
                Line(-7, 0, -3, -4);
                Line(-7, 0, -3, 4);
                Line(7, 0, 3, -4);
                Line(7, 0, 3, 4);
                break;
            default:
                Line(-6, 2, 0, -4);
                Line(0, -4, 6, 2);
                if (LobbyLineupEmoteEvent.IsTeamEmote(emote))
                {
                    Line(-6, 6, 0, 0);
                    Line(0, 0, 6, 6);
                }
                break;
        }
    }

    private void DrawActionEffects(DrawingHandleScreen handle, Vector2 floor, Color accent, float unit)
    {
        var reduced = _configuration.GetCVar(CCVars.ReducedMotion);
        var phase = reduced ? 0.4f : _gestureDuration - _gestureRemaining;
        var wild = LobbyLineupChoreography.IsDance(_gesture) || _gesture is LobbyLineupEmote.VictorySpin or LobbyLineupEmote.Backflip;
        if (!wild && _gesture != LobbyLineupEmote.SquadRally)
            return;
        var pulse = (phase * 1.6f) % 1;
        DrawEllipse(handle, floor, new Vector2(40 + pulse * 25, 5 + pulse * 7) * unit, accent.WithAlpha((1 - pulse) * 0.24f));
        for (var i = 0; i < 12; i++)
        {
            var life = (phase * 0.7f + i * 0.173f) % 1;
            var angle = i * 2.4f;
            var origin = floor + new Vector2(MathF.Sin(angle) * (12 + life * 48), -15 - life * 100) * unit;
            var color = !wild ? accent : i % 3 == 0 ? Color.Cyan : i % 3 == 1 ? Color.Magenta : Color.FromHex("#FFE6A3");
            handle.DrawLine(origin, origin + new Vector2(MathF.Sin(angle) * 4, -5) * unit, color.WithAlpha(1 - life));
        }
    }

    private void DrawEllipse(DrawingHandleScreen handle, Vector2 center, Vector2 radius, Color color)
    {
        var points = _ellipseVertices;
        points[0] = center;
        for (var i = 1; i < points.Length; i++)
        {
            var angle = (i - 1) * MathF.Tau / (points.Length - 2);
            points[i] = center + new Vector2(MathF.Cos(angle), MathF.Sin(angle)) * radius;
        }
        handle.DrawPrimitives(DrawPrimitiveTopology.TriangleFan, points, color);
    }
