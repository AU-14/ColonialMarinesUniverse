    public void SetStageMoving(bool moving)
    {
        StageMoving = moving;
        Preview.Visible = !moving;
        if (moving)
        {
            _gesture = null;
            ClearInteractions();
            EmoteRevision++;
            ClearBubble();
        }
        else
            _entrance = 1;
    }

    public LobbyLineupCard()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _effects = new PartyEffectsOverlay(this) { MouseFilter = MouseFilterMode.Ignore };
        AddChild(_effects);
        _effects.SetPositionInParent(1);
        BubblePanel.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#D4E2DFF5") };
        BubbleText.FontColorOverride = Color.FromHex("#111C20");
    }

    public void SetEntry(LobbyLineupEntry entry, int position)
    {
        ReadyLabel.FontColorOverride = entry.Color;
        CharacterName.FontColorOverride = Color.White;
        JobName.FontColorOverride = Color.FromHex("#BCC9C3");
        CharacterName.Text = entry.Name;
        JobPrototype? job = null;
        if (entry.Job is { } id)
            _prototypes.TryIndex(id, out job);
        JobName.Text = job == null ? Loc.GetString("cmu-lobby-lineup-no-role") : LobbyHighJobPreview.GetDisplayJobName(job);
        _characterTooltip = entry.Name + "\n" + JobName.Text;
        UpdateTooltip();

        if (_entry == null || !_entry.SamePreview(entry))
        {
            Preview.ClearPreview();
            var entity = UserInterfaceManager.GetUIController<LobbyUIController>()
                .LoadProfileEntity(entry.ToPreviewProfile(), job, job != null);
            Preview.PreviewDummy = entity;
            Preview.SetEntity(entity);
            _entrance = -Math.Min(position, 8) * 0.12f;
        }
        if (_entry == null)
        {
            var seed = (uint) entry.UserId.GetHashCode();
            _idleIndex = (int) (seed % 997);
            _nextIdle = 5 + seed % 140 / 10f;
        }
        _entry = entry;
    }

    public void ShowBubble(string text)
    {
        if (!BubblesEnabled)
            return;
        // Plain Label text cannot interpret player-supplied markup.
        _bubbleMessage = text;
        UpdateBubbleText();
        BubblePanel.ToolTip = text;
        _bubbleRemaining = 7;
        BubblePanel.Visible = true;
        UpdateTooltip();
    }

    private void UpdateBubbleText(float? width = null)
    {
        // Dense formations use one legible line; the complete message remains on the character tooltip.
        if (_bubbleMessage == null)
            return;
        var text = WrapBubble(_bubbleMessage,
            Math.Clamp((int) (((width ?? Size.X) - 6) / Math.Max(4, _fontSize * 0.65f)), 6, 26),
            _bubbleHeight * 0.9f - 2 >= _fontSize * 2.7f);
        if (BubbleText.Text != text)
            BubbleText.Text = text;
    }

    private static string WrapBubble(string text, int lineLength, bool twoLines)
    {
        var compact = string.Join(" ", text.Split((char[]?) null, StringSplitOptions.RemoveEmptyEntries));
        if (compact.Length <= lineLength)
            return compact;
        if (!twoLines)
            return compact[..(lineLength - 1)] + "…";
        var split = compact.LastIndexOf(' ', Math.Min(lineLength, compact.Length - 1));
        if (split < lineLength / 2)
            split = lineLength;
        var second = compact[split..].TrimStart();
        if (second.Length > lineLength)
            second = second[..(lineLength - 1)] + "…";
        return compact[..split] + "\n" + second;
    }

    private void UpdateTooltip()
    {
        ToolTip = _bubbleMessage == null ? _characterTooltip : _characterTooltip + "\n" +
            Loc.GetString("cmu-lobby-lineup-chat-tooltip", ("message", _bubbleMessage));
    }

    public void ClearBubble()
    {
        _bubbleRemaining = 0;
        BubblePanel.Visible = false;
        _bubbleMessage = null;
        UpdateTooltip();
    }

    public void PlayEmote(LobbyLineupEmote emote, float delay = 0)
    {
        _interactionTarget = null;
        EmoteRevision++;
        _gesture = emote;
        _gestureDuration = LobbyLineupChoreography.Duration(emote);
        _gestureRemaining = _gestureDuration;
        _gestureDelay = delay;
        _nextIdle = 14 + _idleIndex % 8;
    }

    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        base.MeasureOverride(availableSize);
        return Vector2.Zero;
    }

    protected override Vector2 ArrangeOverride(Vector2 finalSize)
    {
        _bubbleHeight = Math.Min(38, finalSize.Y * 0.23f);
        var nameHeight = Math.Min(17, finalSize.Y * 0.12f);
        var statusHeight = Math.Min(14, finalSize.Y * 0.10f);
        _groundY = finalSize.Y - nameHeight * 2 - statusHeight;
        _plateY = _groundY + statusHeight;
        var fontSize = Math.Clamp((int) (nameHeight * 0.75f), 7, 12);
        if (fontSize != _fontSize)
        {
            _fontSize = fontSize;
            var font = _resources.GetFont("/Fonts/NotoSans/NotoSans-Regular.ttf", fontSize);
            CharacterName.FontOverride = JobName.FontOverride = ReadyLabel.FontOverride = BubbleText.FontOverride = font;
        }
        var inset = Math.Min(finalSize.X, Math.Max(0, _groundY - _bubbleHeight)) * 0.06f;
        _previewBounds = new UIBox2(inset, _bubbleHeight + inset, finalSize.X - inset, _groundY - inset);
        if (Preview.Entity is { } preview)
        {
            // Fit using unrotated bounds so rolls and push-ups do not resize the sprite mid-animation.
            var pixels = _entities.System<SpriteSystem>().GetLocalBounds((preview.Owner, preview.Comp1)).Size * EyeManager.PixelsPerMeter;
            var scale = Math.Max(0.01f, Math.Min(_previewBounds.Width / Math.Max(1, pixels.X),
                _previewBounds.Height / Math.Max(1, pixels.Y)));
            var fitted = new Vector2(scale);
            if (Preview.Scale != fitted)
                Preview.Scale = fitted;
        }
        Preview.Arrange(_previewBounds);
        _effects.Arrange(new UIBox2(Vector2.Zero, finalSize));
        ReadyLabel.Arrange(new UIBox2(0, _groundY, finalSize.X, _plateY));
        CharacterName.Arrange(new UIBox2(0, _plateY, finalSize.X, _plateY + nameHeight));
        JobName.Arrange(new UIBox2(0, _plateY + nameHeight, finalSize.X, finalSize.Y));
        BubblePanel.Arrange(new UIBox2(0, 0, finalSize.X, _bubbleHeight * 0.9f));
        UpdateBubbleText(finalSize.X);
        return finalSize;
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);
        if (args.Function != EngineKeyFunctions.UIClick || _entry == null)
            return;
        Selected?.Invoke(_entry.UserId);
        args.Handle();
    }

    protected override void MouseEntered()
