        _hovered = false;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (StageMoving)
            return;
        var reduced = _configuration.GetCVar(CCVars.ReducedMotion);
        var delta = args.DeltaSeconds;
        _entrance = reduced ? 1f : Math.Min(1f, _entrance + delta / 0.65f);
        Preview.Modulate = Color.White.WithAlpha(Math.Clamp(_entrance, 0, 1));
        _bubbleRemaining = Math.Max(0, _bubbleRemaining - delta);
        if (_bubbleRemaining == 0 && _bubbleMessage != null)
            ClearBubble();
        BubblePanel.Visible = BubblesEnabled && _bubbleRemaining > 0;
        BubblePanel.Modulate = Color.White.WithAlpha(reduced ? 1 : Math.Min(1, _bubbleRemaining * 2));
        var animationDelta = Math.Max(0, delta - Math.Max(0, _gestureDelay));
        _gestureDelay = Math.Max(0, _gestureDelay - delta);
        _gestureRemaining = Math.Max(0, _gestureRemaining - animationDelta);
        if (_gestureRemaining <= 0)
        {
            _gesture = null;
            _interactionTarget = null;
        }

        if (AmbientEnabled && !reduced && _gesture == null && (_nextIdle -= delta) <= 0)
        {
            PlayEmote(_idleIndex++ % 3 == 0 ? LobbyLineupEmote.CheckGear :
                LobbyLineupChoreography.SoloMoves[_idleIndex % LobbyLineupChoreography.SoloMoves.Length]);
            AmbientEmote?.Invoke(this, _gesture!.Value);
        }

        var active = _gestureDelay <= 0 ? _gesture : null;
        var statusLocale = active == null
            ? IsLocalPlayer ? "cmu-lobby-lineup-you" : IsSelected ? "cmu-lobby-lineup-selected" : "cmu-lobby-lineup-ready"
            : EmoteLocale(active.Value);
        if (_statusLocale != statusLocale)
        {
            _statusLocale = statusLocale;
            ReadyLabel.Text = Loc.GetString(statusLocale);
        }
        var phase = _gestureDuration - _gestureRemaining;
        var pose = LobbyLineupChoreography.Sample(active, phase, reduced);
        ApplyInteractions(ref pose, delta, reduced);
        Preview.OverrideDirection = pose.Facing;
        var rotation = new Angle(pose.Rotation);
        // Camera rotation is cancelled by upright humanoid layers. Rotate only this local preview's sprite.
        if (Preview.Sprite is { } sprite && sprite.Rotation != rotation)
            _entities.System<SpriteSystem>().SetRotation((sprite.Owner, sprite), rotation);
        if (active is LobbyLineupEmote.Chestburst or LobbyLineupEmote.XenoMorph)
            Preview.Modulate = Preview.Modulate.WithAlpha(1 - LobbyLineupChoreography.XenoBlend(phase));
        if (_previewBounds.Height > 0)
        {
            var offset = pose.Offset * _previewBounds.Size;
            Preview.Arrange(new UIBox2(_previewBounds.TopLeft + offset, _previewBounds.BottomRight + offset));
        }
    }
