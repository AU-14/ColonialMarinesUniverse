using System;
using Content.Shared.CMU14.Nuke;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;

namespace Content.Client.CMU14.Nuke;

[GenerateTypedNameReferences]
public sealed partial class CMUNukeMenu : DefaultWindow
{
    public CMUNukeMenu()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(CMUNukeUiState state)
    {
        var firstMsg = state.Status switch
        {
            CMUNukeStatus.Decrypting => Loc.GetString("cmu-nuke-ui-decryption-progress",
                ("time", FormatTime(state.DecodeTime))),
            CMUNukeStatus.Decrypted => Loc.GetString("cmu-nuke-ui-decryption-complete"),
            CMUNukeStatus.DetonationCountdown => Loc.GetString("cmu-nuke-ui-detonation-countdown",
                ("time", FormatTime(state.CooldownTime))),
            _ => Loc.GetString("cmu-nuke-ui-device-status"),
        };
        var secondMsg = state.Status switch
        {
            CMUNukeStatus.AwaitDecode when state.SafetyEnabled => Loc.GetString("cmu-nuke-ui-safety-enabled"),
            CMUNukeStatus.AwaitDecode when !state.IsAnchored => Loc.GetString("cmu-nuke-ui-anchor-to-continue"),
            CMUNukeStatus.AwaitDecode when state.CanStartDecryption => Loc.GetString("cmu-nuke-ui-comms-online"),
            CMUNukeStatus.AwaitDecode => Loc.GetString("cmu-nuke-ui-awaiting-comms"),
            CMUNukeStatus.Decrypting => Loc.GetString("cmu-nuke-ui-decryption-active"),
            CMUNukeStatus.Decrypted => Loc.GetString("cmu-nuke-ui-ready-to-activate"),
            CMUNukeStatus.DetonationCountdown => Loc.GetString("cmu-nuke-ui-device-armed"),
            CMUNukeStatus.Cooldown => Loc.GetString("cmu-nuke-ui-decryption-aborted"),
            _ => Loc.GetString("cmu-nuke-ui-status-unavailable"),
        };

        FirstStatusLabel.Text = $"[color=#17170F][bold]{firstMsg}[/bold][/color]";
        SecondStatusLabel.Text = $"[color=#F1E8D4][bold]{secondMsg}[/bold][/color]";
        AnchorButton.Text = state.IsAnchored
            ? Loc.GetString("cmu-nuke-ui-deactivate-anchor")
            : Loc.GetString("cmu-nuke-ui-activate-anchor");
        ToggleSafety.Text = state.SafetyEnabled
            ? Loc.GetString("cmu-nuke-ui-disable-safety")
            : Loc.GetString("cmu-nuke-ui-enable-safety");
        CommandLockoutButton.Text = state.CommandLockout
            ? Loc.GetString("cmu-nuke-ui-disable-command-lockout")
            : Loc.GetString("cmu-nuke-ui-enable-command-lockout");
        AnchorButton.Disabled = !state.CanAnchor || state.BeingUsed;
        ToggleSafety.Disabled = state.BeingUsed ||
            state.Status is CMUNukeStatus.Decrypting or CMUNukeStatus.DetonationCountdown;
        CommandLockoutButton.Disabled = state.BeingUsed;
        StartDecryption.Text = state.Status == CMUNukeStatus.Decrypting
            ? Loc.GetString("cmu-nuke-ui-stop-decryption")
            : Loc.GetString("cmu-nuke-ui-start-decryption");
        StartDecryption.Disabled = state.BeingUsed ||
            (state.Status != CMUNukeStatus.Decrypting && !state.CanStartDecryption);
        ArmButton.Text = state.Status == CMUNukeStatus.DetonationCountdown
            ? Loc.GetString("cmu-nuke-ui-disable-activation")
            : Loc.GetString("cmu-nuke-ui-activate-device");
        ArmButton.Disabled = state.BeingUsed ||
            (state.Status != CMUNukeStatus.DetonationCountdown && !state.AllowArm);
    }

    private static string FormatTime(int seconds)
    {
        var minutes = seconds / 60;
        var remainingSeconds = seconds % 60;
        return $"{minutes:D2}:{remainingSeconds:D2}";
    }
}
