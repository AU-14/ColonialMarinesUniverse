using Content.Shared.CMU14.Threats;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CMU14.Threats;

[GenerateTypedNameReferences]
public sealed partial class ForceInterestEntry : BoxContainer
{
    public event Action<uint, bool>? OnInterestChanged;

    public ForceInterestEntry(ForceInterestInfo force)
    {
        RobustXamlLoader.Load(this);
        ForceName.Text = force.Name;
        Counts.Text = Loc.GetString("cmu-force-interest-counts", ("roles", force.TotalRoles),
            ("interested", force.InterestedPlayers), ("required", force.RequiredPlayers));
        Status.Text = Loc.GetString(force.Ready ? "cmu-force-interest-waiting" : "cmu-force-interest-scheduled");
        InterestButton.Text = Loc.GetString(force.Interested ? "cmu-force-interest-withdraw" : "cmu-force-interest-join");
        InterestButton.Disabled = !force.Interested && !force.CanJoin;
        InterestButton.ToolTip = Loc.GetString("cmu-force-interest-help");
        InterestButton.OnPressed += _ => OnInterestChanged?.Invoke(force.Identifier, !force.Interested);
    }
}
