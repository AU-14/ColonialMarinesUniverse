    // frequencies come from the round's signal plan carried in the BUI state,
    // the prototype value is only the fallback book number
    private RadioFrequency PlanFreq(RadioChannelPrototype proto)
    {
        return _lastState != null && _lastState.ChannelFrequencies.TryGetValue(proto.ID, out var freq)
            ? freq
            : proto.Frequency;
    }

    private void RebuildNetList(ANPRCRadioState state)
    {
        EntryNetList.RemoveAllChildren();

        var opFaction = state.OperatorFaction;

        foreach (var proto in _prototype.EnumeratePrototypes<RadioChannelPrototype>())
        {
            // skip sentinels and non-displayable channels
            if (proto.Frequency == RadioFrequency.Off)
                continue;

            // own-faction nets always list. a foreign net lists once the search
            // receiver has fixed it - the server only puts a foreign channel's
            // frequency in the state after it lands in DiscoveredFrequencies.
            // faction-less channels (colony, civilian) get tuned by raw frequency
            var ownNet = string.IsNullOrEmpty(opFaction) ||
                         string.Equals(proto.Faction, opFaction, StringComparison.OrdinalIgnoreCase);

            var discovered = !ownNet &&
                             !string.IsNullOrEmpty(proto.Faction) &&
                             state.ChannelFrequencies.ContainsKey(proto.ID);

            if (!ownNet && !discovered)
                continue;

            var capturedProto = proto;
            var btn = new Button
            {
                Text = Loc.GetString(discovered ? "anprc-ui-net-entry-intercept" : "anprc-ui-net-entry",
                    ("channel", proto.LocalizedName.ToUpperInvariant()),
                    ("frequency", FormatFreq(PlanFreq(proto)))),
                HorizontalExpand = true,
            };
            btn.OnPressed += _ =>
            {
                if (_entryTargetSlot < 0) return;
                OnSetSlotChannel?.Invoke(_entryTargetSlot, new ProtoId<RadioChannelPrototype>(capturedProto.ID));
                CloseSlotEntryPanel();
            };
            EntryNetList.AddChild(btn);
        }
    }

    private void RebuildSweep(ANPRCRadioState state)
    {
        var online = state.Enabled && (state.IsEquipped || state.Planted);

        SweepButton.Disabled = !online;
        SweepButton.Text = Loc.GetString(state.SweepEnabled ? "anprc-ui-stop-search" : "anprc-ui-start-search");
        SweepButton.Pressed = state.SweepEnabled && online;

        SweepStatusLabel.Text = Loc.GetString(!online
            ? "anprc-ui-search-offline"
            : state.SweepEnabled
                ? "anprc-ui-search-searching"
                : "anprc-ui-search-idle");
        SweepStatusLabel.FontColorOverride = state.SweepEnabled && online ? TextWarn : TextDim;

        if (state.SweepEnabled && online)
        {
            SweepBandLabel.Text = Loc.GetString("anprc-ui-search-head", ("frequency", FormatFreq(state.SweepPosition)));
            SweepBandLabel.FontColorOverride = LcdBright;
            SweepHintLabel.Text = Loc.GetString("anprc-ui-search-active-help");
            SweepHintLabel.FontColorOverride = TextWarn;
        }
        else
        {
            SweepBandLabel.Text = Loc.GetString("anprc-ui-band-idle");
            SweepBandLabel.FontColorOverride = LcdOff;
            SweepHintLabel.Text = Loc.GetString("anprc-ui-search-help");
            SweepHintLabel.FontColorOverride = TextDim;
        }

        SweepContactList.RemoveAllChildren();

        if (state.SweepContacts.Count == 0)
        {
            SweepContactList.AddChild(new Label
            {
                Text = Loc.GetString("anprc-ui-no-contacts"),
                FontColorOverride = TextDim,
            });

            return;
        }

        foreach (var contact in state.SweepContacts)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 4,
            };

            if (contact.Resolved)
            {
                // an own net is dimmed and tagged: it is on the band, but it was never
                // work, and it should not read like a prize the operator won
                row.AddChild(new Label
                {
                    Text = Loc.GetString(contact.Known ? "anprc-ui-contact-own" : "anprc-ui-contact",
                        ("frequency", FormatFreq(contact.Frequency)),
                        ("channel", contact.ChannelName.ToUpperInvariant())),
                    FontColorOverride = contact.Known ? TextDim : TextGood,
                    HorizontalExpand = true,
                    ClipText = true,
                });

                // own nets are already sitting in the operator's presets, so only a
                // fixed foreign net gets the shortcut
                if (!contact.Known)
                {
                    var tuneBtn = new Button
                    {
                        Text = Loc.GetString("anprc-ui-tune-button"),
                        MinWidth = 52,
                        Disabled = state.ActiveSlot < 0 || !state.SlotLabels.ContainsKey(state.ActiveSlot),
                    };

                    var captured = contact.Frequency;
                    var slot = state.ActiveSlot;
                    tuneBtn.OnPressed += _ => OnTuneContact?.Invoke(slot, captured);

                    row.AddChild(tuneBtn);
                }
            }
            else
            {
                // partial fix: only the digits earned so far, the rest still masked
                row.AddChild(new Label
                {
                    Text = Loc.GetString("anprc-ui-contact-partial",
                        ("frequency", MaskDigits(FormatFreq(contact.Frequency), contact.Tier, contact.TierMax)),
                        ("tier", contact.Tier),
                        ("tierMax", contact.TierMax)),
                    FontColorOverride = TextWarn,
                    HorizontalExpand = true,
                    ClipText = true,
                });
            }

            SweepContactList.AddChild(row);
        }
    }

    private void RebuildNetLog(ANPRCRadioState state)
    {
        RebuildNetLogChannelFilter(state);

        NetLogContainer.RemoveAllChildren();

        var shown = 0;
        foreach (var entry in state.NetLog)
        {
            if (!NetLogEntryMatchesFilters(entry))
                continue;

            shown++;
            var ts = TimeSpan.FromSeconds(entry.Timestamp);
            var timeStr = $"{(int) ts.TotalMinutes:D2}:{ts.Seconds:D2}";

            var line = new Label
            {
                Text = Loc.GetString(entry.Intercepted ? "anprc-ui-log-entry-intercept" : "anprc-ui-log-entry",
                    ("time", timeStr),
                    ("sender", entry.SenderName),
                    ("channel", entry.ChannelDisplay)),
                FontColorOverride = entry.Intercepted ? TextWarn : TextLog,
                ClipText = true,
            };
            var msg = new Label
            {
                Text = $"  {entry.Message}",
                FontColorOverride = TextDim,
                ClipText = true,
            };
            NetLogContainer.AddChild(line);
            NetLogContainer.AddChild(msg);
        }

        var filtered = _netLogChannelFilter != null || _netLogSearchFilter.Length > 0;
        NetLogCountLabel.Text = filtered
            ? Loc.GetString("anprc-ui-log-filtered-count", ("shown", shown), ("total", state.NetLog.Count))
            : Loc.GetString("anprc-ui-log-count", ("count", state.NetLog.Count));

        if (filtered && shown == 0 && state.NetLog.Count > 0)
        {
            NetLogContainer.AddChild(new Label
            {
                Text = Loc.GetString("anprc-ui-log-no-filter-match"),
                FontColorOverride = TextDim,
            });
        }
    }

    private bool NetLogEntryMatchesFilters(ANPRCNetLogEntry entry)
    {
        if (_netLogChannelFilter != null && entry.ChannelDisplay != _netLogChannelFilter)
            return false;

        return _netLogSearchFilter.Length == 0 ||
               entry.SenderName.Contains(_netLogSearchFilter, StringComparison.OrdinalIgnoreCase) ||
               entry.Message.Contains(_netLogSearchFilter, StringComparison.OrdinalIgnoreCase);
    }

    // same deal as the callsign dropdown, only rebuild when the set of nets in the log
    // changes so an open dropdown doesn't get yanked shut
    private void RebuildNetLogChannelFilter(ANPRCRadioState state)
    {
        var channels = state.NetLog
            .Select(e => e.ChannelDisplay)
            .Distinct()
            .OrderBy(c => c, StringComparer.OrdinalIgnoreCase)
            .ToList();

        // on a fresh window with an empty log both lists are empty, so the equality
        // check alone would skip the build and leave the dropdown with no ALL NETS
        // entry for the clear button to select back to
        if (NetLogChannelFilter.ItemCount > 0 && channels.SequenceEqual(_netLogChannels))
            return;

        _netLogChannels.Clear();
        _netLogChannels.AddRange(channels);

        NetLogChannelFilter.Clear();
        NetLogChannelFilter.AddItem(Loc.GetString("anprc-ui-all-nets"), 0);
        for (var i = 0; i < _netLogChannels.Count; i++)
        {
            NetLogChannelFilter.AddItem(_netLogChannels[i], i + 1);
        }

        // reselect the previously chosen net, if it rotated out of the 50-entry log fall
        // back to ALL instead of filtering on a ghost
        var selectedIdx = _netLogChannelFilter == null ? -1 : _netLogChannels.IndexOf(_netLogChannelFilter);
        if (selectedIdx < 0)
        {
            _netLogChannelFilter = null;
            NetLogChannelFilter.SelectId(0);
        }
        else
        {
            NetLogChannelFilter.SelectId(selectedIdx + 1);
        }
    }

    private static string FormatFreq(RadioFrequency frequency)
        => frequency.FormatMegahertz();

    // The first three tiers reveal the MHz digits. The final tier reveals the exact
    // kHz carrier, so 259.237 progresses through 2XX.XXX / 25X.XXX / 259.XXX / 259.237.
    private static string MaskDigits(string formatted, int tier, int tierMax)
    {
        if (tier >= tierMax)
            return formatted;

        var earnedDigits = Math.Max(0, tier);
        var digitsSeen = 0;
        var masked = formatted.ToCharArray();

        for (var i = 0; i < masked.Length; i++)
        {
            if (!char.IsAsciiDigit(masked[i]))
                continue;

            digitsSeen++;
            if (digitsSeen > earnedDigits)
                masked[i] = 'X';
        }

        return new string(masked);
    }

    private static string BandName(RadioFrequency frequency)
    {
        var kilohertz = frequency.Kilohertz;
        return kilohertz < 3_000
            ? "LF"
            : kilohertz < 30_000
                ? "HF"
                : kilohertz < 88_000
                    ? "VHF"
                    : kilohertz < 300_000
                        ? "UHF"
                        : "SHF";
    }

    private static string Bars(int filled, int total)
    {
        filled = Math.Clamp(filled, 0, total);
        return new string('█', filled) + new string('░', total - filled);
    }

    private static string ModeShort(RadioMode m) => m switch
    {
        RadioMode.FrequencyHopping => "FH",
        RadioMode.SingleChannel => "SC",
        RadioMode.CipherText => "CT",
        RadioMode.PlainText => "PT",
        _ => "FH",
    };
