using Content.Client.Stylesheets;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.CMU14.BugHelp;

[GenerateTypedNameReferences]
public sealed partial class BugHelpWindow : DefaultWindow
{
    private const int WhatHappenedCap = 2000;
    private const int OptionalTextCap = 1000;
    private const int ExamineCap = 2000;
    private const int ItemQueryCap = 64;

    public event Action<BugHelpWindow>? OnSubmit;

    public BugHelpWindow()
    {
        RobustXamlLoader.Load(this);

        CapOnChange(WhatHappened, WhatHappenedCap);
        CapOnChange(Expected, OptionalTextCap);
        CapOnChange(Steps, OptionalTextCap);
        CapOnChange(ExamineText, ExamineCap);
        ItemQuery.OnTextChanged += args =>
        {
            if (args.Text.Length > ItemQueryCap)
                ItemQuery.Text = args.Text[..ItemQueryCap];
        };

        WhatHappened.OnTextChanged += _ => UpdateSubmit();
        SubmitButton.OnPressed += _ =>
        {
            var whatHappened = Rope.Collapse(WhatHappened.TextRope).Trim();
            if (whatHappened.Length == 0)
                return;

            OnSubmit?.Invoke(this);
        };
    }

    public BugHelpSubmission Collect()
    {
        return new BugHelpSubmission(
            Rope.Collapse(WhatHappened.TextRope).Trim(),
            Optional(Expected),
            Optional(Steps),
            string.IsNullOrWhiteSpace(ItemQuery.Text) ? null : ItemQuery.Text.Trim(),
            Optional(ExamineText));
    }

    private static string? Optional(TextEdit edit)
    {
        var text = Rope.Collapse(edit.TextRope).Trim();
        return text.Length == 0 ? null : text;
    }

    private void UpdateSubmit()
    {
        SubmitButton.Disabled = Rope.Collapse(WhatHappened.TextRope).Trim().Length == 0;
    }

    /// <summary>Truncate past the cap in place; the server caps again as the trust boundary.</summary>
    private static void CapOnChange(TextEdit edit, int cap)
    {
        edit.OnTextChanged += args =>
        {
            var text = Rope.Collapse(args.TextRope);
            if (text.Length > cap)
                edit.TextRope = new Rope.Leaf(text[..cap]);
        };
    }
}

public sealed record BugHelpSubmission(
    string WhatHappened,
    string? Expected,
    string? Steps,
    string? ItemQuery,
    string? ExamineText);
