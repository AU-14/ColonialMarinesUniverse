using Content.Shared.CCVar;
using Content.Shared.CMU14.Input;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.Input;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Input;

namespace Content.Client.CMU14.VoiceChat;

/// <summary>
/// Options tab gathering everything about voice chat: the page link, playback and the talk keys.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CMUVoiceChatTab : Control
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IInputManager _input = default!;
    [Dependency] private IClientConsoleHost _console = default!;
    [Dependency] private CMUVoiceChatManager _voice = default!;

    public CMUVoiceChatTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Control.AddOptionPercentSlider(CCVars.CMUVoiceChatVolume, VolumeSlider, max: 2f);
        Control.AddOptionCheckBox(CCVars.CMUVoiceChatHearSelf, HearSelfCheckBox);
        Control.AddOptionCheckBox(CCVars.CMUVoiceChatShowIntro, ShowIntroCheckBox);
        Control.AddOptionCheckBox(CCVars.CMUVoiceChatSpeakerList, SpeakerListCheckBox);
        Control.Initialize();

        OpenPageButton.OnPressed += _ => _console.ExecuteCommand("voicechat");
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _voice.CodeChanged += Refresh;
        Refresh();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _voice.CodeChanged -= Refresh;
    }

    /// <summary>
    /// Keys are rebound on the Controls tab; this shows what they are currently set to.
    /// </summary>
    public void Refresh()
    {
        var enabled = _cfg.GetCVar(CCVars.CMUVoiceChatEnabled);
        StatusLabel.Text = Loc.GetString(enabled ? "cmu-ui-options-voice-chat-enabled" : "cmu-ui-options-voice-chat-disabled");
        OpenPageButton.Disabled = !enabled;

        CodeLabel.Visible = enabled;
        CodeLabel.Text = _voice.Code is { } code
            ? Loc.GetString("cmu-ui-options-voice-chat-code", ("code", code))
            : Loc.GetString("cmu-ui-options-voice-chat-no-code");

        PushToTalkKeyLabel.Text = KeyLine("cmu-ui-options-voice-chat-key-ptt", CMUKeyFunctions.CMUVoicePushToTalk);
        RadioKeyLabel.Text = KeyLine("cmu-ui-options-voice-chat-key-radio", CMUKeyFunctions.CMUVoiceRadioPushToTalk);
        RadioCycleKeyLabel.Text = KeyLine("cmu-ui-options-voice-chat-key-cycle", CMUKeyFunctions.CMUVoiceRadioCycleChannel);
    }

    private string KeyLine(string label, BoundKeyFunction function)
    {
        var key = _input.TryGetKeyBinding(function, out _)
            ? _input.GetKeyFunctionButtonString(function)
            : Loc.GetString("cmu-ui-options-voice-chat-key-unbound");

        return Loc.GetString(label, ("key", key));
    }
}
