using System.Linq;
using Content.Shared._RMC14.Chemistry.Reagent;
using Content.Shared.CMU14.Yautja;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.CMU14.Yautja;

[GenerateTypedNameReferences]
public sealed partial class CMUYautjaExperimentWindow : DefaultWindow
{
    private readonly IPrototypeManager _prototypes = IoCManager.Resolve<IPrototypeManager>();
    private readonly RMCReagentSystem _reagents = IoCManager.Resolve<IEntityManager>().System<RMCReagentSystem>();
    private readonly Popup _popup = new() { MaxWidth = 340 };
    private CMUYautjaExperimentUiState? _state;
    public event Action<CMUYautjaExperimentMessage>? OnCommand;

    public CMUYautjaExperimentWindow()
    {
        RobustXamlLoader.Load(this);
        DevicePage.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#0D1112") };
        // OpenAtMouse owns attachment to the modal root, including detaching on close.
        OnClose += _popup.Close;
        DeviceTab.OnPressed += _ => ShowPage(0);
        ProceduresTab.OnPressed += _ => ShowPage(1);
        RecordsTab.OnPressed += _ => ShowPage(2);
        HelpButton.OnPressed += _ => ShowText(Loc.GetString("cmu-yautja-experiment-help-title"),
            Loc.GetString("cmu-yautja-experiment-help-short"));
        Diagram.OnSealPressed += ShowSeal;
        SamplesButton.OnPressed += _ => ShowSamples();
        ProcedureButton.OnPressed += _ => ShowProcedure();
        AuthorizeButton.OnPressed += _ => OnCommand?.Invoke(new(CMUYautjaExperimentCommand.Authorize));
        ShowPage(0);
    }

    public void SetBracer(EntityUid owner)
    {
        Diagram.SetEntity(owner);
        Title = IoCManager.Resolve<IEntityManager>().GetComponent<MetaDataComponent>(owner).EntityName;
    }

    public void UpdateState(CMUYautjaExperimentUiState state)
    {
        _state = state;
        Diagram.SetSeals(state.Seals);
        SealStatus.Text = Loc.GetString("cmu-yautja-experiment-seals-short",
            ("count", state.Seals.Count(seal => seal.RecoveredName != null)));
        Strain.Value = state.Heat;
        StrainStatus.Text = Loc.GetString("cmu-yautja-experiment-strain-short", ("heat", state.Heat));
        var selected = _prototypes.Index(state.Selected);
        ProcedureButton.Text = Loc.GetString("cmu-yautja-experiment-selected-procedure", ("name", Loc.GetString(selected.Name)));
        ProcedureButton.ToolTip = Requirements(selected);
        WorkStatus.Text = Loc.GetString(state.Busy ? "cmu-yautja-experiment-working-short" : "cmu-yautja-experiment-apply-tool");
        AuthorizeButton.Visible = state.Unlocked;
        AuthorizeButton.Disabled = state.Busy;
        ProcedureList.RemoveAllChildren();
        RecordList.RemoveAllChildren();
        foreach (var recipe in _prototypes.EnumeratePrototypes<CMUYautjaExperimentPrototype>().OrderBy(r => Loc.GetString(r.Name)))
        {
            var button = new Button { Text = Loc.GetString(recipe.Name), Disabled = state.Busy,
                ToolTip = Requirements(recipe), ToggleMode = true, Pressed = recipe.ID == state.Selected.Id };
            button.OnPressed += _ =>
            {
                OnCommand?.Invoke(new(CMUYautjaExperimentCommand.Select, recipe.ID));
                ShowPage(0);
            };
            ProcedureList.AddChild(button);
            if (!state.Discoveries.Contains(recipe.ID))
                continue;
            var record = new Button { Text = Loc.GetString(recipe.Name) };
            record.OnPressed += _ => ShowText(Loc.GetString(recipe.Name), Loc.GetString(recipe.Lore) + "\n\n" + Loc.GetString(recipe.Response));
            RecordList.AddChild(record);
        }
        if (state.Discoveries.Count == 0)
            RecordList.AddChild(new Label { Text = Loc.GetString("cmu-yautja-experiment-records-empty") });
    }

    private void ShowPage(int page)
    {
        _popup.Close();
        DevicePage.Visible = page == 0;
        ProceduresPage.Visible = page == 1;
        RecordsPage.Visible = page == 2;
        DeviceTab.Disabled = page == 0;
        ProceduresTab.Disabled = page == 1;
        RecordsTab.Disabled = page == 2;
    }

    private string Requirements(CMUYautjaExperimentPrototype recipe) =>
        Loc.GetString("cmu-yautja-experiment-requirements-short",
            ("tool", Loc.GetString(_prototypes.Index(recipe.Tool).ToolName)),
            ("chemicals", string.Join(" + ", recipe.Reagents.Select(pair =>
                $"{pair.Value}u {_reagents.Index(pair.Key).LocalizedName}"))),
            ("seconds", (int) recipe.Duration.TotalSeconds), ("heat", recipe.Heat));

    private void ShowProcedure()
    {
        if (_state == null)
            return;
        var recipe = _prototypes.Index(_state.Selected);
        ShowText(Loc.GetString(recipe.Name), Requirements(recipe) + "\n\n" +
            Loc.GetString("cmu-yautja-experiment-apply-tool"));
    }

    private void ShowSeal(int index)
    {
        if (_state == null || index >= _state.Seals.Count)
            return;
        var seal = _state.Seals[index];
        ShowText(Loc.GetString("cmu-yautja-experiment-seal-title", ("number", index + 1)),
            seal.RecoveredName == null ? seal.Clue :
                Loc.GetString("cmu-yautja-experiment-seal-recovered", ("name", seal.RecoveredName)) + "\n\n" + seal.Clue);
    }

    private BoxContainer PopupContent(string title)
    {
        _popup.Close();
        _popup.RemoveAllChildren();
        var panel = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#202529") },
        };
        var content = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(12), SeparationOverride = 10, MinWidth = 280, MaxWidth = 320 };
        content.AddChild(new Label { Text = title, FontColorOverride = Color.FromHex("#E0AC72") });
        panel.AddChild(content);
        _popup.AddChild(panel);
        return content;
    }

    private void ShowText(string title, string text)
    {
        var content = PopupContent(title);
        var label = new RichTextLabel();
        label.SetMessage(text);
        content.AddChild(label);
        _popup.OpenAtMouse();
    }

    private void ShowSamples()
    {
        if (_state == null)
            return;
        var content = PopupContent(Loc.GetString("cmu-yautja-experiment-samples-tab"));
        var label = new RichTextLabel();
        label.SetMessage(_state.Samples);
        content.AddChild(label);
        var purge = new Button { Text = Loc.GetString("cmu-yautja-experiment-purge"), Disabled = _state.Busy };
        purge.OnPressed += _ =>
        {
            OnCommand?.Invoke(new(CMUYautjaExperimentCommand.Purge));
            _popup.Close();
        };
        content.AddChild(purge);
        _popup.OpenAtMouse();
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            _popup.Close();
            _popup.Dispose();
        }
        base.Dispose(disposing);
    }
}
