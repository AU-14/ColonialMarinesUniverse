using System.Linq;
using System.Numerics;
using Content.Shared.CMU14.Yautja;
using Content.Shared._RMC14.Chemistry.Reagent;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client.CMU14.Yautja;

[GenerateTypedNameReferences]
public sealed partial class CMUYautjaExperimentWindow : BaseWindow
{
    private readonly IEntityManager _entities = IoCManager.Resolve<IEntityManager>();
    private readonly IEyeManager _eye = IoCManager.Resolve<IEyeManager>();
    private readonly IPrototypeManager _prototypes = IoCManager.Resolve<IPrototypeManager>();
    private CMUYautjaExperimentUiState? _state;
    private EntityUid? _bracer;
    private Vector2 _anchor;
    private int _contact;
    private Page _page;
    private string? _record;
    private bool _closeQueued;
    public event Action<CMUYautjaExperimentMessage>? OnCommand;

    private enum Page : byte { None, Procedures, Records }

    public CMUYautjaExperimentWindow()
    {
        RobustXamlLoader.Load(this);
        InspectionPanel.PanelOverride = YautjaBracerUiStyle.Flat(Color.FromHex("#1C2325F5"), Color.FromHex("#A18D6D"));
        Diagram.Visible = InspectionPanel.Visible = false;
        CloseButton.OnPressed += _ => Close();
        Diagram.OnSealPressed += index =>
        {
            _contact = index;
            SetPage(Page.None);
            RefreshContact();
        };
        ProcedureButton.OnPressed += _ => TogglePage(Page.Procedures);
        RecordsButton.OnPressed += _ => TogglePage(Page.Records);
        ProcedureSearch.OnTextChanged += _ => RefreshDrawer();
        AuthorizeButton.OnPressed += _ => OnCommand?.Invoke(new(CMUYautjaExperimentCommand.Authorize));
        foreach (var button in new[] { CloseButton, ProcedureButton, RecordsButton, AuthorizeButton })
            button.StyleBoxOverride = YautjaBracerUiStyle.Flat(Color.FromHex("#343E40"), Color.FromHex("#66726F"));
    }

    public void SetBracer(EntityUid owner)
    {
        _bracer = owner;
        ItemName.Text = _entities.GetComponent<MetaDataComponent>(owner).EntityName;
        UpdateAnchor();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateAnchor();
    }

    private void UpdateAnchor()
    {
        if (Parent == null || _closeQueued || _bracer is not { } owner)
            return;
        if (!_entities.TryGetComponent(owner, out TransformComponent? transform) ||
            transform.GridUid == null || transform.ParentUid != transform.GridUid ||
            transform.MapID != _eye.CurrentEye.Position.MapId)
        {
            // FrameUpdate is traversing WindowRoot.Children; detach after that traversal.
            _closeQueued = true;
            Diagram.Visible = InspectionPanel.Visible = false;
            UserInterfaceManager.DeferAction(Close);
            return;
        }

        // No recreated sprite or terrain: only the controls move with the live world's projection.
        var point = _eye.WorldToScreen(_entities.System<SharedTransformSystem>().GetWorldPosition(transform)) / UIScale - Parent.GlobalPosition;
        if (!float.IsFinite(point.X) || !float.IsFinite(point.Y))
            return;
        var visible = point.X >= 0 && point.Y >= 0 && point.X <= Parent.Size.X && point.Y <= Parent.Size.Y;
        Diagram.Visible = InspectionPanel.Visible = visible;
        if (SetSize != Parent.Size)
            SetSize = Parent.Size;
        if (Position != Vector2.Zero)
            LayoutContainer.SetPosition(this, Vector2.Zero);
        if (_anchor != point)
        {
            _anchor = point;
            InvalidateArrange();
        }
    }

    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        Diagram.Measure(new Vector2(320, 160));
        InspectionPanel.Measure(new Vector2(360, MathF.Max(0, MathF.Min(410, availableSize.Y - 16))));
        return Vector2.Zero;
    }

    protected override Vector2 ArrangeOverride(Vector2 finalSize)
    {
        Diagram.Arrange(UIBox2.FromDimensions(_anchor - CMUYautjaBracerDiagram.Anchor, new Vector2(320, 160)));
        var size = Vector2.Min(InspectionPanel.DesiredSize, Vector2.Max(Vector2.Zero, finalSize - new Vector2(16)));
        var position = _anchor + new Vector2(-size.X / 2, 110);
        // Keep the menu on screen without moving the contacts off their physical target.
        foreach (var offset in new[]
                 {
                     new Vector2(-size.X / 2, 110), new Vector2(-size.X / 2, -90 - size.Y),
                     new Vector2(180, -size.Y / 2), new Vector2(-180 - size.X, -size.Y / 2),
                 })
        {
            var candidate = _anchor + offset;
            if (candidate.X < 8 || candidate.Y < 8 || candidate.X + size.X > finalSize.X - 8 ||
                candidate.Y + size.Y > finalSize.Y - 8)
                continue;
            position = candidate;
            break;
        }
        position = Vector2.Clamp(position, new Vector2(8), Vector2.Max(new Vector2(8), finalSize - size - new Vector2(8)));
        InspectionPanel.Arrange(UIBox2.FromDimensions(position, size));
        return finalSize;
    }

    public void UpdateState(CMUYautjaExperimentUiState state)
    {
        _state = state;
        SealStatus.Text = Loc.GetString("cmu-yautja-experiment-locks", ("count", state.Seals.Count(seal => seal.RecoveredName != null)));
        Strain.Value = state.Heat;
        StrainStatus.Text = Loc.GetString("cmu-yautja-experiment-strain-short", ("heat", state.Heat));
        var selected = _prototypes.Index(state.Selected);
        ProcedureButton.Text = Loc.GetString("cmu-yautja-experiment-choose", ("name", Loc.GetString(selected.Name)));
        ProcedureButton.ToolTip = Loc.GetString("cmu-yautja-experiment-procedures-tab");
        Requirement.Text = SampleRequirement(selected);
        Requirement.ToolTip = SampleRequirement(selected, detailed: true);
        ToolRequirement.Text = Loc.GetString("cmu-yautja-experiment-tool-requirement",
            ("tool", Loc.GetString(_prototypes.Index(selected.Tool).ToolName)), ("seconds", (int) selected.Duration.TotalSeconds));
        WorkStatus.Text = Loc.GetString(state.Busy ? "cmu-yautja-experiment-working-compact" : "cmu-yautja-experiment-physical-tool");
        AuthorizeButton.Visible = state.Unlocked;
        AuthorizeButton.Disabled = state.Busy;
        ProcedureButton.Disabled = state.Busy;
        RefreshContact();
        RefreshDrawer();
    }

    private void RefreshContact()
    {
        if (_state == null || _contact >= _state.Seals.Count)
            return;
        Diagram.SetSeals(_state.Seals, _contact);
        var seal = _state.Seals[_contact];
        ContactTitle.Text = Loc.GetString(seal.RecoveredName == null ? "cmu-yautja-experiment-seal-title" :
            "cmu-yautja-experiment-contact-open", ("number", _contact + 1));
        Clue.SetMessage(seal.RecoveredName ?? seal.Clue);
    }

    private string SampleRequirement(CMUYautjaExperimentPrototype recipe, bool detailed = false)
    {
        if (recipe.Reagent is { } reagent)
            return Loc.GetString(detailed ? "cmu-yautja-experiment-standard-requirement" : "cmu-yautja-experiment-standard-short",
                ("amount", recipe.SampleAmount), ("reagent", _entities.System<RMCReagentSystem>().Index(reagent).LocalizedName));
        return Loc.GetString(detailed ? "cmu-yautja-experiment-generated-requirement" : "cmu-yautja-experiment-sample-requirement",
            ("amount", recipe.SampleAmount), ("tier", recipe.MinimumTier),
            ("property", _prototypes.Index(recipe.Property!.Value).LocalizedName), ("level", recipe.PropertyLevel));
    }

    private void TogglePage(Page page) => SetPage(_page == page ? Page.None : page);

    private void SetPage(Page page)
    {
        _page = page;
        _record = null;
        RefreshDrawer();
    }

    private void RefreshDrawer()
    {
        Drawer.Visible = _page != Page.None;
        ProcedureSearch.Visible = _page == Page.Procedures;
        DrawerContent.RemoveAllChildren();
        if (_state == null || _page == Page.None)
            return;
        switch (_page)
        {
            case Page.Procedures:
                DrawerTitle.Text = Loc.GetString("cmu-yautja-experiment-procedures-tab");
                foreach (var recipe in _prototypes.EnumeratePrototypes<CMUYautjaExperimentPrototype>().OrderBy(r => Loc.GetString(r.Name)))
                {
                    var name = Loc.GetString(recipe.Name);
                    if (!name.Contains(ProcedureSearch.Text, StringComparison.CurrentCultureIgnoreCase))
                        continue;
                    var button = DrawerButton(name, _state.Busy);
                    button.ToolTip = SampleRequirement(recipe, detailed: true);
                    button.OnPressed += _ =>
                    {
                        OnCommand?.Invoke(new(CMUYautjaExperimentCommand.Select, recipe.ID));
                        SetPage(Page.None);
                    };
                }
                break;
            case Page.Records:
                DrawerTitle.Text = Loc.GetString("cmu-yautja-experiment-records-tab");
                if (_record is { } id && _prototypes.TryIndex<CMUYautjaExperimentPrototype>(id, out var record))
                {
                    DrawerText(Loc.GetString(record.Lore));
                    DrawerText(Loc.GetString(record.Response));
                    DrawerButton(Loc.GetString("cmu-yautja-experiment-back")).OnPressed += _ => SetPage(Page.Records);
                }
                else
                {
                    foreach (var discovery in _state.Discoveries.OrderBy(id => id.Id))
                    {
                        var recipe = _prototypes.Index(discovery);
                        DrawerButton(Loc.GetString(recipe.Name)).OnPressed += _ => { _record = recipe.ID; RefreshDrawer(); };
                    }
                    if (_state.Discoveries.Count == 0)
                        DrawerText(Loc.GetString("cmu-yautja-experiment-records-empty"));
                }
                break;
        }
    }

    private Button DrawerButton(string text, bool disabled = false)
    {
        var button = new Button { Text = text, Disabled = disabled, ClipText = true, MinHeight = 28,
            StyleBoxOverride = YautjaBracerUiStyle.Flat(Color.FromHex("#293235"), Color.FromHex("#47534F")) };
        DrawerContent.AddChild(button);
        return button;
    }

    private void DrawerText(string text)
    {
        var label = new RichTextLabel();
        label.SetMessage(text);
        DrawerContent.AddChild(label);
    }
}
