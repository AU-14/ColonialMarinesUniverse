using Content.Shared.CMU14.Fob;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.CMU14.Fob;

[GenerateTypedNameReferences]
public sealed partial class CMUFobControlWindow : DefaultWindow
{
    public CMUFobControlWindow() => RobustXamlLoader.Load(this);

    private static string Clock(int seconds) => $"{seconds / 60}:{seconds % 60:00}";

    private static string GunLabel(CMUFobGunStatus[] guns, int slot)
    {
        if (slot >= guns.Length) return string.Empty;
        var gun = guns[slot];
        return Loc.GetString("cmu-fob-gun-status", ("slot", slot + 1),
            ("condition", Loc.GetString($"cmu-fob-gun-condition-{gun.Condition.ToString().ToLowerInvariant()}")),
            ("ammo", gun.Ammunition), ("damage", gun.Damage));
    }

    public void UpdateState(CMUFobControlState state)
    {
        ReserveLabel.Text = Loc.GetString("cmu-fob-reserve", ("time", Clock(state.Remaining)));
        StateLabel.Text = Loc.GetString(state.State switch
        {
            CMUFobReserveState.Standby => "cmu-fob-state-standby",
            CMUFobReserveState.Starting => "cmu-fob-state-starting",
            CMUFobReserveState.Active => "cmu-fob-state-active",
            CMUFobReserveState.Empty => "cmu-fob-state-empty",
            _ => "cmu-fob-state-closed",
        });
        RestartLabel.Text = Loc.GetString("cmu-fob-restart", ("time", Clock(state.Restart)));
        MinimumLabel.Text = Loc.GetString("cmu-fob-minimum", ("time", Clock(state.Minimum)));
        StartupLabel.Visible = state.State == CMUFobReserveState.Starting;
        StartupLabel.Text = Loc.GetString("cmu-fob-startup", ("time", Clock(state.Startup)));
        Activate.Disabled = !state.CanActivate;
        Deactivate.Disabled = !state.CanDeactivate;
        FirstGun.Text = GunLabel(state.Guns, 0);
        SecondGun.Text = GunLabel(state.Guns, 1);
        var hasJob = state.First.Length > 0 || state.Second.Length > 0;
        JobLabel.Text = Loc.GetString(state.NoRelayPair ? "cmu-fob-job-unavailable" : hasJob ? "cmu-fob-job-active"
            : state.JobTime > 0 ? "cmu-fob-job-next" : "cmu-fob-job-waiting", ("time", Clock(state.JobTime)));
        FirstRelay.Text = state.First;
        SecondRelay.Text = state.Second;
        RewardLabel.Visible = hasJob;
        RewardLabel.Text = Loc.GetString("cmu-fob-job-reward", ("time", Clock(state.Reward)));
    }
}
