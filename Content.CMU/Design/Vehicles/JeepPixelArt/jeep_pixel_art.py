    brass, glass, hose = (196, 160, 72), (196, 214, 214), (52, 54, 56)
    body = {}

    def box(x0, x1, y0, y1, colour, layer=body):
        for x in range(x0, x1 + 1):
            for y in range(y0, y1 + 1):
                layer[(x, y)] = colour

    # Hose looping from the grip's foot out to the right edge.
