# ── Geometry, in art pixels. Mirrored by CMUPhotoWindow. ─────────────────────
# Room round the paper for its shadow: light from the top left throws it down and right. Kept to two
# pixels so the window hugs the print; a wider shadow reads as empty window under it.
PAD_L, PAD_T, PAD_R, PAD_B = 1, 1, 2, 2
# Paper kept whole in each corner patch: the corner shading and wear live here.
CORNER = 8
# The tiled middle; wide so the grain does not visibly repeat.
TILE = 32
NINE_SLICE = dict(left=PAD_L + CORNER, top=PAD_T + CORNER, right=PAD_R + CORNER, bottom=PAD_B + CORNER)
FRAME_W = NINE_SLICE["left"] + TILE + NINE_SLICE["right"]
FRAME_H = NINE_SLICE["top"] + TILE + NINE_SLICE["bottom"]
# Paper between the edge and the picture; the foot's depth comes from the caption under the picture.
BORDER = 10
CONTENT = dict(left=PAD_L + BORDER, top=PAD_T + BORDER, right=PAD_R + BORDER, bottom=PAD_B + 7)
# The recess: a lip in the paper, then the dark edge of the developed area.
WINDOW = 8
WINDOW_SLICE = 2
# The close mark: a small pencilled cross in the top border, CLOSE_INSET in from the paper's corner.
CLOSE = 7
CLOSE_INSET = 2

# ── Palette ──────────────────────────────────────────────────────────────────
WEAR = {
    "clean": dict(paper=(237, 233, 221), hi=(247, 244, 235), lo=(222, 216, 201), edge=(196, 189, 172),
                  grain=2),
    # Yellowed with age and handling, grubby toward its edges.
    "aged": dict(paper=(231, 220, 192), hi=(240, 231, 205), lo=(214, 200, 168), edge=(176, 160, 126),
                 grain=3),
    # Handled a lot: scuffed corners, a thumbprint and one corner bent back.
    "worn": dict(paper=(234, 228, 212), hi=(244, 239, 225), lo=(217, 209, 190), edge=(184, 175, 155),
                 grain=3),
}
BACKING = (38, 36, 38)          # the black back of the print, seen where a corner is bent over
UNDEVELOPED = (34, 37, 33)       # the picture area before the image shows
REAGENT = (24, 23, 21)           # the dark line where the developer stops
SHADOW = (12, 10, 8)
INK = (34, 38, 58)               # marker on the item sprite's caption strip
OUTLINE = (66, 62, 56)           # the item sprite's outline, dark enough to read on any floor


def rgba(c, a=255):
    return c if len(c) == 4 else (c[0], c[1], c[2], a)


def shade(c, d):
    return tuple(max(0, min(255, v + d)) for v in c[:3])


class Layer:
    def __init__(self, w, h):
        self.w, self.h = w, h
        self.px = {}

    def set(self, x, y, c, a=255):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.px[(x, y)] = rgba(c, a)

    def get(self, x, y):
        return self.px.get((x, y))

    def rect(self, x0, y0, x1, y1, c, a=255):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.set(x, y, c, a)

    def outline(self, x0, y0, x1, y1, c, a=255):
        for x in range(x0, x1 + 1):
            self.set(x, y0, c, a)
            self.set(x, y1, c, a)
        for y in range(y0 + 1, y1):
            self.set(x0, y, c, a)
            self.set(x1, y, c, a)

    def over(self, x, y, c, a):
        """Alpha-composites one pixel over what is there."""
        under = self.px.get((x, y))
        if under is None:
            self.set(x, y, c, a)
            return
        k = a / 255
        ua = under[3] / 255
        out_a = k + ua * (1 - k)
        mix = tuple(round((c[i] * k + under[i] * ua * (1 - k)) / out_a) for i in range(3))
        self.set(x, y, mix, round(out_a * 255))

    def image(self):
        img = Image.new("RGBA", (self.w, self.h), (0, 0, 0, 0))
        for (x, y), c in self.px.items():
            img.putpixel((x, y), c)
        return img


class Rng:
    """Tiny deterministic generator, so the art is identical on every run."""

    def __init__(self, seed):
        self.state = seed * 2654435761 % 2 ** 32 or 1

    def next(self):
        self.state ^= (self.state << 13) % 2 ** 32
        self.state ^= self.state >> 17
        self.state ^= (self.state << 5) % 2 ** 32
        return self.state / 2 ** 32


# ── Primitives ───────────────────────────────────────────────────────────────
def grain(L, x0, y0, x1, y1, base, amount, seed):
    """Paper tooth: every pixel a shade either side of the base, and the odd short fibre."""
    rng = Rng(seed)
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            r = rng.next()
            d = -amount if r < 0.16 else amount if r > 0.9 else -1 if r < 0.3 else 0
            L.set(x, y, shade(base, d))
    rng = Rng(seed + 7)
    for y in range(y0, y1 + 1):
        x = x0
        while x <= x1:
            if rng.next() < 0.025:
                run = 2 + int(rng.next() * 2)
                for xx in range(x, min(x + run, x1 + 1)):
                    L.set(xx, y, shade(base, -amount - 1))
                x += run + 3
            else:
                x += 1


def drop_shadow(L, x0, y0, x1, y1):
    """A soft shadow down and right of a sheet whose paper is x0..x1, y0..y1."""
    # Ambient: a faint ring all round, so the print lifts off a dark background too.
    L.outline(x0 - 1, y0 - 1, x1 + 1, y1 + 1, SHADOW, 28)
    # Cast: the sheet's shape moved down and right, densest where it is nearest the sheet.
    for y in range(y0 + 1, y1 + PAD_B + 1):
        for x in range(x0 + 1, x1 + PAD_R + 1):
            dx = max(0, x - x1)
            dy = max(0, y - y1)
            if dx == 0 and dy == 0:
                continue
            far = max(dx, dy)
            a = 84 if far <= 1 else 34
            # The shadow's own corner is rounder than the sheet's.
            if dx >= PAD_R and dy >= PAD_B:
                continue
            L.set(x, y, SHADOW, a)


def sheet_edges(L, x0, y0, x1, y1, pal):
    """The cut edge, a lit top and left, a shaded foot and right side, and slightly eased corners."""
    for x in range(x0, x1 + 1):
        L.set(x, y0, pal["edge"])
        L.set(x, y1, shade(pal["edge"], -14))
        L.set(x, y0 + 1, pal["hi"])
        L.set(x, y1 - 1, pal["lo"])
    for y in range(y0, y1 + 1):
        L.set(x0, y, pal["edge"])
        L.set(x1, y, shade(pal["edge"], -10))
    for y in range(y0 + 1, y1):
        L.set(x0 + 1, y, pal["hi"])
        L.set(x1 - 1, y, pal["lo"])
    # The second row in from the shaded sides, half way back to the paper.
    for x in range(x0 + 2, x1 - 1):
        L.set(x, y1 - 2, mix(pal["lo"], pal["paper"]))
    for y in range(y0 + 2, y1 - 1):
        L.set(x1 - 2, y, mix(pal["lo"], pal["paper"]))
    # Eased corners: the corner pixel goes, its neighbours soften.
    for cx, cy in ((x0, y0), (x1, y0), (x0, y1), (x1, y1)):
        L.px.pop((cx, cy), None)
    L.set(x0 + 1, y0 + 1, mix(pal["hi"], pal["edge"]))


def mix(a, b, t=0.5):
    return tuple(round(a[i] * (1 - t) + b[i] * t) for i in range(3))


# ── The frame ────────────────────────────────────────────────────────────────
def frame(wear="clean"):
    pal = WEAR[wear]
    L = Layer(FRAME_W, FRAME_H)
    x0, y0 = PAD_L, PAD_T
    x1, y1 = FRAME_W - 1 - PAD_R, FRAME_H - 1 - PAD_B
    drop_shadow(L, x0, y0, x1, y1)
    grain(L, x0, y0, x1, y1, pal["paper"], pal["grain"], seed=11)
    sheet_edges(L, x0, y0, x1, y1, pal)
    if wear == "aged":
        age(L, x0, y0, x1, y1, pal)
    if wear == "worn":
        scuff(L, x0, y0, x1, y1, pal)
    return L


def corners(x0, y0, x1, y1):
    """The four corner patches, as (x, y, sx, sy): sx and sy point inward."""
    return ((x0, y0, 1, 1), (x1, y0, -1, 1), (x0, y1, 1, -1), (x1, y1, -1, -1))


def age(L, x0, y0, x1, y1, pal):
    """Grime worked into the corners by fingers, fading inward; kept inside the corner patches."""
    grime = shade(pal["edge"], -6)
    rng = Rng(23)
    for cx, cy, sx, sy in corners(x0, y0, x1, y1):
        for i in range(1, CORNER - 1):
            for j in range(1, CORNER - 1):
                d = i + j
                if d < 7 and rng.next() < (7 - d) / 7 * 0.55:
                    L.over(cx + sx * i, cy + sy * j, grime, 70)


def scuff(L, x0, y0, x1, y1, pal):
    """Scuffed corners, a thumbprint at the lower left and the top left corner bent back."""
    rng = Rng(5)
    for cx, cy, sx, sy in corners(x0, y0, x1, y1):
        for _ in range(5):
            i, j = 1 + int(rng.next() * 5), 1 + int(rng.next() * 5)
            L.over(cx + sx * i, cy + sy * j, shade(pal["edge"], -20), 90)
    # A thumbprint: faint whorl arcs, left by whoever has been holding it.
    tx, ty = x0 + 3, y1 - 6
    for x, y in ((1, 0), (2, 0), (3, 0), (0, 1), (4, 1), (1, 2), (2, 2), (3, 2), (0, 3), (4, 3), (1, 4), (2, 4), (3, 4)):
        L.over(tx + x, ty + y, shade(pal["lo"], -16), 70)
    # Dog-ear at the top left, clear of the close mark: a little fold shows the print's black back.
    for i in range(3):
        for j in range(3 - i):
            L.set(x0 + i, y0 + j, BACKING if i + j < 2 else shade(BACKING, 18))
    L.px.pop((x0, y0), None)
    for i in range(4):
        L.over(x0 + i, y0 + 3 - i, SHADOW, 60)


# ── The picture's recess ─────────────────────────────────────────────────────
def window():
    """Lip and dark edge round the picture; the middle is the undeveloped emulsion."""
    L = Layer(WINDOW, WINDOW)
    L.rect(0, 0, WINDOW - 1, WINDOW - 1, UNDEVELOPED)
    # The paper's lip, as light and shadow over whatever paper it is cut from.
    for i in range(WINDOW):
        L.set(i, 0, SHADOW, 70)
        L.set(0, i, SHADOW, 54)
        L.set(i, WINDOW - 1, (255, 255, 250), 120)
        L.set(WINDOW - 1, i, (255, 255, 250), 96)
    L.set(0, WINDOW - 1, SHADOW, 20)
    L.set(WINDOW - 1, 0, SHADOW, 20)
    L.outline(1, 1, WINDOW - 2, WINDOW - 2, REAGENT)
    return L


def window_shade():
    """Drawn over the picture: the lip's shadow along its top and left, and a glint of gloss."""
    L = Layer(WINDOW, WINDOW)
    for i in range(WINDOW):
        L.over(i, 0, SHADOW, 92)
        L.over(i, 1, SHADOW, 34)
        L.over(0, i, SHADOW, 70)
        L.over(1, i, SHADOW, 22)
    L.over(WINDOW - 1, WINDOW - 1, (255, 255, 255), 20)
    return L


# ── The close mark ───────────────────────────────────────────────────────────
PENCIL = (128, 122, 110)
PENCIL_HOVER = (70, 58, 52)


def close_mark(hover=False):
    """A small cross pressed into the paper with a pencil: graphite strokes with a lit lip under them."""
    L = Layer(CLOSE, CLOSE)
    ink = PENCIL_HOVER if hover else PENCIL
    for i in range(1, CLOSE - 1):
        for x, y in ((i, i), (CLOSE - 1 - i, i)):
            L.set(x, y, ink, 255 if hover else 220)
            # The groove catches the light on its lower side.
            if L.get(x, y + 1) is None:
                L.set(x, y + 1, (255, 253, 246), 110)
    # Tapered stroke ends: the pencil lifts off.
    for x, y in ((1, 1), (CLOSE - 2, 1), (1, CLOSE - 2), (CLOSE - 2, CLOSE - 2)):
        L.set(x, y, ink, 150 if hover else 120)
    if hover:
        # A faint smudge round it, as if a thumb is about to rub it out.
        for x in range(CLOSE):
            for y in range(CLOSE):
                if L.get(x, y) is None and 0 < x < CLOSE - 1 and 0 < y < CLOSE - 1:
                    L.set(x, y, PENCIL, 26)
    return L


# ── The item sprite ──────────────────────────────────────────────────────────
# The print's window on the 32x32 sprite. The client draws a thumbnail of the picture here.
ITEM_WINDOW = (10, 8, 12, 12)


def item(wear="clean", developed=None):
    """The print lying on the floor: two pixels of paper round the window, a deep foot with writing on it."""
    pal = WEAR[wear]
    L = Layer(32, 32)
    wx, wy, ww, wh = ITEM_WINDOW
    x0, y0, x1, y1 = wx - 3, wy - 3, wx + ww + 2, wy + wh + 5
    for y in range(y0 + 1, y1 + 1):
        L.set(x1 + 1, y, SHADOW, 64)
    for x in range(x0 + 1, x1 + 2):
        L.set(x, y1 + 1, SHADOW, 64)
    L.rect(x0, y0, x1, y1, pal["paper"])
    L.outline(x0, y0, x1, y1, OUTLINE)
    for cx, cy in ((x0, y0), (x1, y0), (x0, y1), (x1, y1)):
        L.px.pop((cx, cy), None)
    L.rect(x0 + 1, y0 + 1, x1 - 1, y0 + 1, pal["hi"])
    L.rect(x0 + 1, y0 + 1, x0 + 1, y1 - 1, pal["hi"])
    L.rect(x1 - 1, y0 + 2, x1 - 1, y1 - 1, pal["lo"])
    L.rect(x0 + 2, y1 - 1, x1 - 1, y1 - 1, pal["lo"])
    L.rect(wx, wy, wx + ww - 1, wy + wh - 1, UNDEVELOPED)
    if developed is not None:
        for (x, y), c in developed.items():
            L.set(wx + x, wy + y, c)
    # The lip: shade along the window's top and left, catching light along its foot.
    for x in range(wx - 1, wx + ww + 1):
        L.set(x, wy - 1, mix(pal["lo"], OUTLINE, 0.35))
        L.set(x, wy + wh, pal["hi"])
    for y in range(wy, wy + wh):
        L.set(wx - 1, y, mix(pal["lo"], OUTLINE, 0.25))
    # A scribbled caption on the foot.
    for x, dy in ((1, 0), (2, -1), (3, 0), (5, 0), (6, -1), (7, 0), (8, 0)):
        L.set(wx + x, wy + wh + 2 + dy, INK, 190 if dy == 0 else 120)
    return L


# ── Export ───────────────────────────────────────────────────────────────────
def write_rsi(name, size, states):
    path = TEXTURES / f"{name}.rsi"
    path.mkdir(parents=True, exist_ok=True)
    for old in path.glob("*.png"):
        old.unlink()
    meta = {"version": 1, "license": LICENSE, "copyright": COPYRIGHT,
            "size": {"x": size[0], "y": size[1]}, "states": []}
    for state, layer in states:
        layer.image().save(path / f"{state}.png")
        meta["states"].append({"name": state})
    (path / "meta.json").write_text(json.dumps(meta, indent=4) + "\n", encoding="utf-8", newline="\n")


def export_assets():
    TEXTURES.mkdir(parents=True, exist_ok=True)
    pngs = []
    for wear in WEAR:
        name = "polaroid_frame.png" if wear == "clean" else f"polaroid_frame_{wear}.png"
        frame(wear).image().save(TEXTURES / name)
        pngs.append(name)
    window().image().save(TEXTURES / "polaroid_window.png")
    window_shade().image().save(TEXTURES / "polaroid_shade.png")
    close_mark().image().save(TEXTURES / "polaroid_close.png")
    close_mark(hover=True).image().save(TEXTURES / "polaroid_close_hover.png")
    pngs += ["polaroid_window.png", "polaroid_shade.png", "polaroid_close.png", "polaroid_close_hover.png"]
    write_rsi("photo", (32, 32), [("icon", item())])

    files = ", ".join(f'"{p}"' for p in pngs)
    (TEXTURES / "attributions.yml").write_text(
        f'- files: [{files}]\n  license: "{LICENSE}"\n  copyright: "{COPYRIGHT}"\n  source: "{SOURCE}"\n',
        encoding="utf-8", newline="\n")


# ── Review material ──────────────────────────────────────────────────────────
def nine_slice(img, w, h, m, tile=True):
    """Lays a nine-slice out at w x h art pixels, tiling edges and middle as StyleBoxTexture's Tile mode does."""
    out = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    l, t, r, b = m["left"], m["top"], m["right"], m["bottom"]
    sw, sh = img.width, img.height
    cols = [(0, l, 0, l), (l, sw - r, l, w - r), (sw - r, sw, w - r, w)]
    rows = [(0, t, 0, t), (t, sh - b, t, h - b), (sh - b, sh, h - b, h)]
    for sx0, sx1, dx0, dx1 in cols:
        for sy0, sy1, dy0, dy1 in rows:
            part = img.crop((sx0, sy0, sx1, sy1))
            if dx1 <= dx0 or dy1 <= dy0:
                continue
            if tile:
                for yy in range(dy0, dy1, part.height):
                    for xx in range(dx0, dx1, part.width):
                        piece = part.crop((0, 0, min(part.width, dx1 - xx), min(part.height, dy1 - yy)))
                        out.alpha_composite(piece, (xx, yy))
            else:
                out.alpha_composite(part.resize((dx1 - dx0, dy1 - dy0), Image.NEAREST), (dx0, dy0))
    return out


def sample_photo(size):
    """A stand-in print made from the game's own sprites: floor, a camera and a roll of film."""
    tex = REPO / "Resources/Textures"
    cmu = REPO / "Content.CMU/Resources/Textures"
    img = Image.new("RGBA", (size, size), (0, 0, 0, 255))
    floor = next((p for p in [tex / "_RMC14/Tiles/almayer/floor.png", tex / "Tiles/steel.png"]
                  if p.exists()), None)
    if floor:
        f = Image.open(floor).convert("RGBA").crop((0, 0, 32, 32))
        for y in range(0, size, 32):
            for x in range(0, size, 32):
                img.alpha_composite(f, (x, y))
    sprites = [cmu / "CMU14/HunterShip/obj/items/paper.rsi/camera.png",
               cmu / "CMU14/HunterShip/obj/items/paper.rsi/film.png",
               tex / "Objects/Devices/travel_camera.rsi/icon.png"]
    spots = [(size // 2 - 16, size // 2 - 16), (size // 2 + 8, size // 2), (size // 2 - 40, size // 2 + 6)]
    for path, spot in zip(sprites, spots):
        if path.exists():
            img.alpha_composite(Image.open(path).convert("RGBA").crop((0, 0, 32, 32)), spot)
    return img


def viewer(wear, photo, scale, art_scale, caption):
    """The photo window as CMUPhotoWindow lays it out, at screen pixels."""
    p = photo.width * scale
    inner = p + 4 * art_scale                  # the recess's lip and dark edge
    caption_h = 22 * art_scale
    w = CONTENT["left"] * art_scale + inner + CONTENT["right"] * art_scale
    h = CONTENT["top"] * art_scale + inner + 3 * art_scale + caption_h + CONTENT["bottom"] * art_scale
    fr = frame(wear).image()
    sheet = nine_slice(fr, -(-w // art_scale), -(-h // art_scale), NINE_SLICE)
    out = sheet.resize((sheet.width * art_scale, sheet.height * art_scale), Image.NEAREST)
    ox, oy = CONTENT["left"] * art_scale, CONTENT["top"] * art_scale
    win = nine_slice(window().image(), inner // art_scale, inner // art_scale,
                     dict(left=WINDOW_SLICE, top=WINDOW_SLICE, right=WINDOW_SLICE, bottom=WINDOW_SLICE), tile=False)
    out.alpha_composite(win.resize((inner, inner), Image.NEAREST), (ox, oy))
    out.alpha_composite(photo.resize((p, p), Image.NEAREST), (ox + 2 * art_scale, oy + 2 * art_scale))
    sh = nine_slice(window_shade().image(), p // art_scale, p // art_scale,
                    dict(left=WINDOW_SLICE, top=WINDOW_SLICE, right=WINDOW_SLICE, bottom=WINDOW_SLICE), tile=False)
    out.alpha_composite(sh.resize((p, p), Image.NEAREST), (ox + 2 * art_scale, oy + 2 * art_scale))
    mark = close_mark().image()
    mark = mark.resize((mark.width * art_scale, mark.height * art_scale), Image.NEAREST)
    out.alpha_composite(mark, (out.width - (PAD_R + CLOSE_INSET + CLOSE) * art_scale,
                               (PAD_T + CLOSE_INSET) * art_scale))
    font_path = REPO / "Content.CMU/Resources/Fonts/ComicNeue/ComicNeue-Bold.ttf"
    d = ImageDraw.Draw(out)
    font = ImageFont.truetype(str(font_path), 15) if font_path.exists() else ImageFont.load_default()
    d.multiline_text((ox + 6, oy + inner + 3 * art_scale + 6), caption, fill=INK + (235,), font=font, spacing=4)
    return out


def export_review():
    REVIEW.mkdir(parents=True, exist_ok=True)
    big = 8
    tiles = [frame(w).image() for w in WEAR] + [window().image(), window_shade().image(), close_mark().image(),
                                                close_mark(True).image(), item().image()]
    gap = 8
    sheet_w = sum(t.width * big for t in tiles) + gap * (len(tiles) + 1)
    sheet_h = max(t.height * big for t in tiles) + gap * 2
    sheet = Image.new("RGBA", (sheet_w, sheet_h), (52, 54, 62, 255))
    x = gap
    for t in tiles:
        sheet.alpha_composite(t.resize((t.width * big, t.height * big), Image.NEAREST), (x, gap))
        x += t.width * big + gap
