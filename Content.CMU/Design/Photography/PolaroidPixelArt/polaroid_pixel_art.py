"""
Pixel-art instant photo: the source of truth for the photograph's art.

Run from anywhere:  python polaroid_pixel_art.py [review folder]

Writes the game assets into Content.CMU/Resources/Textures/CMU14/Photography/:

  polaroid_frame*.png    the print's paper as a nine-slice, one file per wear variant
  polaroid_window.png    the recess the picture sits in, as a nine-slice
  polaroid_shade.png     the lip's shadow, a nine-slice drawn over the picture
  polaroid_close*.png    the close mark pencilled in the frame's top corner, plain and hovered
  photo.rsi              the print as an item, with an empty window for its thumbnail

and review material (a contact sheet and a mock-up of the viewer) into polaroid_pixel_art/ in the
system temp folder, or the folder given on the command line, outside the repo.

Everything is drawn from primitives on small grids in one warm off-white palette, lit from the
top left like the rest of the CMU art. The frame is a real instant print's proportions: an even
border on three sides and a deep one at the foot where the caption is written. The paper is a
nine-slice so prints of any size share one texture: its corners hold the shadow, edge shading
and any wear, its edges and centre tile.

CMUPhotoWindow draws these at a whole-number scale and uses the margins in NINE_SLICE and
CONTENT; change one and you must change the other.
"""
