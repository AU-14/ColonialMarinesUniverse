def stamp_logo(L, x0, y0, h, w, m, dark, lit):
    """The company mark pressed into a panel like stamped lettering: dark, lit along its lower edge."""
    mark = Layer()
    width = wy_logo(mark, 0, 0, h=h, w=w, m=m)
    for (x, y) in mark.px:
        L.set(x0 + x, y0 + y + 1, lit)
    for (x, y) in mark.px:
        L.set(x0 + x, y0 + y, dark)
    return width


