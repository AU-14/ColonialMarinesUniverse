def shift(layer, src, dst):
    """Moves a layer drawn at `src` (x, y) onto `dst`, so sprites drawn in place share one RSI size."""
    out = Layer()
    for (px, py), c in layer.px.items():
        out.set(px - src[0] + dst[0], py - src[1] + dst[1], c)
    return out


# The note counter's run (atm_cash.wav, played by the server as cash comes out or goes in). The slot's
# frames are timed to it: dispensing, the shutter lights as the motor starts, the notes' edges show
# while they are counted, and the stack comes out as the counting stops; depositing, the notes are
# drawn in first, then counted. Each animation lasts exactly as long as the sound.
CASH_WAV = REPO / "Content.CMU/Resources/Audio/CMU14/ColonyEconomy/atm_cash.wav"


def cash_timing(tick=0.02):
    """(sound length, start and end of the counting) in seconds."""
    length, levels = wav_levels(CASH_WAV, tick)
    loud = [i for i, level in enumerate(levels) if level >= 0.5 * max(levels)]
    return length, loud[0] * tick, (loud[-1] + 1) * tick


CASH_SECONDS, COUNT_START, COUNT_END = cash_timing()
DISPENSE_DELAYS = [round(d, 3) for d in (COUNT_START, COUNT_END - COUNT_START - 0.2, 0.1, 0.1,
                                         max(0.05, CASH_SECONDS - COUNT_END))]
DEPOSIT_DELAYS = [round(d, 3) for d in (0.1, 0.1, 0.1, COUNT_END - 0.3, 0.15,
                                        max(0.05, CASH_SECONDS - COUNT_END - 0.15))]


