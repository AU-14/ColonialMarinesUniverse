    ramp = ("#c6a46f", "#cdab77", "#d3b17e", SHELF_TOP, "#dcbb8a", "#e0c090")
    depth = SHELF_FRONT - SHELF_BACK
    for y in range(SHELF_BACK, SHELF_FRONT + 1):
        left, right = shelf_span(y)
        L.rect(left, y, right, y, ramp[min(len(ramp) - 1, (y - SHELF_BACK) * len(ramp) // (depth + 1))])
