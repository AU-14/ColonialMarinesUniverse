def write_rsi(name, size, states):
    """states: list of (state name, [layers], delays or None)."""
    path = TEXTURES / f"{name}.rsi"
    path.mkdir(parents=True, exist_ok=True)
    for old in path.glob("*.png"):
        old.unlink()
    meta = {"version": 1, "license": LICENSE, "copyright": COPYRIGHT,
            "size": {"x": size[2], "y": size[3]}, "states": []}
    for state, frames, delays in states:
        sheet = Image.new("RGBA", (size[2] * len(frames), size[3]), (0, 0, 0, 0))
        for i, frame in enumerate(frames):
            sheet.paste(frame.image(size), (i * size[2], 0))
        sheet.save(path / f"{state}.png")
        entry = {"name": state}
        if delays:
            entry["delays"] = [delays]
        meta["states"].append(entry)
    (path / "meta.json").write_text(json.dumps(meta, indent=4) + "\n", encoding="utf-8", newline="\n")
    return path


