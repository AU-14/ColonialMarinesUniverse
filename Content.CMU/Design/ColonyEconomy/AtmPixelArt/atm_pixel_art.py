# The sparks follow the zaps in the seized reader's sound, which the window loops from the moment the
# machine goes out: the sound's loudness every SPARK_TICK picks the frame - a burst at a wire on the
# loudest moments, flying embers on the quieter ones, nothing in the gaps - and the loop lasts
# exactly as long as the sound, so the two stay together.
ZAP_WAV = REPO / "Content.CMU/Resources/Audio/CMU14/ColonyEconomy/atm_zap.wav"
SPARK_TICK = 0.04
SPARK_BURSTS = (0, 3, 5)            # SPARK_FRAMES with a wire bursting, taken in turn
SPARK_EMBERS = (1, 2, 4, 6)         # SPARK_FRAMES with only embers flying
SPARK_QUIET = 7


def wav_levels(path, tick):
    """(length in seconds, loudness of every `tick` seconds) of a mono 16-bit WAV."""
    import wave
    with wave.open(str(path)) as w:
        rate, data = w.getframerate(), w.readframes(w.getnframes())
    samples = [int.from_bytes(data[i:i + 2], "little", signed=True) for i in range(0, len(data), 2)]
    step = int(rate * tick)
    levels = []
    for i in range(0, len(samples), step):
        chunk = samples[i:i + step]
        levels.append((sum(s * s for s in chunk) / len(chunk)) ** 0.5)
    return len(samples) / rate, levels


def spark_timeline():
    """(SPARK_FRAMES index, seconds) runs that cover the zap sound once."""
    length, levels = wav_levels(ZAP_WAV, SPARK_TICK)
    loudest = max(levels)
    runs, bursts, embers = [], 0, 0
    for level in levels:
        if level >= 0.45 * loudest:
            frame, bursts = SPARK_BURSTS[bursts % len(SPARK_BURSTS)], bursts + 1
        elif level >= 0.15 * loudest:
            frame, embers = SPARK_EMBERS[embers % len(SPARK_EMBERS)], embers + 1
        else:
            frame = SPARK_QUIET
        if runs and frame == runs[-1][0] == SPARK_QUIET:
            runs[-1][1] += SPARK_TICK
        else:
            runs.append([frame, SPARK_TICK])
    # The last tick is a part one; trim so the loop is exactly the sound's length.
    runs[-1][1] += length - sum(d for _, d in runs)
    return [(frame, round(seconds, 4)) for frame, seconds in runs]


