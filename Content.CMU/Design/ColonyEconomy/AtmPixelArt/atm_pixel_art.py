def smooth(t):
    return t * t * (3 - 2 * t)


def at(keys, t):
    for (t0, v0), (t1, v1) in zip(keys, keys[1:]):
        if t <= t1:
            return round(v0 + (v1 - v0) * smooth((t - t0) / (t1 - t0) if t1 > t0 else 1))
    return keys[-1][1]


