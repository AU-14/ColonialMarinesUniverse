# ── Cash ─────────────────────────────────────────────────────────────────────
# Dollar bills, drawn lying flat as they come out of the slot toward the customer, after the game's
# note (_RMC14/Objects/Misc/spacecash.rsi): a dark outline, cream paper inside a framed border, grey
# corner marks, the grey portrait panel with its dark bust, a green seal and a grey one. Each is laid
# out on a trapezoid that starts inside the slot and widens as it nears, like the shelf below, with
# a crisp one-pixel outline whatever its size, and it darkens toward the slot, where it is still
# inside the machine. It comes out leading edge first. More money is more notes: each one under the
# top bill lies NOTE_LEAD rows further out and a little to one side, so their front edges show
# below it as separate bills. The window picks the stack from the amount.
CASH_FAR_Y, CASH_ROWS = 202, 12     # the trapezoid's far row, inside the slot, and a bill's depth
CASH_FAR_W, CASH_NEAR_W = 40, 61    # its width at the far row and at the near edge
CASH_MID = 84                       # the slot's centre
PRESENTED = CASH_ROWS
MAX_NOTES = 5
NOTE_SHIFTS = (0, -1, 2, -2, 1)     # each note's sideways shift, top note first
NOTE_LEAD = 2                       # rows each note under the top one lies further out
# How dark each row is, counted from the far edge: deep in the slot almost black, clear once out.
CASH_SHADE = (0.85, 0.7, 0.55, 0.4, 0.28, 0.18, 0.1, 0.05)
BILL = dict(outline="#2a2a2a", paper="#ccc7b4", paper_hi="#d6ceb7", border="#b8ab94", mark="#76736c",
            panel="#a19b8b", bust="#4e4a41", bust_lo="#444138", seal="#508460", seal_hi="#6ca07c")


def cash_span(row, shift=0):
    """Left and right ends of the trapezoid on `row`, counted from its far edge."""
    width = CASH_FAR_W + (CASH_NEAR_W - CASH_FAR_W) * row / (CASH_ROWS - 1)
    return round(CASH_MID - width / 2) + shift, round(CASH_MID + width / 2) - 1 + shift


def cash_shade(colour, row):
    r, g, b, _ = rgba(colour)
    keep = 1 - (CASH_SHADE[row] if row < len(CASH_SHADE) else 0)
    return "#%02x%02x%02x" % (int(r * keep), int(g * keep), int(b * keep))


def bill_colour(u, v, left, right, near):
    """The note at (u, v), each 0..1 across and down it; `left`, `right`, `near` mark its edge pixels."""
    if left or right or near:
        return BILL["outline"]
    if u < 0.05 or u > 0.95 or v > 0.9:
        return BILL["paper_hi"] if v > 0.9 and 0.05 <= u <= 0.95 else BILL["border"]
    if v < 0.08:
        return BILL["border"]
    if (0.08 <= u <= 0.17 or 0.83 <= u <= 0.92) and (0.16 <= v <= 0.34 or 0.62 <= v <= 0.8):
        return BILL["mark"]
    du, dv = (u - 0.5) / 0.19, (v - 0.48) / 0.36
    if du * du + dv * dv <= 1:
        # The portrait: a round head over rounded shoulders.
        if ((u - 0.5) / 0.065) ** 2 + ((v - 0.33) / 0.15) ** 2 <= 1:
            return BILL["bust"]
        if v >= 0.54 and ((u - 0.5) / 0.135) ** 2 + ((v - 0.86) / 0.32) ** 2 <= 1:
            return BILL["bust_lo"]
        return BILL["panel"]
    if ((u - 0.76) / 0.06) ** 2 + ((v - 0.48) / 0.16) ** 2 <= 1:
        return BILL["seal_hi"] if u < 0.76 and v < 0.45 else BILL["seal"]
    if ((u - 0.24) / 0.045) ** 2 + ((v - 0.48) / 0.12) ** 2 <= 1:
        return BILL["mark"]
    return BILL["paper"]


def draw_bill(L, drop, shift):
    """One bill with its front edge `drop` rows out of the slot; the part still inside is hidden."""
    for row in range(max(0, drop - CASH_ROWS), drop):
        x0, x1 = cash_span(row, shift)
        v = 1 - (drop - row - 0.5) / CASH_ROWS
        for x in range(x0, x1 + 1):
            u = (x - x0 + 0.5) / (x1 - x0 + 1)
            colour = bill_colour(u, v, x == x0, x == x1, row == drop - 1)
            L.set(x, CASH_FAR_Y + row, cash_shade(colour, row))


def cash(drop, light=1.0, notes=1):
    """
    A stack of `notes` bills `drop` rows out of the slot (0..CASH_ROWS), the shutter lit at `light`
    (0..1). The rows showing are each note's leading part, so they are seen sliding out or in.
    """
    L = Layer()
    if light > 0:
        # A dim lamp behind the open shutter, brightest just inside the lip.
        for y, f in ((201, 0.55), (202, 0.8), (203, 1.0), (204, 0.9), (205, 0.75), (206, 0.6), (207, 0.5), (208, 0.4), (209, 0.3)):
            k = light * f
            L.rect(56, y, 112, y, "#%02x%02x%02x" % (int(0x0a + 0x1e * k), int(0x0c + 0x2a * k), int(0x08 + 0x14 * k)))
    drop = min(drop, CASH_ROWS)
    if drop <= 0:
        return L
    notes = min(notes, MAX_NOTES)
    for i in reversed(range(notes)):
        draw_bill(L, drop + NOTE_LEAD * i, NOTE_SHIFTS[i])
    # The bills' shadow below the front-most edge.
    front = drop + NOTE_LEAD * (notes - 1)
    x0, x1 = cash_span(front - 1)
    L.rect(x0 + 1, CASH_FAR_Y + front, x1 - 1, CASH_FAR_Y + front, "#3d3324")
    return L


