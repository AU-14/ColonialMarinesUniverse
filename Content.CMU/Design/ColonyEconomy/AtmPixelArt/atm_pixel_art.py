def rgba(c):
    if isinstance(c, tuple):
        return c
    c = c.lstrip("#")
    return (int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16), int(c[6:8], 16) if len(c) == 8 else 255)


class Layer:
    def __init__(self, name=""):
        self.name = name
        self.px = {}

    def set(self, x, y, c):
        if 0 <= x < W and 0 <= y < H:
            self.px[(x, y)] = rgba(c)

    def get(self, x, y):
        return self.px.get((x, y))

    def rect(self, x0, y0, x1, y1, c):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.set(x, y, c)

    def outline(self, x0, y0, x1, y1, c, rounded=False):
        for x in range(x0, x1 + 1):
            if rounded and x in (x0, x1):
                continue
            self.set(x, y0, c)
            self.set(x, y1, c)
        for y in range(y0 + 1, y1):
            self.set(x0, y, c)
            self.set(x1, y, c)

    def glyphs(self, font, x, y, text, c, gap=1, bold=False):
        for ch in text:
            g = font.get(ch, font[" "])
            for gy, row in enumerate(g):
                for gx, bit in enumerate(row):
                    if bit == "#":
                        self.set(x + gx, y + gy, c)
                        if bold:
                            self.set(x + gx + 1, y + gy, c)
            x += len(g[0]) + gap + (1 if bold else 0)

    def blend(self, other):
        """Alpha-composites `other` over this layer, pixel by pixel."""
        for (x, y), (r, g, b, a) in other.px.items():
            under = self.px.get((x, y))
            if under is None or a == 255:
                self.px[(x, y)] = (r, g, b, a)
                continue
            k = a / 255
            ur, ug, ub, ua = under
            self.px[(x, y)] = (round(r * k + ur * (1 - k)), round(g * k + ug * (1 - k)),
                               round(b * k + ub * (1 - k)), max(ua, a))

    def paste(self, other, clip=None):
        for (x, y), c in other.px.items():
            if clip is None or (clip[0] <= x <= clip[2] and clip[1] <= y <= clip[3]):
                self.px[(x, y)] = c

    def image(self, rect=None):
        x0, y0, w, h = rect or (0, 0, W, H)
        img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        for (x, y), c in self.px.items():
            if x0 <= x < x0 + w and y0 <= y < y0 + h:
                img.putpixel((x - x0, y - y0), c)
        return img


def text_width(font, text, gap=1, bold=False):
    return sum(len(font.get(ch, font[" "])[0]) + gap + (1 if bold else 0) for ch in text) - gap


def centred(font, text, cx):
    return cx - text_width(font, text) // 2


# ── Shading helpers ──────────────────────────────────────────────────────────
# Light comes from the top-left throughout: raised edges catch it on their top and left and fall
# into shadow on their bottom and right; recesses do the opposite.
BAYER4 = ((0, 8, 2, 10), (12, 4, 14, 6), (3, 11, 1, 9), (15, 7, 13, 5))


def gradient(L, x0, y0, x1, y1, ramp):
    """Vertical gradient through `ramp`, ordered-dithered between neighbouring steps."""
    span = max(1, y1 - y0)
    for y in range(y0, y1 + 1):
        t = (y - y0) / span * (len(ramp) - 1)
        lo = int(t)
        frac = t - lo
        for x in range(x0, x1 + 1):
            step = lo + (1 if frac * 16 > BAYER4[y % 4][x % 4] + 0.5 and lo + 1 < len(ramp) else 0)
            L.set(x, y, ramp[step])


def bevel(L, x0, y0, x1, y1, hi, lo, raised=True):
    """One-pixel lit and shaded edges round a box; inverted for a recess."""
    a, b = (hi, lo) if raised else (lo, hi)
    L.rect(x0, y0, x1, y0, a)
    L.rect(x0, y0, x0, y1, a)
    L.rect(x0, y1, x1, y1, b)
    L.rect(x1, y0, x1, y1, b)


class _Rng:
    """Tiny deterministic generator, so the art is identical on every run."""

    def __init__(self, seed):
        self.state = seed * 2654435761 % 2 ** 32 or 1

    def next(self):
        self.state ^= (self.state << 13) % 2 ** 32
        self.state ^= self.state >> 17
        self.state ^= (self.state << 5) % 2 ** 32
        return self.state / 2 ** 32


def streaks(L, x0, y0, x1, y1, colour, seed, density=0.06):
    """Brushed-metal grain: short horizontal runs a shade off the base."""
    rng = _Rng(seed)
    for y in range(y0, y1 + 1):
        x = x0
        while x <= x1:
            if rng.next() < density:
                run = 2 + int(rng.next() * 6)
                for xx in range(x, min(x + run, x1 + 1)):
                    L.set(xx, y, colour)
                x += run + 2
            else:
                x += 1


def specks(L, x0, y0, x1, y1, colour, seed, density=0.012):
    """Wear: odd pixels of chipped paint or grime."""
    rng = _Rng(seed)
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if rng.next() < density:
                L.set(x, y, colour)


def stamp(L, font, x, y, text, dark, lit):
    """Lettering pressed into a panel: dark strokes with their lower edge catching the light."""
    L.glyphs(font, x, y + 1, text, lit)
    L.glyphs(font, x, y, text, dark)


def screw(L, cx, cy):
    """
    A round steel head with a single slot, lit from the top left like everything else on the
    machine: no outline, just a light rim, a dark rim and the slot.
    """
    head = [".###.", "#####", "#####", "#####", ".###."]
    for y, row in enumerate(head):
        for x, bit in enumerate(row):
            if bit == "#":
                rim = C["screw_hi"] if x + y <= 2 else C["screw_lo"] if x + y >= 6 else C["screw"]
                L.set(cx - 2 + x, cy - 2 + y, rim)
    L.rect(cx - 1, cy, cx + 1, cy, C["screw_slot"])


def pin(L, x, y):
    """A tiny two-pixel fixing for small plates."""
    L.set(x, y, C["screw_hi"])
    L.set(x + 1, y + 1, "#2a2420")


def rivet(L, cx, cy):
    for dx, dy in ((0, -1), (-1, 0), (1, 0), (0, 1)):
        L.set(cx + dx, cy + dy, "#211e1a")
    L.set(cx - 1, cy - 1, "#5a544f")


def bone_slot(L, x0, y0, x1, y1, plate):
    """A slot with rounded end-caps standing one pixel proud of the bar at each end."""
    L.rect(x0 + 2, y0 + 1, x1 - 2, y1 - 1, C["slot"])
    for cx in (x0, x1 - 4):
        L.rect(cx, y0, cx + 4, y1, C["slot"])
        for x, y in ((cx, y0), (cx + 4, y0), (cx, y1), (cx + 4, y1)):
            L.set(x, y, plate)
    L.rect(x0 + 5, y1, x1 - 5, y1, C["slot_rim"])


def glass(L, ramp, gleam=None):
    """The tube face, darkening towards the bezel, with an optional gleam in the top-left."""
    x, y, w, h = LAYOUT["glass"]
    steps = (1, 3, 6, 10)
    for yy in range(y, y + h):
        for xx in range(x, x + w):
            dx, dy = min(xx - x, x + w - 1 - xx), min(yy - y, y + h - 1 - yy)
            d = min(dx, dy, (dx + dy) // 2 + 1)
            L.set(xx, yy, ramp[next((n for n, s in enumerate(steps) if d < s), len(steps))])
    if gleam:
        for i in range(16):
            for j in range(2):
                L.set(x + 3 + i + j, y + 16 - i + j, gleam)


# ── Weyland-Yutani mark ──────────────────────────────────────────────────────
def wy_logo(L, x0, y0, h=27, w=17, m=6, gold=None, grey=None):
    """
    Four 45-degree strokes, so every diagonal is a clean one-pixel staircase, and three identical
    grey triangles: two hanging from the top between the arms, one standing under the middle peak.
    """
    gold, grey = gold or C["gold"], grey or C["grey"]
    b0 = x0 + 2 * (h - 1)          # top of the middle peak; the two middle strokes share it
    d0 = b0 + 2 * (h - 1)
    for y in range(h):
        for xs in (x0 + y, b0 - y, b0 + y, d0 - y):
            L.rect(xs, y0 + y, xs + w - 1, y0 + y, gold if y else C["gold_hi"])
        for left, right in ((x0 + y + w + m, b0 - y - 1 - m),        # top-left notch
                            (b0 + y + w + m, d0 - y - 1 - m),        # top-right notch
                            (b0 - y + w + m, b0 + y - 1 - m)):       # under the peak
            if left <= right:
                L.rect(left, y0 + y, right, y0 + y, grey)
    return 4 * (h - 1) + w


