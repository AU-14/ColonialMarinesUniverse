def rects(layer):
    runs = {}
    for y in range(H):
        x = 0
        while x < W:
            c = layer.px.get((x, y))
            if c is None:
                x += 1
                continue
            x1 = x
            while x1 + 1 < W and layer.px.get((x1 + 1, y)) == c:
                x1 += 1
            runs[(x, y)] = (x1, c)
            x = x1 + 1
    out, used = [], set()
    for (x, y), (x1, c) in sorted(runs.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        if (x, y) in used:
            continue
        y1 = y
        while runs.get((x, y1 + 1)) == (x1, c) and (x, y1 + 1) not in used:
            y1 += 1
            used.add((x, y1))
        out.append((x, y, x1 - x + 1, y1 - y + 1, c))
    return out


def svg_group(layer, visible):
    def fill(c):
        return "#%02x%02x%02x" % c[:3] + ("" if c[3] == 255 else f'" fill-opacity="{c[3] / 255:.2f}')
    body = "".join(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill(c)}"/>'
                   for x, y, w, h, c in rects(layer))
    return f'  <g id="{layer.name}"{"" if visible else " display=\"none\""}>{body}</g>\n'


