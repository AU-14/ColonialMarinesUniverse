/// <summary>
/// The Lodge: Pitch Camp and the kit, the one-Lodge rule, regeneration, the under-attack alert, the marine map
/// reveal and what happens when it falls. The clan's state itself is in <see cref="BadBloodCampRuleSystem"/>.
/// <para>
/// This is the core file. The trophy offering, the spit, squads, the armory and the kennel each go in a new
/// partial file and use the partial hooks at the bottom, they do not edit this file.
/// </para>
/// <para>
/// Dependency fields already taken by the core: _area, _badBlood, _damageable, _hands, _popup, _rule, _timing,
/// _transform.
/// </para>
/// </summary>
public sealed partial class BadBloodCampSystem : EntitySystem
{
    public static readonly EntProtoId LodgePrototype = "CMUBadBloodCamp";
    public static readonly EntProtoId KitPrototype = "CMUBadBloodCampKit";

    private static readonly TimeSpan UpdateEvery = TimeSpan.FromSeconds(1);

    [Dependency] private AreaSystem _area = default!;
    [Dependency] private BadBloodSystem _badBlood = default!;
    [Dependency] private DamageableSystem _damageable = default!;
    [Dependency] private SharedHandsSystem _hands = default!;
    [Dependency] private SharedPopupSystem _popup = default!;
    [Dependency] private BadBloodCampRuleSystem _rule = default!;
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private SharedTransformSystem _transform = default!;

    public override void Initialize()
    {
        SubscribeLocalEvent<BadBloodCampComponent, MapInitEvent>(OnLodgeMapInit);
        SubscribeLocalEvent<BadBloodCampComponent, DamageChangedEvent>(OnLodgeDamaged);
        SubscribeLocalEvent<BadBloodCampComponent, DestructionEventArgs>(OnLodgeDestruction);
        SubscribeLocalEvent<BadBloodCampComponent, EntityTerminatingEvent>(OnLodgeTerminating);

        SubscribeLocalEvent<BadBloodLeaderComponent, BadBloodPitchCampActionEvent>(OnPitchCamp);
        SubscribeLocalEvent<BadBloodCampKitComponent, BadBloodCampKitDeployAttemptEvent>(OnKitDeployAttempt);
        SubscribeLocalEvent<BadBloodCampKitComponent, EntityTerminatingEvent>(OnKitTerminating);

        InitializeOffering();
        InitializeSpit();
        InitializeSquads();
        InitializeArmory();
        InitializeKennel();
    }

    public override void Update(float frameTime)
    {
        if (!_rule.TryGetRule(out var rule) || !TryGetLodge(out var lodge))
            return;

        var now = _timing.CurTime;
        if (now < lodge.Comp.NextUpdate)
            return;

        lodge.Comp.NextUpdate = now + UpdateEvery;

        if (lodge.Comp.Regen > 0f &&
            now - lodge.Comp.LastDamagedAt >= lodge.Comp.RegenDelay &&
            _damageable.GetTotalDamage(lodge.Owner) > FixedPoint2.Zero)
        {
            _damageable.HealEvenly(lodge.Owner, FixedPoint2.New(-lodge.Comp.Regen));
        }

        RefreshReveal(lodge, rule, now);

        TickOffering(lodge, rule, now);
        TickSpit(lodge, rule, now);
        TickSquads(lodge, rule, now);
        TickArmory(lodge, rule, now);
        TickKennel(lodge, rule, now);
    }

    #region The Lodge and its parts

    /// <summary>
    /// The clan's standing Lodge.
    /// </summary>
    public bool TryGetLodge(out Entity<BadBloodCampComponent> lodge)
    {
        lodge = default;
        if (_rule.GetLodge() is not { } uid || !TryComp(uid, out BadBloodCampComponent? comp))
            return false;

        lodge = (uid, comp);
        return true;
    }

    /// <summary>
    /// A part of the standing Lodge: the spit, the Ascension Stone, the armory, the kennel or the cauldron.
    /// The parts are spawned right after the Lodge, so they are not there yet while the pitched hooks and
    /// <see cref="BadBloodLodgePitchedEvent"/> run. A Lodge spawned without its kit has no parts at all.
    /// </summary>
    public bool TryGetPart(BadBloodCampPartKind kind, out EntityUid part)
    {
        part = default;
        if (!_rule.HasLodge())
            return false;

        var query = EntityQueryEnumerator<BadBloodCampPartComponent>();
        while (query.MoveNext(out var uid, out var comp))
        {
            if (comp.Kind != kind || TerminatingOrDeleted(uid))
                continue;

            part = uid;
            return true;
        }

        return false;
    }

    private void OnLodgeMapInit(Entity<BadBloodCampComponent> ent, ref MapInitEvent args)
    {
        ent.Comp.LastDamagedAt = _timing.CurTime;

        if (!_rule.TryGetRule(out var rule) || !_rule.TryRegisterLodge(ent.Owner, out var first))
            return;

        LodgePitchedOffering(ent, rule, first);
        LodgePitchedSpit(ent, rule, first);
        LodgePitchedSquads(ent, rule, first);
        LodgePitchedArmory(ent, rule, first);
        LodgePitchedKennel(ent, rule, first);

        var ev = new BadBloodLodgePitchedEvent(rule, ent.Owner, first);
        RaiseLocalEvent(ref ev);

        _rule.AnnounceToClan(Loc.GetString(first
            ? "cmu-bad-blood-camp-pitched-first"
            : "cmu-bad-blood-camp-pitched"));
    }

    private void OnLodgeDestruction(Entity<BadBloodCampComponent> ent, ref DestructionEventArgs args)
    {
        HandleLodgeGone(ent);
    }

    // catches a Lodge deleted without being destroyed
    private void OnLodgeTerminating(Entity<BadBloodCampComponent> ent, ref EntityTerminatingEvent args)
    {
        HandleLodgeGone(ent);
    }

    private void HandleLodgeGone(Entity<BadBloodCampComponent> ent)
    {
        if (ent.Comp.Destroyed)
            return;

        ent.Comp.Destroyed = true;

        if (!_rule.TryGetRule(out var rule) || !_rule.UnregisterLodge(ent.Owner))
            return;

        LodgeDestroyedOffering(ent, rule);
        LodgeDestroyedSpit(ent, rule);
        LodgeDestroyedSquads(ent, rule);
        LodgeDestroyedArmory(ent, rule);
        LodgeDestroyedKennel(ent, rule);

        var ev = new BadBloodLodgeDestroyedEvent(rule, ent.Owner);
        RaiseLocalEvent(ref ev);

        _rule.AnnounceToClan(Loc.GetString("cmu-bad-blood-camp-destroyed"), PopupType.LargeCaution);
    }

    private void OnLodgeDamaged(Entity<BadBloodCampComponent> ent, ref DamageChangedEvent args)
    {
        if (!args.DamageIncreased || args.DamageDelta == null || args.DamageDelta.GetTotal() <= FixedPoint2.Zero)
            return;

        var now = _timing.CurTime;
        ent.Comp.LastDamagedAt = now;

        if (_rule.GetLodge() != ent.Owner)
            return;

        RevealLodge(ent.Comp.AttackRevealTime);

        if (ent.Comp.LastAlertAt is { } last && now - last < ent.Comp.AlertCooldown)
            return;

        ent.Comp.LastAlertAt = now;
        _rule.AnnounceToClan(Loc.GetString("cmu-bad-blood-camp-under-attack"), PopupType.MediumCaution);
    }

    #endregion

    #region Marine map reveal

    /// <summary>
    /// Shows the standing Lodge on the marine and GOVFOR tactical maps for <paramref name="duration"/>, or until
    /// <see cref="HideLodge"/> when it is null. A shorter reveal never cuts a longer one short.
    /// The core already reveals it by itself after each hit, for as long as the clan ship is inbound or arrived,
    /// and while no Bad Blood is alive. False if no Lodge stands.
    /// </summary>
    public bool RevealLodge(TimeSpan? duration = null)
    {
        if (!_rule.TryGetRule(out var rule) || !TryGetLodge(out var lodge))
            return false;

        var now = _timing.CurTime;
        if (duration is { } time)
        {
            var until = now + time;
            if (until > lodge.Comp.RevealedUntil)
                lodge.Comp.RevealedUntil = until;
        }
        else
        {
            lodge.Comp.RevealPermanent = true;
        }

        RefreshReveal(lodge, rule, now);
        return true;
    }

    /// <summary>
    /// Ends every reveal asked for through <see cref="RevealLodge"/>. The Lodge stays on the map while one of the
    /// core's own reasons still holds.
    /// </summary>
    public void HideLodge()
    {
        if (!_rule.TryGetRule(out var rule) || !TryGetLodge(out var lodge))
            return;

        lodge.Comp.RevealPermanent = false;
        lodge.Comp.RevealedUntil = TimeSpan.Zero;
        RefreshReveal(lodge, rule, _timing.CurTime);
    }

    public bool IsLodgeRevealed()
    {
        return TryGetLodge(out var lodge) && lodge.Comp.Revealed;
    }

    private void RefreshReveal(Entity<BadBloodCampComponent> lodge, Entity<BadBloodCampRuleComponent> rule, TimeSpan now)
    {
        var reveal = lodge.Comp.RevealPermanent ||
                     now < lodge.Comp.RevealedUntil ||
                     rule.Comp.ShipState != BadBloodShipState.None ||
                     _rule.CountLivingBadBloods() == 0;

        if (reveal == lodge.Comp.Revealed)
            return;

        lodge.Comp.Revealed = reveal;
        if (reveal)
            EntityManager.AddComponents(lodge.Owner, lodge.Comp.RevealComponents);
        else
            EntityManager.RemoveComponents(lodge.Owner, lodge.Comp.RevealComponents);
    }

    #endregion

    #region Pitch Camp and the kit

    private void OnPitchCamp(Entity<BadBloodLeaderComponent> ent, ref BadBloodPitchCampActionEvent args)
    {
        if (args.Handled)
            return;

        args.Handled = true;
        TryPitchCamp(ent.Owner);
    }

    /// <summary>
    /// The Pitch Camp action: puts a Lodge kit in the Leader's hands. Refused for anyone else, while a Lodge
    /// stands and during the rebuild cooldown. A kit that is still lying around is replaced.
    /// </summary>
    public bool TryPitchCamp(EntityUid user)
    {
        if (!_badBlood.IsBadBloodLeader(user) || !_rule.TryGetRule(out var rule))
        {
            _popup.PopupEntity(Loc.GetString("cmu-bad-blood-camp-kit-leader-only"), user, user, PopupType.SmallCaution);
            return false;
        }

        if (_rule.HasLodge())
        {
            _popup.PopupEntity(Loc.GetString("cmu-bad-blood-camp-already-standing"), user, user, PopupType.SmallCaution);
            return false;
        }

        var now = _timing.CurTime;
        if (rule.Comp.NextCampAt is { } next && now < next)
        {
            var seconds = (int) Math.Ceiling((next - now).TotalSeconds);
            _popup.PopupEntity(Loc.GetString("cmu-bad-blood-camp-cooldown", ("seconds", seconds)), user, user, PopupType.SmallCaution);
            return false;
        }

        if (rule.Comp.Kit is { } old && !TerminatingOrDeleted(old))
            QueueDel(old);

        var kit = Spawn(KitPrototype, Transform(user).Coordinates);
        rule.Comp.Kit = kit;
        rule.Comp.KitOut = true;
        _hands.PickupOrDrop(user, kit);
        _popup.PopupEntity(Loc.GetString("cmu-bad-blood-camp-kit-ready"), user, user);
        return true;
    }

    // the shared kit system has already checked the user is the Leader
    private void OnKitDeployAttempt(Entity<BadBloodCampKitComponent> ent, ref BadBloodCampKitDeployAttemptEvent args)
    {
        if (args.Cancelled)
            return;

        string? reason = null;
        if (!_rule.TryGetRule(out var rule))
            reason = "cmu-bad-blood-camp-kit-leader-only";
        else if (_rule.HasLodge())
            reason = "cmu-bad-blood-camp-already-standing";
        else if (IsRoofed(args.User))
            reason = "cmu-bad-blood-camp-roofed";
        else if (IsNearLandingZone(args.User, rule.Comp.CampLandingZoneDistance))
            reason = "cmu-bad-blood-camp-near-landing-zone";

        if (reason == null)
            return;

        args.Cancelled = true;
        if (!args.Quiet)
            _popup.PopupEntity(Loc.GetString(reason), args.User, args.User, PopupType.SmallCaution);
    }

    private void OnKitTerminating(Entity<BadBloodCampKitComponent> ent, ref EntityTerminatingEvent args)
    {
        if (!_rule.TryGetRule(out var rule) || rule.Comp.Kit != ent.Owner)
            return;

        rule.Comp.Kit = null;
        rule.Comp.KitOut = false;
    }

    private bool IsRoofed(EntityUid user)
    {
        _area.CanOrbitalBombard(Transform(user).Coordinates, out var roofed);
        return roofed;
    }

    private bool IsNearLandingZone(EntityUid user, float distance)
    {
        if (distance <= 0f)
            return false;

        var here = _transform.GetMapCoordinates(user);
        var query = EntityQueryEnumerator<DropshipDestinationComponent, TransformComponent>();
        while (query.MoveNext(out var uid, out _, out var xform))
        {
            if (xform.MapID != here.MapId)
                continue;

            var there = _transform.GetMapCoordinates(uid, xform);
            if ((there.Position - here.Position).Length() < distance)
                return true;
        }

        return false;
    }

