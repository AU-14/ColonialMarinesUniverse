"""Regenerate washer damage profiles from the repository's explosion prototypes."""

import argparse
from decimal import Decimal
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / "Content.CMU/Resources/Prototypes/CMU14/Entities/Structures/Hygiene/laundry_explosions.yml"
PREFIX = "CMULaundryHalf"


def generate():
    profiles = {}
    for directory in (ROOT / "Resources/Prototypes", ROOT / "Content.CMU/Resources/Prototypes"):
        for path in sorted(directory.rglob("*.yml")):
            if path == OUTPUT:
                continue
            text = path.read_text(encoding="utf-8-sig")
            if not re.search(r"^- type: explosion\s*(?:#.*)?$", text, re.MULTILINE):
                continue
            for block in re.split(r"(?=^- type: )", text, flags=re.MULTILINE):
                if not re.match(r"- type: explosion\s*(?:#.*)?\n", block):
                    continue
                original = re.search(r"^  id: (\S+)", block, re.MULTILINE).group(1)
                if original.startswith(PREFIX):
                    continue
                if original in profiles:
                    raise ValueError(f"Duplicate explosion prototype: {original}")
                block = re.sub(r"^  id: \S+", f"  id: {PREFIX}{original}", block, count=1, flags=re.MULTILINE)
                damage = re.search(r"^  damagePerIntensity:\n(?:(?:    .*|\s*)\n)+", block, re.MULTILINE)
                if damage is None:
                    raise ValueError(f"Missing damagePerIntensity: {original}")
                scaled = re.sub(
                    r"^(      \w+: )(-?\d+(?:\.\d+)?)([ \t]*(?:#.*)?)$",
                    lambda match: match[1] + str(Decimal(match[2]) / 2) + match[3],
                    damage[0], flags=re.MULTILINE,
                )
                if scaled == damage[0]:
                    raise ValueError(f"No numeric damage entries: {original}")
                block = block[:damage.start()] + scaled + block[damage.end():]
                profiles[original] = block.strip()
    header = "# Generated by Content.CMU/Tools/Hygiene/generate_laundry_explosions.py.\n"
    header += "# Explosion prototypes do not inherit; only damagePerIntensity differs from the originals.\n"
    return header + "\n\n".join(profiles[key] for key in sorted(profiles)) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the profiles without changing files.")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != generated:
            parser.exit(1, "Washer explosion profiles need regeneration. Run this script without --check.\n")
        print("Washer explosion profiles are current.")
    else:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
        print(f"Updated {OUTPUT.relative_to(ROOT)}")
