using Content.Client.CMU14.UI;
using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using static Content.Client.CMU14.UI.CMUMachineUiStyle;

namespace Content.Client._RMC14.Chemistry.Centrifuge;

[GenerateTypedNameReferences]
public sealed partial class RMCCentrifugeWindow : DefaultWindow
{
    private readonly Label _modeLabel;
    private readonly Label _sourceLabel;
    private readonly Font _bannerFont;

    public RMCCentrifugeWindow()
    {
        RobustXamlLoader.Load(this);
        RemoveWindowBorder(this);

        _bannerFont = IoCManager.Resolve<IResourceCache>().GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);
        LabelEdit.StyleBoxOverride = Field();

        _modeLabel = ModeButton.SetIcon(CMUIcons.ArrowsRotate, "Mode: split", 16).Label;

        _sourceLabel = SourceButton.SetIcon(CMUIcons.Flask, "Input: Container", 16).Label;

        ConnectButton.SetIcon(CMUIcons.Link, "Connect a Turing Dispenser", 16);

        EjectInputButton.SetIcon(CMUIcons.Eject, "Eject", 16);
        EjectOutputButton.SetIcon(CMUIcons.Eject, "Eject", 16);
    }

    public void SetMode(string text)
    {
        _modeLabel.Text = text;
    }

    public void SetSource(string text)
    {
        _sourceLabel.Text = text;
    }

    public void SetConnection(bool connected)
    {
        Notice(ConnectionPanel,
            ConnectionLabel,
            connected ? "Turing Dispenser connected!" : "No Turing Dispenser connected!",
            NoticeInfoColor,
            _bannerFont);
    }

    public void SetLabel(string? label)
    {
        if (LabelEdit.HasKeyboardFocus())
            return;

        LabelEdit.Text = label ?? string.Empty;
    }
}
