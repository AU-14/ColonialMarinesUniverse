// CMU14 class: redesigned CRT vendor presentation (upstream UI class retained).
using Content.Client.CMU14.Interface;
using Content.Client.CMU14.Yautja;
using Content.Shared._RMC14.Vendors;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.Vendors;

[GenerateTypedNameReferences]
public sealed partial class CMAutomatedVendorSection : Control
{
    public CMVendorSection? Section;

    public CMAutomatedVendorSection()
    {
        RobustXamlLoader.Load(this);
        SectionSurface.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = CrtTerminalPalette.Surface1,
            ContentMarginLeftOverride = 8,
            ContentMarginRightOverride = 8,
            ContentMarginTopOverride = 6,
            ContentMarginBottomOverride = 8,
        };
        SectionRule.PanelOverride = new StyleBoxFlat { BackgroundColor = CrtTerminalPalette.Line };
        EntryCount.FontColorOverride = CrtTerminalPalette.TextDim;
    }

    public void UseYautjaTheme()
    {
        SectionSurface.PanelOverride = YautjaBracerUiStyle.Flat(YautjaBracerUiStyle.Card, YautjaBracerUiStyle.MutedBorder);
        SectionRule.PanelOverride = YautjaBracerUiStyle.Flat(YautjaBracerUiStyle.MutedBorder, YautjaBracerUiStyle.MutedBorder);
        EntryCount.FontColorOverride = YautjaBracerUiStyle.Muted;
    }

    public void UpdateCount(int visible, int total)
    {
        EntryCount.Text = visible == total ? total.ToString() : $"{visible}/{total}";
    }
}
