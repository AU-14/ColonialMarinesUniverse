// CMU14 class: redesigned CRT vendor presentation (upstream UI class retained).
using Content.Client.CMU14.Interface;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.Vendors;

[GenerateTypedNameReferences]
public sealed partial class CMAutomatedVendorPanel : Control
{
    public static Color DefaultColor => CrtTerminalPalette.Surface2;
    public static Color DefaultBorderColor => CrtTerminalPalette.Line;
    public static Color DefaultHoveredColor => CrtTerminalPalette.Surface3;

    public Color Color = DefaultColor;
    public Color BorderColor = DefaultBorderColor;
    public Color HoveredColor = DefaultHoveredColor;

    public CMAutomatedVendorPanel()
    {
        RobustXamlLoader.Load(this);
        Button.OnDrawModeChanged += UpdateColor;
        Button.TextLabel.FontColorOverride = CrtTerminalPalette.TextBright;
        UpdateColor();
    }

    private void UpdateColor()
    {
        var panel = (StyleBoxFlat) Panel.PanelOverride!;
        panel.BackgroundColor = Button.Disabled
            ? CrtTerminalPalette.Surface1
            : Button.IsHovered ? HoveredColor : Color;
        panel.BorderColor = BorderColor;
        panel.BorderThickness = new Thickness(1);
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        UpdateColor();
    }
}
