    /// <summary>
    ///     The ghost roles list: faction categories down a rail, and in the pane a banner per role
    ///     with one line under it for every entity offering that role.
    /// </summary>
    [GenerateTypedNameReferences]
    public sealed partial class GhostRolesWindow : DefaultWindow
    {
        [Dependency] private IConfigurationManager _cfg = default!;
        [Dependency] private IEntityManager _entityManager = default!;
        [Dependency] private IStylesheetManager _stylesheetManager = default!;
        [Dependency] private IResourceCache _resourceCache = default!;
        [Dependency] private IPrototypeManager _prototypes = default!;

        private const string OtherCategory = "Other";

        private const int TitleSize = 8;
        private const int RailSize = 9;
        private const int NoteSize = 8;
        private const int MessageSize = 9;

        private const float ScanlineDepth = 0.9f;

        public event Action<GhostRoleInfo>? OnRoleRequestButtonClicked;
        public event Action<GhostRoleInfo>? OnRoleFollow;

        /// <summary>Fired when the ghost presses the call-in button. Runs on each press while enabled.</summary>
        public event Action? OnGhostCallPressed; // CMU14

        private readonly List<EntryState> _entries = new();
        private readonly List<RailEntry> _rail = new();
        private readonly Dictionary<string, int> _categoryCounts = new();

        private string _searchText = string.Empty;

        private string? _selectedCategory;

        private int _availableRoleCount;
        private bool _updatingEntries;
        private Vector2 _entryUpdateScrollValue;

        private readonly CrtScreenControl _shaderPass;
        private readonly Control _cornerTicks;

        public GhostRolesWindow()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            Contents.Margin = new Thickness(0);

            _cornerTicks = CrtLobbyTheme.CornerTicks(HivePalette.Accent.WithAlpha(0.55f));
            Ground.AddChild(_cornerTicks);

            _shaderPass = new CrtScreenControl
            {
                // DefaultWindow's own BoxContainer, so the raster covers the title bar too.
                Source = Children.OfType<BoxContainer>().First(),
                HorizontalExpand = true,
                VerticalExpand = true,
                Phosphor = HivePalette.Accent,
                Intensity = ScanlineDepth,
                Curvature = 0f,
                Grain = false,
                Roll = false,
                ArtifactAmount = 0f,
            };
            AddChild(_shaderPass);

            ApplyTheme();

            SearchBar.OnTextChanged += OnSearchTextChanged;
            GhostCallButton.OnPressed += _ => OnGhostCallPressed?.Invoke(); // CMU14
            _cfg.OnValueChanged(CCVars.CrtUiEnabled, OnCrtUiEnabledChanged);
            _cfg.OnValueChanged(CCVars.CrtUiColor, OnCrtUiColorChanged);
        }


        [Obsolete("Controls should only be removed from UI tree instead of being disposed")]
        protected override void Dispose(bool disposing)
        {
            base.Dispose(disposing);

            _cfg.UnsubValueChanged(CCVars.CrtUiEnabled, OnCrtUiEnabledChanged);
            _cfg.UnsubValueChanged(CCVars.CrtUiColor, OnCrtUiColorChanged);
        }

        private void OnCrtUiEnabledChanged(bool _) => ApplyTheme();

        private void OnCrtUiColorChanged(string _) => ApplyTheme();

        private void ApplyTheme()
        {
            Stylesheet = _stylesheetManager.SheetNano;

            var crt = StyleNano.CrtUiEnabled;
            var header = FindControl<PanelContainer>("WindowHeader");
            var titleLabel = FindControl<Label>("TitleLabel");
            var closeButton = FindControl<TextureButton>("CloseButton");

            if (crt)
                AddStyleClass(StyleNano.StyleClassCrtWindow);
            else
                RemoveStyleClass(StyleNano.StyleClassCrtWindow);

            header.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = HivePalette.Surface2,
                BorderColor = HivePalette.Line,
                BorderThickness = new Thickness(1),
                ContentMarginLeftOverride = 5,
                ContentMarginRightOverride = 6,
            };

            titleLabel.FontOverride = HivePalette.Font(_resourceCache, TitleSize);
            titleLabel.FontColorOverride = HivePalette.Accent;
            closeButton.Modulate = HivePalette.TextDim;

            Ground.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = HivePalette.Surface0,
                BorderColor = HivePalette.Line,
                BorderThickness = new Thickness(1, 0, 1, 1),
            };

            FilterBar.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = HivePalette.Surface1,
                BorderColor = HivePalette.Line,
                BorderThickness = new Thickness(0, 0, 0, 1),
                ContentMarginLeftOverride = 10,
                ContentMarginRightOverride = 10,
                ContentMarginTopOverride = 7,
                ContentMarginBottomOverride = 6,
            };

            RailPanel.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = HivePalette.Surface1,
                BorderColor = HivePalette.Line,
                BorderThickness = new Thickness(0, 0, 1, 0),
            };

            SearchBar.AddStyleClass(StyleNano.StyleClassHiveLineEdit);
            StyleScrollBars(RailScroll);
            StyleScrollBars(RoleScroll);

            CountLabel.FontOverride = HivePalette.Font(_resourceCache, NoteSize);
            CountLabel.FontColorOverride = HivePalette.TextDim;

            NoRolesMessage.FontOverride = HivePalette.Font(_resourceCache, MessageSize);
            NoRolesMessage.FontColorOverride = HivePalette.TextDim;

            foreach (var entry in _entries)
            {
                var accent = AccentOf(entry.Category);
                entry.Banner.ApplyTheme(accent);
                entry.Instances.ApplyTheme(accent);
            }

            foreach (var rail in _rail)
                StyleRailEntry(rail, rail.Id == _selectedCategory);

            _shaderPass.Visible = crt;
            _cornerTicks.Visible = crt;
        }

        private static void StyleScrollBars(Control scroll)
        {
            foreach (var child in scroll.Children)
            {
                if (child is ScrollBar bar && !bar.HasStyleClass(StyleNano.StyleClassHiveScrollBar))
                    bar.AddStyleClass(StyleNano.StyleClassHiveScrollBar);
            }
        }

        public void ClearEntries()
        {
            _availableRoleCount = 0;
            _entries.Clear();
            _categoryCounts.Clear();
            EntryContainer.DisposeAllChildren();

            if (_updatingEntries)
                return;

            RebuildRail();
            UpdateVisibleEntries();
        }

        // CMU14 method
        /// <summary>Shows or hides the ghost call-in row from the menu state, with the gate that still blocks it.</summary>
        public void UpdateGhostCall(GhostThirdPartyCallState? state)
        {
            GhostCallBox.Visible = state != null;
            if (state is not { } call)
                return;

            if (call.Pending)
            {
                GhostCallButton.Visible = true;
                GhostCallButton.Text = Loc.GetString("cmu-ghost-call-pending");
                GhostCallButton.Disabled = true;
                GhostCallStatus.Text = string.Empty;
            }
            else if (call.Available)
            {
                GhostCallButton.Visible = true;
                GhostCallButton.Text = Loc.GetString("cmu-ghost-call-button");
                GhostCallButton.Disabled = false;
                GhostCallStatus.Text = Loc.GetString("cmu-ghost-call-status-available");
            }
            else if (call.MinutesLeft > 0)
            {
                GhostCallButton.Visible = false;
                GhostCallStatus.Text = Loc.GetString("cmu-ghost-call-status-time", ("minutes", call.MinutesLeft));
            }
            else
            {
                GhostCallButton.Visible = true;
                GhostCallButton.Text = Loc.GetString("cmu-ghost-call-button");
                GhostCallButton.Disabled = true;
                GhostCallStatus.Text = call.Dead < call.RequiredDead
                    ? Loc.GetString("cmu-ghost-call-status-dead",
                        ("dead", call.Dead), ("required", call.RequiredDead))
                    : Loc.GetString("cmu-ghost-call-deny-none");
            }
        }

