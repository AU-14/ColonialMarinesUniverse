        /// <summary>
        ///     Adds one role: a banner, and a line for each of the <paramref name="roles"/> entities
        ///     offering it.
        /// </summary>
        public void AddEntry(
            string name,
            string description,
            string? category,
            bool hasAccess,
            FormattedMessage? reason,
            IEnumerable<GhostRoleInfo> roles,
            SpriteSystem spriteSystem)
        {
            var infos = roles.ToList();
            if (infos.Count == 0)
                return;

            _availableRoleCount += infos.Count;

            var categoryId = ResolveCategory(category);
            var accent = AccentOf(categoryId);
            var raffle = infos.Any(role => role.Kind != GhostRoleKind.FirstComeFirstServe);

            var banner = new GhostRoleInfoBox(
                name,
                description,
                infos[0].Entity,
                infos[0].EntityPrototype,
                infos[0].JobPrototype,
                infos.Count,
                raffle,
                accent);

            var instances = new GhostRoleButtonsBox(hasAccess, reason, infos, spriteSystem, accent);
            instances.OnRoleSelected += info => OnRoleRequestButtonClicked?.Invoke(info);
            instances.OnRoleFollow += info => OnRoleFollow?.Invoke(info);

            var entry = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical,
                HorizontalExpand = true,
                SeparationOverride = 0,
                Children = { banner, instances },
            };

            EntryContainer.AddChild(entry);

            // Locations are searchable too - "medbay" is a reasonable thing to type.
            var locations = string.Join(
                " ",
                infos.Select(role => role.Location).Where(location => !string.IsNullOrEmpty(location)));

            var searchText = $"{name} {description} {CategoryName(categoryId)} {locations}";

            _entries.Add(new EntryState(entry, banner, instances, searchText, categoryId));
            _categoryCounts[categoryId] = _categoryCounts.GetValueOrDefault(categoryId) + infos.Count;

            if (_updatingEntries)
                return;

            RebuildRail();
            UpdateVisibleEntries();
        }

        public void BeginEntryUpdate()
        {
            _entryUpdateScrollValue = RoleScroll.GetScrollValue(ignoreVisible: true);
            _updatingEntries = true;
            ClearEntries();
        }

        public void EndEntryUpdate()
        {
            _updatingEntries = false;
            RebuildRail();
            UpdateVisibleEntries();

            RoleScroll.SetScrollValue(_entryUpdateScrollValue);
            RoleScroll.HScrollTarget = _entryUpdateScrollValue.X;
            RoleScroll.VScrollTarget = _entryUpdateScrollValue.Y;
        }

        private void RebuildRail()
        {
            RailList.DisposeAllChildren();
            _rail.Clear();

            // A selection whose category has just emptied out would otherwise leave the pane blank.
            if (_selectedCategory != null && !_categoryCounts.ContainsKey(_selectedCategory))
                _selectedCategory = null;

            AddRailEntry(null, Loc.GetString("cmu-ghost-roles-all-category"), HivePalette.Accent, _availableRoleCount);

            var ordered = _categoryCounts
                .OrderBy(pair => WeightOf(pair.Key))
                .ThenBy(pair => CategoryName(pair.Key));

            foreach (var (id, count) in ordered)
            {
                AddRailEntry(id, CategoryName(id), AccentOf(id), count);
            }

            foreach (var rail in _rail)
                StyleRailEntry(rail, rail.Id == _selectedCategory);
        }

        private void AddRailEntry(string? id, string name, Color accent, int count)
        {
            var box = new StyleBoxFlat
            {
                BackgroundColor = Color.Transparent,
                BorderColor = HivePalette.Rule,
                BorderThickness = new Thickness(0, 0, 0, 1),
                ContentMarginLeftOverride = 0,
                ContentMarginRightOverride = 12,
                ContentMarginTopOverride = 9,
                ContentMarginBottomOverride = 8,
            };

            var marker = new PanelContainer
            {
                MinWidth = 2,
                Visible = false,
                PanelOverride = new StyleBoxFlat { BackgroundColor = accent },
            };

            var pip = new PanelContainer
            {
                MinSize = new Vector2(6, 6),
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(10, 0, 0, 0),
                PanelOverride = new StyleBoxFlat { BackgroundColor = accent },
            };

            var nameLabel = new Label
            {
                Text = name,
                ClipText = true,
                VerticalAlignment = VAlignment.Center,
                HorizontalExpand = true,
                Margin = new Thickness(8, 0, 0, 0),
            };

            var countLabel = new Label
            {
                Text = count.ToString(),
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(10, 0, 0, 0),
            };

            var button = new ContainerButton
            {
                HorizontalExpand = true,
                StyleBoxOverride = box,
                Children =
                {
                    new BoxContainer
                    {
                        Orientation = LayoutOrientation.Horizontal,
                        SeparationOverride = 0,
                        HorizontalExpand = true,
                        Children = { marker, pip, nameLabel, countLabel },
                    },
                },
            };

            var rail = new RailEntry(id, box, marker, nameLabel, countLabel, accent);
            _rail.Add(rail);

            button.OnPressed += _ => SelectCategory(id);
            button.OnMouseEntered += _ =>
            {
                if (!marker.Visible)
                    box.BackgroundColor = HivePalette.Surface2;
            };
            button.OnMouseExited += _ =>
            {
                if (!marker.Visible)
                    box.BackgroundColor = Color.Transparent;
            };

            RailList.AddChild(button);
        }

        private void SelectCategory(string? id)
        {
            _selectedCategory = id;

            foreach (var rail in _rail)
                StyleRailEntry(rail, rail.Id == id);

            UpdateVisibleEntries();
        }

        private void StyleRailEntry(RailEntry rail, bool selected)
        {
            rail.Marker.Visible = selected;
            rail.Box.BackgroundColor = selected ? HivePalette.Surface2 : Color.Transparent;

            rail.Name.FontOverride = HivePalette.Font(_resourceCache, RailSize);
            rail.Name.FontColorOverride = selected ? HivePalette.TextBright : HivePalette.TextDim;

            rail.Count.FontOverride = HivePalette.Font(_resourceCache, NoteSize);
            rail.Count.FontColorOverride = selected ? rail.Accent : HivePalette.TextFaint;
        }

        private void UpdateVisibleEntries()
        {
            CountLabel.Text = Loc.GetString(
                "cmu-ghost-roles-summary",
                ("roles", _availableRoleCount),
                ("categories", _categoryCounts.Count));

            var searching = !string.IsNullOrWhiteSpace(_searchText);
            var anyVisible = false;

            foreach (var entry in _entries)
            {
                var visible = searching
                    ? entry.SearchText.Contains(_searchText, StringComparison.OrdinalIgnoreCase)
                    : _selectedCategory == null || entry.Category == _selectedCategory;

                entry.Control.Visible = visible;
                anyVisible |= visible;
            }

            RoleScroll.Visible = anyVisible;
            NoRolesMessage.Text = _availableRoleCount == 0
                ? Loc.GetString("ghost-roles-window-no-roles-available-label")
                : Loc.GetString("ghost-roles-window-no-results-label");
            NoRolesMessage.Visible = !anyVisible;
        }

        private void OnSearchTextChanged(LineEdit.LineEditEventArgs args)
        {
            _searchText = args.Text.Trim();
            UpdateVisibleEntries();
        }

        private string ResolveCategory(string? category)
        {
            return !string.IsNullOrEmpty(category) && _prototypes.HasIndex<GhostRoleCategoryPrototype>(category)
                ? category
                : OtherCategory;
        }

        private Color AccentOf(string category)
        {
            return HivePalette.Readable(_prototypes.TryIndex<GhostRoleCategoryPrototype>(category, out var proto)
                ? proto.Color
                : HivePalette.Accent);
        }

        private string CategoryName(string category)
        {
            return _prototypes.TryIndex<GhostRoleCategoryPrototype>(category, out var proto)
                ? Loc.GetString(proto.Name)
                : category;
        }

        private int WeightOf(string category)
        {
            return _prototypes.TryIndex<GhostRoleCategoryPrototype>(category, out var proto)
                ? proto.Weight
                : int.MaxValue;
        }

        private readonly record struct EntryState(
            Control Control,
            GhostRoleInfoBox Banner,
            GhostRoleButtonsBox Instances,
            string SearchText,
            string Category);

        /// <summary>One rail entry. <see cref="Id"/> is null for the "all roles" entry.</summary>
        private sealed record RailEntry(
            string? Id,
            StyleBoxFlat Box,
            PanelContainer Marker,
            Label Name,
            Label Count,
            Color Accent);
    }
