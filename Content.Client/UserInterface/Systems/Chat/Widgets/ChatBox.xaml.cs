            if (repopulate)
                RepopulateSecondary();
        }
        else
        {
            SecondaryContents.Clear();
            _secondaryRepeatQueue.Clear();
        }

        UpdateTabButtons();
        SyncSplitControls();

        if (save)
            SaveSplitSettings();
    }

