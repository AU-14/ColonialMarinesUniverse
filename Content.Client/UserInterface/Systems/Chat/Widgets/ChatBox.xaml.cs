    private void OnTabDragStarted(string tabId)
    {
        if (string.Equals(tabId, ChatUserSettings.AllTabId, StringComparison.OrdinalIgnoreCase))
            return;

        _draggingTabId = tabId;
        _dragTargetTabId = null;
        UpdateTabDragVisuals();
    }

    private void OnTabDragEntered(string targetTabId)
    {
        if (_draggingTabId == null)
            return;

        if (string.Equals(_draggingTabId, targetTabId, StringComparison.OrdinalIgnoreCase) ||
            string.Equals(targetTabId, ChatUserSettings.AllTabId, StringComparison.OrdinalIgnoreCase))
        {
            _dragTargetTabId = null;
            UpdateTabDragVisuals();
            return;
        }

        _dragTargetTabId = targetTabId;
        UpdateTabDragVisuals();
    }

    private void OnTabDragExited(string targetTabId)
    {
        if (_draggingTabId == null ||
            !string.Equals(_dragTargetTabId, targetTabId, StringComparison.OrdinalIgnoreCase))
            return;

        _dragTargetTabId = null;
        UpdateTabDragVisuals();
    }

    private void OnTabDragEnded(string tabId)
    {
        var draggingTabId = _draggingTabId;
        if (draggingTabId == null)
            return;

        var targetTabId = _dragTargetTabId;

        _draggingTabId = null;
        _dragTargetTabId = null;

        UpdateTabDragVisuals();

        if (targetTabId != null)
            MoveTabByDrag(draggingTabId, targetTabId);
    }

    private void UpdateTabDragVisuals()
    {
        foreach (var (tabId, button) in _tabButtons)
        {
            var dragging = string.Equals(tabId, _draggingTabId, StringComparison.OrdinalIgnoreCase);
            var dropTarget = string.Equals(tabId, _dragTargetTabId, StringComparison.OrdinalIgnoreCase);
            button.SetDragVisualState(dragging, dropTarget);
        }
    }

    private void OnSplitResizeDragged(GUIMouseMoveEventArgs args)
    {
        if (!_splitChatEnabled)
            return;

        // Measured along whichever axis the panes are split. The secondary pane is the second
        // child, so its share is the distance from the pointer to the far edge either way.
        var extent = _splitHorizontal ? ChatPanes.Width : ChatPanes.Height;
        if (extent <= 0)
            return;

        var farEdge = _splitHorizontal
            ? ChatPanes.GlobalPosition.X + ChatPanes.Width
            : ChatPanes.GlobalPosition.Y + ChatPanes.Height;
        var pointer = _splitHorizontal ? args.GlobalPosition.X : args.GlobalPosition.Y;

        var ratio = (int) Math.Round((farEdge - pointer) / extent * 100f);
        var normalized = ChatUserSettings.NormalizeSplitRatioPercent(ratio);
        if (normalized == _secondaryRatioPercent)
            return;

        _secondaryRatioPercent = normalized;
        ApplySplitRatio();
    }

    private void OnSplitDirectionSelected(bool horizontal)
    {
        if (_splitHorizontal == horizontal)
            return;

        _splitHorizontal = horizontal;
        ApplySplitOrientation();
        ApplySplitRatio();
        SyncSplitControls();
        SaveSplitSettings();

        // Both panes change width, and RichTextLabel caches its line breaks from the last measure,
        // so every row has to be re-laid out or the text keeps the old wrapping.
        RefreshVisibleChatLayout(forceScrollToBottom: true);
    }

    /// <summary>
    ///     Lays the two panes out stacked or side by side. The stretch ratios in
    ///     <see cref="ApplySplitRatio"/> work along either axis, so only the orientation, the drag
    ///     handle's axis and its thickness have to change.
    /// </summary>
    private void ApplySplitOrientation()
    {
        ChatPanes.Orientation = _splitHorizontal
            ? BoxContainer.LayoutOrientation.Horizontal
            : BoxContainer.LayoutOrientation.Vertical;

        // The secondary pane holds the handle and its log, and runs the same way as the split so the
        // handle always lands on the boundary between the two panes.
        SecondaryPane.Orientation = ChatPanes.Orientation;

        SecondaryResizeHandle.Horizontal = _splitHorizontal;
        SecondaryResizeHandle.HorizontalExpand = !_splitHorizontal;
        SecondaryResizeHandle.VerticalExpand = _splitHorizontal;
        SecondaryResizeHandle.MinWidth = _splitHorizontal ? SplitHandleThickness : 0;
        SecondaryResizeHandle.MinHeight = _splitHorizontal ? 0 : SplitHandleThickness;
    }

    private void OnSplitResizeEnded()
    {
        if (_splitChatEnabled)
            SaveSplitSettings();
    }

    private void ApplySplitRatio()
    {
        _secondaryRatioPercent = ChatUserSettings.NormalizeSplitRatioPercent(_secondaryRatioPercent);
        Contents.SizeFlagsStretchRatio = 100 - _secondaryRatioPercent;
        SecondaryPane.SizeFlagsStretchRatio = _secondaryRatioPercent;
    }

