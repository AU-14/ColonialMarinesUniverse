    private FormattedMessage CreateFormattedMessage(ChatMessage message, Color color, ChatStyleSettings? style = null)
    {
        // TrimEnd, because a wrapper that ends in a line break renders as blank rows at the foot of
        // the message - invisible until announcements gained a background. RMC14's WrapHive is the
        // one that does it today.
        var markup = StripChatActionCommandLink(message.WrappedMessage.TrimEnd(), message);
        markup = StripDuplicateChannelPrefix(markup, message);
        markup = _colorWholeMessage
            ? ChatUserSettings.ApplyStyleMarkup(markup, style, ChatUserSettings.DefaultFontSize)
            : ChatUserSettings.ApplyFontMarkup(RemoveOuterColorMarkup(markup), style, ChatUserSettings.DefaultFontSize);

        var formatted = new FormattedMessage(3);
        if (_colorWholeMessage)
            formatted.PushColor(color);

        AddChatMarkup(formatted, markup, message.Channel);

        if (_colorWholeMessage)
            formatted.Pop();

        return FilterProblematicTags(formatted, allowCommandLinks: true);
    }

    private static string StripChatActionCommandLink(string markup, ChatMessage message)
    {
        if (!message.GhostFollowEntity.Valid && !message.XenoWatchEntity.Valid)
        {
            return markup;
        }

        while (markup.StartsWith("[cmdlink=", StringComparison.OrdinalIgnoreCase))
        {
            var tagEnd = markup.IndexOf("/]", StringComparison.Ordinal);
            if (tagEnd < 0)
                return markup;

            var afterTag = tagEnd + 2;
            if (afterTag < markup.Length && markup[afterTag] == ' ')
                afterTag++;

            markup = markup[afterTag..];
        }

        return markup;
    }

    private static string RemoveOuterColorMarkup(string markup)
    {
        if (!markup.StartsWith("[color=", StringComparison.OrdinalIgnoreCase) ||
            !markup.EndsWith("[/color]", StringComparison.OrdinalIgnoreCase))
        {
            return markup;
        }

        var openEnd = markup.IndexOf(']');
        if (openEnd < 0)
            return markup;

        return markup.Substring(openEnd + 1, markup.Length - openEnd - "[/color]".Length - 1);
    }

    private FormattedMessage CreateLegacyFormattedMessage(ChatMessage message, Color color)
    {
        var formatted = new FormattedMessage(3);
        formatted.PushColor(color);

        // RMC14
        if (!string.IsNullOrWhiteSpace(message.LanguageIcon))
            AddChatMarkup(formatted, $"[langicon language=\"{FormattedMessage.EscapeStringParameter(message.LanguageIcon)}\"][/langicon]", message.Channel);
        // RMC14
        AddChatMarkup(formatted, message.WrappedMessage.TrimEnd(), message.Channel);

        formatted.Pop();

        return FilterProblematicTags(formatted, allowCommandLinks: true);
    }

    private void AddChatMarkup(FormattedMessage formatted, string markup, ChatChannel channel)
    {
        if (ChatMarkupParser.AddMarkup(formatted, markup) is not { } error ||
            !_reportedInvalidMarkup.Add(markup))
        {
            return;
        }

        _sawmill.Warning($"Invalid markup in {channel} chat message; using permissive fallback: {error}");
    }

    private static string StripDuplicateChannelPrefix(string markup, ChatMessage message)
    {
        if (!string.IsNullOrWhiteSpace(message.Display?.ChannelLabel))
        {
            var label = message.Display.ChannelLabel.ToUpperInvariant();
            markup = StripVisiblePrefix(markup, $"{label}: ");
            markup = StripVisiblePrefix(markup, $"{label} ");

            if (message.Channel == ChatChannel.Radio)
            {
                markup = StripVisiblePrefix(markup, $@"\[{message.Display.ChannelLabel}\] ");
                markup = StripVisiblePrefix(markup, $"[{message.Display.ChannelLabel}] ");
                markup = StripRadioChannelPrefix(markup);
            }
        }

        switch (message.Channel)
        {
            case ChatChannel.OOC:
                return StripVisiblePrefix(markup, "OOC: ");
            case ChatChannel.LOOC:
                return StripVisiblePrefix(markup, "LOOC: ");
            case ChatChannel.Dead:
                return StripVisiblePrefix(markup, "DEAD: ");
            case ChatChannel.Admin:
            case ChatChannel.AdminAlert:
            case ChatChannel.AdminChat:
                markup = StripVisiblePrefix(markup, "ADMIN: ");
                return StripVisiblePrefix(markup, "ASAY: ");
            case ChatChannel.MentorChat:
                return StripVisiblePrefix(markup, "MENTOR: ");
            default:
                return markup;
        }
    }

    private static string StripRadioChannelPrefix(string markup)
    {
        var index = GetVisibleTextStart(markup);
        if (index < 0 || index + 2 > markup.Length || markup[index] != '\\' || markup[index + 1] != '[')
            return markup;

        var end = markup.IndexOf(@"\] ", index + 2, StringComparison.Ordinal);
        if (end < 0)
            return markup;

        return markup.Remove(index, end + 3 - index);
    }

    private static string StripVisiblePrefix(string markup, string prefix)
    {
        var index = GetVisibleTextStart(markup);
        if (index < 0 || index + prefix.Length > markup.Length)
            return markup;

        if (!markup.Substring(index, prefix.Length).Equals(prefix, StringComparison.OrdinalIgnoreCase))
            return markup;

        return markup.Remove(index, prefix.Length);
    }

    private static int GetVisibleTextStart(string markup)
    {
        var index = 0;
        while (index < markup.Length && markup[index] == '[')
        {
            if (index + 1 < markup.Length && markup[index + 1] == '/')
                break;

            var end = markup.IndexOf(']', index);
            if (end < 0)
                break;

            index = end + 1;
        }

        return index;
    }

    /// <summary>
    ///     Markup tags chat is allowed to render. Anything not listed is dropped by
    ///     <see cref="FilterProblematicTags"/> and its text renders in the control's own font.
    /// </summary>
    /// <remarks>
    ///     <para>
    ///     <c>bold</c> and <c>bolditalic</c> are dropped under CRT, and that is a fix rather than a
    ///     restriction. <c>BoldTag</c> resolves the <b>global</b> <c>DefaultBold</c> font prototype,
    ///     so a bold span ignores the control's font entirely - which meant sender names, which are
    ///     bold, rendered in proportional NotoSans while the message beside them was the mono OSD
    ///     face. At the shared size of 8 the proportional face reads noticeably smaller and thinner,
    ///     which is what made the names hard to read.
    ///     </para>
    ///     <para>
    ///     Dropping the tag here is deliberately narrower than the engine's supported alternative,
    ///     <c>FontTagHijackHolder.Hijack</c>: that intercepts prototype resolution globally and would
    ///     change bold text in the guidebook and everywhere else, to fix a problem that only exists
    ///     in chat. A terminal has no bold anyway.
    ///     </para>
    ///     <para>
    ///     <c>italic</c> has the same flaw (<c>DefaultItalic</c>) and is deliberately left in - it is
    ///     not currently causing a visible problem, and dropping it would take emote formatting with
    ///     it. Revisit if italic text starts looking out of place.
    ///     </para>
    /// </remarks>
    // Takes the flag rather than reading StyleNano.CrtUiEnabled: StylesheetManager subscribes to the
    // same cvar and is what sets that static, and the cvar system does not order subscribers, so
    // reading it from our own handler can see the pre-toggle value.
    private static HashSet<string> BuildMarkupWhitelist(bool crtEnabled)
    {
        var tags = new HashSet<string>
        {
            "mono", "scramble", "bullet", "cmdlink", "color", "font", "head", "italic", "langicon"
        };

        if (!crtEnabled)
        {
            tags.Add("bold");
            tags.Add("bolditalic");
        }

        return tags;
    }

    // RMC14
    private FormattedMessage FilterProblematicTags(FormattedMessage message, bool allowCommandLinks)
    {
        var output = new FormattedMessage(message.Count);
        foreach (var tag in message)
        {
            if (tag.Name == "cmdlink" && !allowCommandLinks)
                continue;

            if (tag.Name is not { } name || _whitelist.Contains(name))
                output.PushTag(tag);
        }
        return output;
    }
