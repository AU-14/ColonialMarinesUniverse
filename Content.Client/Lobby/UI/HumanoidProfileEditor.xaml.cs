        {
            InsurgencyGovernmentJobList.DisposeAllChildren();
            InsurgencyInsurgentJobList.DisposeAllChildren();
            InsurgencyCivilianJobList.DisposeAllChildren();
            ColonyCivilianJobList.DisposeAllChildren();
