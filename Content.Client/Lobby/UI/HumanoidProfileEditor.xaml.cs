        private void ReloadPreview(bool updateDirty = true)
        {
            if (Profile == null)
            {
                SpriteView.ClearPreview();
                UpdatePreviewJobLabel(null);
                return;
            }

            var previewEntry = GetCurrentPreviewJob();
            var previewJob = JobOverride ?? previewEntry?.Job;
            var previewProfile = GetPreviewProfile(Profile);

            SpriteView.ClearPreview();
            var previewDummy = _controller.LoadProfileEntity(previewProfile, previewJob, ShowClothes.Pressed);
            SpriteView.PreviewDummy = previewDummy;
            SpriteView.SetEntity(previewDummy);
            SpriteView.SetName(previewProfile.Name);
            UpdatePreviewJobLabel(previewEntry);

            if (updateDirty)
                SetDirty();
        }

