        private void HandleToggleWalk(BaseButton.ButtonToggledEventArgs args)
        {
            _cfg.SetCVar(CCVars.ToggleWalk, args.Pressed);
            _cfg.SaveToFile();
            InitToggleWalk();

            if (!_keyControls.TryGetValue(EngineKeyFunctions.Walk, out var keyControl))
            {
                return;
            }

            var bindingType = args.Pressed ? KeyBindingType.Toggle : KeyBindingType.State;
            for (var i = 0; i <= 1; i++)
            {
                var binding = (i == 0 ? keyControl.BindButton1 : keyControl.BindButton2).Binding;
                if (binding == null)
                {
                    continue;
                }

                var registration = new KeyBindingRegistration
                {
                    Function = EngineKeyFunctions.Walk,
                    BaseKey = binding.BaseKey,
                    Mod1 = binding.Mod1,
                    Mod2 = binding.Mod2,
                    Mod3 = binding.Mod3,
                    Priority = binding.Priority,
                    Type = bindingType,
                    CanFocus = binding.CanFocus,
                    CanRepeat = binding.CanRepeat,
                };

                _deferCommands.Add(() =>
                {
                    _inputManager.RemoveBinding(binding);
                    _inputManager.RegisterBinding(registration);
                });
            }

            _deferCommands.Add(_inputManager.SaveToUserData);
        }

        // Emotes usable by a bare Human, for the emote-keybind pickers below. Spawns a throwaway
        // nullspace copy of the actual human mob (not the lightweight character-preview dummy,
        // which is missing Hands/Vocal/Speech/etc. and would fail almost every emote whitelist)
        // so the same whitelist/blacklist checks the emotes wheel uses can run without requiring
        // the local player to actually be playing a human right now.
        private List<EmotePrototype> GetHumanAvailableEmotes()
        {
            var result = new List<EmotePrototype>();

            try
            {
                if (!_prototypeManager.HasIndex<EntityPrototype>(HumanMobPrototype))
                    return result;

                var whitelistSystem = _entityManager.System<EntityWhitelistSystem>();
                var dummy = _entityManager.SpawnEntity(HumanMobPrototype, MapCoordinates.Nullspace);

                try
                {
                    _entityManager.TryGetComponent<SpeechComponent>(dummy, out var speech);

                    foreach (var emote in _prototypeManager.EnumeratePrototypes<EmotePrototype>())
                    {
                        if (emote.Category == EmoteCategory.Invalid || emote.ChatTriggers.Count == 0)
                            continue;

                        if (!whitelistSystem.IsWhitelistPassOrNull(emote.Whitelist, dummy))
                            continue;

                        if (whitelistSystem.IsBlacklistPass(emote.Blacklist, dummy))
                            continue;

                        if (!emote.Available && (speech == null || !speech.AllowedEmotes.Contains(emote.ID)))
                            continue;

                        result.Add(emote);
                    }
                }
                finally
                {
                    _entityManager.DeleteEntity(dummy);
                }
            }
            catch (Exception)
            {
                // Never let a failure here (e.g. no active entity context yet) take down the whole options menu.
                return result;
            }

            result.Sort((a, b) => string.Compare(Loc.GetString(a.Name), Loc.GetString(b.Name), StringComparison.Ordinal));
            return result;
        }

