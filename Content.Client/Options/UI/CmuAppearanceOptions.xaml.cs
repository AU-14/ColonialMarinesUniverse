using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client.Options.UI;

[GenerateTypedNameReferences]
public sealed partial class CmuAppearanceOptions : BoxContainer
{
    [Dependency] private IConfigurationManager _cfg = default!;

    public event Action<bool, string>? CrtUiPreviewChanged;

    public CmuAppearanceOptions()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void RegisterOptions(OptionsTabControlRow controller)
    {
        controller.AddOptionDropDown(CCVars.CMUUiFont, UiFontDropDown,
        [
            new OptionDropDownCVar<string>.ValueOption(CCVars.CMUUiFontTheme, Loc.GetString("cmu-ui-font-theme")),
            new OptionDropDownCVar<string>.ValueOption(CCVars.CMUUiFontNotoSans, Loc.GetString("cmu-ui-font-original")),
            new OptionDropDownCVar<string>.ValueOption(CCVars.CMUUiFontComicSans, Loc.GetString("cmu-ui-font-comic-sans")),
            new OptionDropDownCVar<string>.ValueOption(CCVars.CMUUiFontRobotoMono, Loc.GetString("cmu-ui-font-roboto-mono")),
            new OptionDropDownCVar<string>.ValueOption(CCVars.CMUUiFontCozette, Loc.GetString("cmu-ui-font-cozette")),
            new OptionDropDownCVar<string>.ValueOption(CCVars.CMUUiFontNotoSansDisplay, Loc.GetString("cmu-ui-font-noto-display")),
        ]);
        controller.AddOptionCheckBox(CCVars.CMUCrtMenuEffect, CrtMenuEffectCheckBox);
        controller.AddOptionPercentSlider(CCVars.CMUCrtEffectIntensity, CrtIntensitySlider);
        var crtUiEnabled = controller.AddOption(new OptionCrtUiEnabled(controller, _cfg, CrtUiEnabledCheckBox));
        crtUiEnabled.PreviewValueChanged += UpdateCrtUiOptionsPreview;

        var crtUiColor = controller.AddOption(new OptionCrtUiColor(controller, _cfg, CrtUiColorSlider));
        crtUiColor.PreviewValueChanged += UpdateCrtUiOptionsPreview;
        controller.AddOptionCheckBox(CCVars.CMUChatCrtHaze, ChatCrtHazeCheckBox);

        // Not previewed like the two above, and not hidden when CRT is off either - it only does
        // anything under the CRT theme, but it is an accessibility setting and hiding it behind
        // another toggle is how people fail to find it. It applies on Apply like every other
        // checkbox here.
        controller.AddOptionCheckBox(CCVars.CMUChatReadableFont, ChatReadableFontCheckBox);

        // Directly under the readable-font box because the two compose - they are the same setting
        // to a player ("make chat easier to read"), split only because one changes the face and the
        // other the size, and either is useful without the other.
        // Off first here, unlike the tint below: normal size is the default and the list reads as
        // strength ascending from it.
        controller.AddOptionDropDown(
            CCVars.CMUChatBigFont,
            ChatBigFontDropDown,
            [
                new OptionDropDownCVar<string>.ValueOption(
                    CCVars.CMUChatBigFontOff,
                    Loc.GetString("ui-options-crt-chat-big-font-off")),
                new OptionDropDownCVar<string>.ValueOption(
                    CCVars.CMUChatBigFontOne,
                    Loc.GetString("ui-options-crt-chat-big-font-one")),
                new OptionDropDownCVar<string>.ValueOption(
                    CCVars.CMUChatBigFontTwo,
                    Loc.GetString("ui-options-crt-chat-big-font-two")),
            ]);

        controller.AddOptionDropDown(
            CCVars.CMUChatRowTint,
            ChatRowTintDropDown,
            [
                new OptionDropDownCVar<string>.ValueOption(
                    CCVars.CMUChatRowTintFull,
                    Loc.GetString("ui-options-crt-chat-row-tint-full")),
                new OptionDropDownCVar<string>.ValueOption(
                    CCVars.CMUChatRowTintMuted,
                    Loc.GetString("ui-options-crt-chat-row-tint-muted")),
                new OptionDropDownCVar<string>.ValueOption(
                    CCVars.CMUChatRowTintOff,
                    Loc.GetString("ui-options-crt-chat-row-tint-off")),
            ]);

    }

    private void UpdateCrtUiOptionsVisibility()
    {
        CrtUiColorSlider.Visible = CrtUiEnabledCheckBox.Pressed;
    }

    private void UpdateCrtUiOptionsPreview()
    {
        UpdateCrtUiOptionsVisibility();

        CrtUiPreviewChanged?.Invoke(CrtUiEnabledCheckBox.Pressed, CrtUiColorSlider.Picker.Color.ToHex());
    }

    private sealed class OptionCrtUiEnabled : BaseOptionCVar<bool>
    {
        private readonly CheckBox _checkBox;
        private bool _suppressToggle;

        public event Action? PreviewValueChanged;

        protected override bool Value
        {
            get => _checkBox.Pressed;
            set
            {
                _suppressToggle = true;
                try
                {
                    _checkBox.Pressed = value;
                }
                finally
                {
                    _suppressToggle = false;
                }
            }
        }

        public OptionCrtUiEnabled(
            OptionsTabControlRow controller,
            IConfigurationManager cfg,
            CheckBox checkBox)
            : base(controller, cfg, CCVars.CrtUiEnabled)
        {
            _checkBox = checkBox;
            _checkBox.OnToggled += _ =>
            {
                if (_suppressToggle)
                    return;

                ValueChanged();
            };
        }

        public override void LoadValue()
        {
            base.LoadValue();
            NotifyPreviewValueChanged();
        }

        public override void SaveValue()
        {
            base.SaveValue();
            NotifyPreviewValueChanged();
        }

        public override void ResetToDefault()
        {
            base.ResetToDefault();
            NotifyPreviewValueChanged();
        }

        protected override void ValueChanged()
        {
            base.ValueChanged();
            NotifyPreviewValueChanged();
        }

        private void NotifyPreviewValueChanged()
        {
            PreviewValueChanged?.Invoke();
        }
    }

    private sealed class OptionCrtUiColor : BaseOptionCVar<string>
    {
        private readonly OptionColorSlider _slider;
        private bool _suppressColorChanged;

        public event Action? PreviewValueChanged;

        protected override string Value
        {
            get => _slider.Picker.Color.ToHex();
            set
            {
                _suppressColorChanged = true;
                try
                {
                    _slider.Picker.Color = ResolveCrtColor(value);
                }
                finally
                {
                    _suppressColorChanged = false;
                }
            }
        }

        public OptionCrtUiColor(
            OptionsTabControlRow controller,
            IConfigurationManager cfg,
            OptionColorSlider slider)
            : base(controller, cfg, CCVars.CrtUiColor)
        {
            _slider = slider;

            slider.Picker.OnColorChanged += _ =>
            {
                if (_suppressColorChanged)
                    return;

                ValueChanged();
            };
        }

        public override void LoadValue()
        {
            base.LoadValue();
            NotifyPreviewValueChanged();
        }

        public override void SaveValue()
        {
            base.SaveValue();
            NotifyPreviewValueChanged();
        }

        public override void ResetToDefault()
        {
            base.ResetToDefault();
            NotifyPreviewValueChanged();
        }

        protected override void ValueChanged()
        {
            base.ValueChanged();
            NotifyPreviewValueChanged();
        }

        protected override bool IsValueEqual(string a, string b)
        {
            return ResolveCrtColor(a).ToHex() == ResolveCrtColor(b).ToHex();
        }

        private void NotifyPreviewValueChanged()
        {
            PreviewValueChanged?.Invoke();
        }

        private static Color ResolveCrtColor(string value)
        {
            if (Color.TryFromHex(value, out var color))
                return color;

            return value switch
            {
                CCVars.CrtUiColorBlue => Color.FromHex("#58CCFF"),
                CCVars.CrtUiColorOrange => Color.FromHex("#FFB454"),
                CCVars.CrtUiColorRed => Color.FromHex("#FF4E5E"),
                CCVars.CrtUiColorPurple => Color.FromHex("#C45BFF"),
                _ => Color.FromHex(CCVars.CrtUiColorDefault),
            };
        }
    }
}
