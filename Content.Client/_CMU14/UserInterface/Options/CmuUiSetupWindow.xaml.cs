using Content.Client.Lobby.UI;
using Content.Client.Stylesheets;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client._CMU14.UserInterface.Options;

[GenerateTypedNameReferences]
public sealed partial class CmuUiSetupWindow : DefaultWindow
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IStylesheetManager _styles = default!;

    public CmuUiSetupWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        Introduction.SetMessage(Loc.GetString("cmu-ui-setup-introduction"));
        Appearance.RegisterOptions(Settings);
        Settings.Initialize();
        Appearance.CrtUiPreviewChanged += _styles.PreviewCrtUi;
        SaveButton.OnPressed += _ => SaveAndContinue();
        LaterButton.OnPressed += _ => Close();
    }

    public static bool NeedsSetup(IConfigurationManager config)
    {
        if (config.GetCVar(CCVars.CMUUiConfigured))
            return false;

        // Existing installations with custom appearance settings have already made a choice.
        // Muted was the old row-tint default; neither that nor the new full default proves setup.
        return config.GetCVar(CCVars.CrtUiEnabled) == CCVars.CrtUiEnabled.DefaultValue &&
               config.GetCVar(CCVars.CrtUiColor) is CCVars.CrtUiColorDefault or CCVars.CrtUiColorGreen &&
               config.GetCVar(CCVars.CMUUiFont) == CCVars.CMUUiFontTheme &&
               !config.GetCVar(CCVars.CMUChatReadableFont) &&
               config.GetCVar(CCVars.CMUChatBigFont) == CCVars.CMUChatBigFontOff &&
               config.GetCVar(CCVars.CMUChatRowTint) is CCVars.CMUChatRowTintFull or CCVars.CMUChatRowTintMuted &&
               config.GetCVar(CCVars.CMUCrtMenuEffect) &&
               config.GetCVar(CCVars.CMUChatCrtHaze) &&
               config.GetCVar(CCVars.CMUCrtEffectIntensity) == CCVars.CMUCrtEffectIntensity.DefaultValue;
    }

    public void SaveAndContinue()
    {
        _cfg.SetCVar(CCVars.CMUUiConfigured, true);
        Settings.ApplyChanges();
        Close();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _styles.CrtThemeChanged += RefreshTheme;
        RefreshTheme();
    }

    protected override void ExitedTree()
    {
        _styles.CrtThemeChanged -= RefreshTheme;
        _styles.ResetCrtUiPreview();
        base.ExitedTree();
    }

    private void RefreshTheme()
    {
        Stylesheet = _styles.SheetNano;
        CrtLobbyTheme.ApplyWindow(this);
    }
}
